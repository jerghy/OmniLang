//! Flutter codegen: IR -> Flutter Dart components/widgets.
//!
//! Each component generates a `.dart` file with a StatefulWidget + State class.
//! Each store generates a `xxx_store.dart` file with a ChangeNotifier class.
//! Uses `super::dart::dart_type()` for Dart type annotations.

use std::collections::HashMap;

use super::{CodeWriter, Codegen, CompileOutput, CompiledFile};
use crate::ir::*;

pub struct FlutterCodegen;

impl Codegen for FlutterCodegen {
    fn generate(&self, ir: &IRProgram, _source_files: &HashMap<String, String>) -> CompileOutput {
        let mut files = Vec::new();

        for (name, comp) in ir.all_components() {
            let dart = self.gen_component_dart(name, comp, ir);
            files.push(CompiledFile {
                path: format!("{}.dart", name),
                content: dart,
            });
        }

        for (name, store) in ir.all_stores() {
            let store_dart = self.gen_store_dart(name, store);
            files.push(CompiledFile {
                path: format!("{}_store.dart", name),
                content: store_dart,
            });
        }

        CompileOutput::success(files)
    }
}

impl FlutterCodegen {
    /// Generate a complete .dart file for a component as a StatefulWidget.
    fn gen_component_dart(&self, name: &str, comp: &ComponentIR, ir: &IRProgram) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang \u{2014} Flutter target");
        w.emit("");
        w.emit("import 'package:flutter/material.dart';");
        w.emit("");

        // Store imports
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                w.emit(&format!("import './{}_store.dart';", store_ref));
            }
        }
        if !comp.store_refs.is_empty() {
            w.emit("");
        }

        let state_name = format!("_{}State", name);

        // ── StatefulWidget ──
        w.emit(&format!("class {} extends StatefulWidget {{", name));
        w.indent();

        if comp.props.is_empty() {
            w.emit(&format!("const {}({{super.key}});", name));
        } else {
            // Constructor with named parameters for props
            w.emit("const {");
            w.indent();
            w.emit("super.key,");
            for prop_name in comp.props.keys() {
                w.emit(&format!("required this.{},", prop_name));
            }
            w.dedent();
            w.emit("});");

            // Field declarations for props
            w.emit("");
            for (prop_name, prop_type) in &comp.props {
                let ann = super::dart::dart_type(&prop_type.kind, &prop_type.type_args);
                w.emit(&format!("final {} {};", ann, prop_name));
            }
        }

        w.emit("");
        w.emit("@override");
        w.emit(&format!(
            "State<{}> createState() => {}();",
            name, state_name
        ));

        w.dedent();
        w.emit("}");
        w.emit("");

        // ── State class ──
        w.emit(&format!("class {} extends State<{}> {{", state_name, name));
        w.indent();

        // State variables as class fields
        for state in &comp.states {
            let ann = super::dart::dart_type(&state.r#type.kind, &state.r#type.type_args);
            let init = format_expr_ir_flutter(&state.initial_value);
            w.emit(&format!("{} {} = {};", ann, state.name, init));
        }
        if !comp.states.is_empty() {
            w.emit("");
        }

        // Computed properties as getters
        for computed in &comp.computeds {
            let ret_type =
                super::dart::dart_type(&computed.r#type.kind, &computed.r#type.type_args);
            w.emit(&format!("{} get {} {{", ret_type, computed.name));
            w.indent();
            w.emit(&format!(
                "return {};",
                format_expr_ir_flutter(&computed.body)
            ));
            w.dedent();
            w.emit("}");
            w.emit("");
        }

        // initState (for mount lifecycle and effects)
        let has_mount = comp.lifecycles.iter().any(|lc| lc.kind == "mount");
        let has_effects = !comp.effects.is_empty();
        if has_mount || has_effects {
            w.emit("@override");
            w.emit("void initState() {");
            w.indent();
            w.emit("super.initState();");
            for lc in &comp.lifecycles {
                if lc.kind == "mount" {
                    for stmt in &lc.body.statements {
                        generate_statement_flutter(&mut w, stmt);
                    }
                }
            }
            for effect in &comp.effects {
                for stmt in &effect.body.statements {
                    generate_statement_flutter(&mut w, stmt);
                }
            }
            w.dedent();
            w.emit("}");
            w.emit("");
        }

        // dispose (for unmount lifecycle)
        let has_unmount = comp.lifecycles.iter().any(|lc| lc.kind == "unmount");
        if has_unmount {
            w.emit("@override");
            w.emit("void dispose() {");
            w.indent();
            for lc in &comp.lifecycles {
                if lc.kind == "unmount" {
                    for stmt in &lc.body.statements {
                        generate_statement_flutter(&mut w, stmt);
                    }
                }
            }
            w.emit("super.dispose();");
            w.dedent();
            w.emit("}");
            w.emit("");
        }

        // Functions as methods on State
        for func in &comp.fns {
            generate_function_flutter(&mut w, func);
            w.emit("");
        }

        // Build method
        w.emit("@override");
        w.emit("Widget build(BuildContext context) {");
        w.indent();

        if let Some(view) = &comp.view {
            let tree_expr = format_view_tree(view);
            w.emit(&format!("return {};", tree_expr));
        } else {
            // Default widget tree
            w.emit("return Container(");
            w.indent();
            w.emit(&format!("child: Text('{}'),", name));
            w.dedent();
            w.emit(");");
        }

        w.dedent();
        w.emit("}");

        w.dedent();
        w.emit("}");

        w.into_string()
    }

    /// Generate a store .dart file as a ChangeNotifier class.
    fn gen_store_dart(&self, name: &str, store: &StoreIR) -> String {
        let mut w = CodeWriter::new();
        w.emit(&format!(
            "// Generated by OmniLang \u{2014} Store: {}",
            name
        ));
        w.emit("");

        if store.signals.is_empty() && store.getters.is_empty() {
            w.emit("import 'package:flutter/material.dart';");
            w.emit("");
            w.emit(&format!("class {} {{", name));
            w.indent();
            w.emit(&format!("{}();", name));
            w.dedent();
            w.emit("}");
            return w.into_string();
        }

        w.emit("import 'package:flutter/material.dart';");
        w.emit("");

        // ChangeNotifier class
        w.emit(&format!("class {} extends ChangeNotifier {{", name));
        w.indent();

        // Fields (signals)
        for (sig_name, sig_type) in &store.signals {
            let ann = super::dart::dart_type(&sig_type.kind, &sig_type.type_args);
            let default_val = store
                .signal_defaults
                .get(sig_name)
                .map(format_json_value_flutter)
                .unwrap_or_else(|| "null".into());
            w.emit(&format!("{} {} = {};", ann, sig_name, default_val));
        }

        // Constructor
        w.emit("");
        w.emit(&format!("{}() {{", name));
        w.indent();
        for sig_name in store.signals.keys() {
            let default_val = store
                .signal_defaults
                .get(sig_name)
                .map(format_json_value_flutter)
                .unwrap_or_else(|| "null".into());
            w.emit(&format!("this.{} = {};", sig_name, default_val));
        }
        w.dedent();
        w.emit("}");

        // Getters
        for (getter_name, getter_expr) in &store.getters {
            w.emit("");
            w.emit(&format!("get {} {{", getter_name));
            w.indent();
            w.emit(&format!("return {};", format_expr_ir_flutter(getter_expr)));
            w.dedent();
            w.emit("}");
        }

        // Setter methods with notifyListeners for each signal
        for (sig_name, sig_type) in &store.signals {
            w.emit("");
            let setter_name = format!("set{}", capitalize_first(sig_name));
            let ann = super::dart::dart_type(&sig_type.kind, &sig_type.type_args);
            w.emit(&format!("void {}({} value) {{", setter_name, ann));
            w.indent();
            w.emit(&format!("this.{} = value;", sig_name));
            w.emit("notifyListeners();");
            w.dedent();
            w.emit("}");
        }

        w.dedent();
        w.emit("}");
        w.into_string()
    }
}

// ═══════════════════════════════════════════════════════════════
// View tree formatting (single-line Flutter widget expressions)
// ═══════════════════════════════════════════════════════════════

/// Render a ViewTree as a single-line Flutter widget expression string.
fn format_view_tree(node: &ViewTree) -> String {
    match node {
        ViewTree::Element(el) => format_element(el),
        ViewTree::Text(text) => {
            if text.starts_with('{') && text.ends_with('}') {
                // OmniView interpolation: {name} -> Text('$name')
                let inner = &text[1..text.len() - 1];
                if inner.chars().all(|c| c.is_alphanumeric() || c == '_') {
                    format!("Text('${}')", inner)
                } else {
                    format!("Text('${{{}}}')", inner)
                }
            } else {
                format!("Text('{}')", text.replace('\'', "\\'"))
            }
        }
        ViewTree::Interpolation(_expr) => "Text('')".to_string(),
        ViewTree::Conditional(cond) => format_conditional(cond),
        ViewTree::ListRendering(list) => format_list_rendering(list),
        ViewTree::Slot(_) => "SizedBox.shrink()".to_string(),
    }
}

/// Format an ElementIR node as a Flutter widget constructor expression.
fn format_element(el: &ElementIR) -> String {
    let widget = tag_to_flutter_widget(&el.tag);
    let mut args: Vec<String> = Vec::new();

    // Props -> widget constructor parameters
    for (name, value) in &el.props {
        let formatted = format_expr_ir_flutter(value);
        match name.as_str() {
            "style" => {
                // Style is handled via inline props on the widget;
                // For now, skip complex CSS-style parsing
            }
            other => {
                let param = prop_to_flutter_param_name(other);
                if !param.is_empty() {
                    args.push(format!("{}: {}", param, formatted));
                }
            }
        }
    }

    // Events -> callback parameters
    for (name, handler) in &el.events {
        let callback_name = event_to_flutter_callback(name);
        let body = match handler.kind.as_str() {
            "fn_ref" => {
                if let Some(ref fn_name) = handler.r#ref {
                    format!("() {{ {}(); }}", fn_name)
                } else {
                    "() {}".to_string()
                }
            }
            "inline_fn" => {
                if let Some(ref body) = handler.body {
                    format_inline_handler_flutter(body)
                } else {
                    "() {}".to_string()
                }
            }
            "store_action" => {
                if let Some(ref action) = handler.r#ref {
                    format!("() {{ /* TODO: action {} */ }}", action)
                } else {
                    "() {}".to_string()
                }
            }
            other => format!("() {{ /* TODO: kind '{}' */ }}", other),
        };
        args.push(format!("{}: {}", callback_name, body));
    }

    // Bindings
    for (bind_name, signal_ref) in &el.bindings {
        let param = binding_to_flutter_param(bind_name);
        if !param.is_empty() {
            args.push(format!("{}: {}", param, signal_ref.name));
        }
    }

    // Children
    if el.children.is_empty() {
        // No children
    } else if el.children.len() == 1 {
        let child_str = format_view_tree(&el.children[0]);
        args.push(format!("child: {}", child_str));
    } else {
        let children: Vec<String> = el.children.iter().map(format_view_tree).collect();
        args.push(format!("children: [{}]", children.join(", ")));
    }

    if args.is_empty() {
        format!("{}()", widget)
    } else {
        format!("{}({})", widget, args.join(", "))
    }
}

/// Format a ConditionalIntent as a Dart ternary expression.
fn format_conditional(cond: &ConditionalIntent) -> String {
    if cond.branches.is_empty() {
        if let Some(ref fb) = cond.fallback {
            return format_view_tree(fb);
        }
        return "SizedBox()".to_string();
    }

    let mut result = String::new();
    for (i, branch) in cond.branches.iter().enumerate() {
        let cond_str = format_expr_ir_flutter(&branch.condition);
        let body_str = branch
            .body
            .as_ref()
            .map(format_view_tree)
            .unwrap_or_else(|| "SizedBox()".to_string());
        if i == 0 {
            result.push_str(&format!("{} ? {}", cond_str, body_str));
        } else {
            result.push_str(&format!(" : {} ? {}", cond_str, body_str));
        }
    }

    // Fallback
    if let Some(ref fb) = cond.fallback {
        result.push_str(&format!(" : {}", format_view_tree(fb)));
    } else {
        result.push_str(" : SizedBox()");
    }

    result
}

/// Format a ListRenderingIntent as a .map().toList() expression.
fn format_list_rendering(list: &ListRenderingIntent) -> String {
    let iterable_str = format_expr_ir_flutter(&list.iterable);
    let item_name = &list.item_binding.name;
    let body_str = list
        .body
        .as_ref()
        .map(format_view_tree)
        .unwrap_or_else(|| "SizedBox()".to_string());

    format!(
        "{}.map<Widget>(({}) => {}).toList()",
        iterable_str, item_name, body_str
    )
}

