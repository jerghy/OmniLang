/// Build an inline callback string from a BlockIR for Flutter event handlers.
fn format_inline_handler_flutter(body: &BlockIR) -> String {
    if body.statements.is_empty() {
        return "() {}".to_string();
    }
    let mut hw = CodeWriter::new();
    hw.emit("() {");
    hw.indent();
    for stmt in &body.statements {
        generate_statement_flutter(&mut hw, stmt);
    }
    hw.dedent();
    hw.emit("}");
    hw.into_string().trim().to_string()
}

// ═══════════════════════════════════════════════════════════════
// Statement generation (Flutter/Dart)
// ═══════════════════════════════════════════════════════════════

fn generate_statement_flutter(w: &mut CodeWriter, stmt: &StatementIR) {
    match stmt {
        StatementIR::LetStmtIR {
            name,
            value,
            r#type,
        } => {
            let rhs = value
                .as_ref()
                .map(format_expr_ir_flutter)
                .unwrap_or_else(|| "null".into());
            if let Some(ref ty) = r#type {
                let ann = super::dart::dart_type(&ty.kind, &ty.type_args);
                w.emit(&format!("{} {} = {};", ann, name, rhs));
            } else {
                w.emit(&format!("var {} = {};", name, rhs));
            }
        }
        StatementIR::IfStmtIR {
            condition,
            then_body,
            else_body,
        } => {
            let cond = format_expr_ir_flutter(condition);
            w.emit(&format!("if ({}) {{", cond));
            w.indent();
            for s in &then_body.statements {
                generate_statement_flutter(w, s);
            }
            w.dedent();
            if let Some(else_blk) = else_body {
                if !else_blk.statements.is_empty() {
                    w.emit("} else {");
                    w.indent();
                    for s in &else_blk.statements {
                        generate_statement_flutter(w, s);
                    }
                    w.dedent();
                }
            }
            w.emit("}");
        }
        StatementIR::ReturnStmtIR { value } => {
            let rhs = value
                .as_ref()
                .map(format_expr_ir_flutter)
                .unwrap_or_else(|| "null".into());
            w.emit(&format!("return {};", rhs));
        }
        StatementIR::MutationStmt { intent: None } => {}
        StatementIR::MutationStmt {
            intent: Some(mut_intent),
        } => {
            let target = &mut_intent.target.name;
            let amount = mut_intent
                .amount
                .as_ref()
                .map(format_expr_ir_flutter)
                .unwrap_or_else(|| "0".into());
            w.emit("setState(() {");
            w.indent();
            match mut_intent.operation.as_str() {
                "direct_assign" => {
                    w.emit(&format!("{} = {};", target, amount));
                }
                "increment" => {
                    w.emit(&format!("{} += {};", target, amount));
                }
                "decrement" => {
                    w.emit(&format!("{} -= {};", target, amount));
                }
                "multiply" => {
                    w.emit(&format!("{} *= {};", target, amount));
                }
                "divide" => {
                    w.emit(&format!("{} /= {};", target, amount));
                }
                "modulo" => {
                    w.emit(&format!("{} %= {};", target, amount));
                }
                other => {
                    w.emit(&format!(
                        "// TODO: mutation operation '{}' on '{}'",
                        other, target
                    ));
                }
            }
            w.dedent();
            w.emit("});");
        }
        StatementIR::ExprStmtIR { expr } => {
            let line = format_expr_ir_flutter(expr);
            if line != "null" {
                w.emit(&format!("{};", line));
            }
        }
        StatementIR::EventEmitStmtIR { event_name, args } => {
            let arg_str = if args.is_empty() {
                String::new()
            } else {
                let formatted: Vec<String> = args.iter().map(format_expr_ir_flutter).collect();
                format!("({})", formatted.join(", "))
            };
            w.emit(&format!("// emit event: {}{}", event_name, arg_str));
        }
        StatementIR::WhileStmtIR { condition, body } => {
            let cond = format_expr_ir_flutter(condition);
            w.emit(&format!("while ({}) {{", cond));
            w.indent();
            for s in &body.statements {
                generate_statement_flutter(w, s);
            }
            w.dedent();
            w.emit("}");
        }
        StatementIR::ForInStmtIR {
            var_name,
            iterable,
            body,
        } => {
            let iter = format_expr_ir_flutter(iterable);
            w.emit(&format!("for (var {} in {}) {{", var_name, iter));
            w.indent();
            for s in &body.statements {
                generate_statement_flutter(w, s);
            }
            w.dedent();
            w.emit("}");
        }
        StatementIR::BreakStmtIR => {
            w.emit("break;");
        }
        StatementIR::ContinueStmtIR => {
            w.emit("continue;");
        }
        _ => {}
    }
}

/// Generate a function as a method on the State class.
fn generate_function_flutter(w: &mut CodeWriter, func: &FunctionIR) {
    // Build parameter list — Dart uses `Type name` for positional params
    let mut param_strs = Vec::new();
    for p in &func.params {
        let mut s = String::new();
        if let Some(ref ty) = p.r#type {
            let ann = super::dart::dart_type(&ty.kind, &ty.type_args);
            s.push_str(&format!("{} ", ann));
        }
        s.push_str(&p.name);
        param_strs.push(s);
    }

    // Determine return type
    // Wrap in Future<T> for async functions
    let return_prefix = if func.is_async {
        match func.return_type {
            Some(ref rt) if rt.kind != "void" && rt.kind != "()" => {
                format!(
                    "Future<{}> ",
                    super::dart::dart_type(&rt.kind, &rt.type_args)
                )
            }
            _ => "Future<void> ".to_string(),
        }
    } else {
        func.return_type
            .as_ref()
            .filter(|rt| rt.kind != "void" && rt.kind != "()")
            .map(|rt| format!("{} ", super::dart::dart_type(&rt.kind, &rt.type_args)))
            .unwrap_or_default()
    };

    let async_kw = if func.is_async { "async " } else { "" };
    let all_params = param_strs.join(", ");
    w.emit(&format!(
        "{}{}({}) {}{{",
        return_prefix, func.name, all_params, async_kw
    ));
    w.indent();

    for stmt in &func.body.statements {
        generate_statement_flutter(w, stmt);
    }

    w.dedent();
    w.emit("}");
}

// ═══════════════════════════════════════════════════════════════
// Expression formatting
// ═══════════════════════════════════════════════════════════════

fn format_expr_ir_flutter(expr: &ExprIR) -> String {
    match expr {
        ExprIR::LiteralExpr { value } => format_json_value_flutter(value),
        ExprIR::IdentifierExpr { name } => name.clone(),
        ExprIR::FieldAccessExpr { object, field } => {
            format!("{}.{}", format_expr_ir_flutter(object), field)
        }
        ExprIR::BinaryOpExpr { op, left, right } => {
            let dart_op = binary_op_to_flutter(op);
            let lhs = format_expr_ir_flutter(left);
            let rhs = format_expr_ir_flutter(right);
            format!("{} {} {}", lhs, dart_op, rhs)
        }
        ExprIR::UnaryOpExpr { op, operand } => {
            let dart_op = match op.as_str() {
                "not" => "!",
                "neg" => "-",
                _ => op,
            };
            format!("{}{}", dart_op, format_expr_ir_flutter(operand))
        }
        ExprIR::TernaryIR {
            cond,
            then_expr,
            else_expr,
        } => {
            let c = format_expr_ir_flutter(cond);
            let t = format_expr_ir_flutter(then_expr);
            let e = format_expr_ir_flutter(else_expr);
            format!("{} ? {} : {}", c, t, e)
        }
        ExprIR::CallExpr { name, args } => {
            let arg_strs: Vec<String> = args.iter().map(format_expr_ir_flutter).collect();
            format!("{}({})", name, arg_strs.join(", "))
        }
        ExprIR::StoreFieldAccessExpr {
            store_alias,
            field_name,
            call_args,
        } => {
            let args: Vec<String> = call_args.iter().map(format_expr_ir_flutter).collect();
            let arg_str = if args.is_empty() {
                String::new()
            } else {
                format!("({})", args.join(", "))
            };
            format!("{}.{}{}", store_alias, field_name, arg_str)
        }
        ExprIR::ArrayExpr { elements } => {
            let items: Vec<String> = elements.iter().map(format_expr_ir_flutter).collect();
            format!("[{}]", items.join(", "))
        }
        ExprIR::StructExpr { fields, .. } => {
            let entries: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("\"{}\": {}", k, format_expr_ir_flutter(v)))
                .collect();
            format!("{{{}}}", entries.join(", "))
        }
        ExprIR::VariantLiteral {
            union_type,
            variant,
            fields,
        } => {
            let entries: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("{}: {}", k, format_expr_ir_flutter(v)))
                .collect();
            format!("{}.{}({})", union_type, variant, entries.join(", "))
        }
        ExprIR::MethodCallExpr {
            object,
            method,
            args,
            ..
        } => {
            let obj = format_expr_ir_flutter(object);
            let arg_strs: Vec<String> = args.iter().map(|a| format_expr_ir_flutter(a)).collect();
            format!("{}.{}({})", obj, method, arg_strs.join(", "))
        }
        ExprIR::BlockExpr { tail, .. } => format_expr_ir_flutter(tail),
        ExprIR::IndexExpr { object, index } => {
            let obj = format_expr_ir_flutter(object);
            let idx = format_expr_ir_flutter(index);
            format!("({obj})[{idx}]")
        }
        ExprIR::AwaitExpr { operand } => {
            format!("await {}", format_expr_ir_flutter(operand))
        }
                ExprIR::MatchExpr { .. } => "null".into(),
        ExprIR::ClosureExpr { params, body } => {
            let b = format_expr_ir_flutter(body);
            if params.is_empty() {
                format!("(() => {b})")
            } else {
                let p = params.join(", ");
                format!("(({p}) => {b})")
            }
        }
    }
}

/// Format a JSON value as a Dart literal (shared with Flutter).
fn format_json_value_flutter(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::Null => "null".into(),
        serde_json::Value::Bool(b) => {
            if *b {
                "true".into()
            } else {
                "false".into()
            }
        }
        serde_json::Value::Number(n) => n.to_string(),
        serde_json::Value::String(s) => {
            let escaped = s
                .replace('\\', "\\\\")
                .replace('\'', "\\'")
                .replace('\n', "\\n")
                .replace('\r', "\\r")
                .replace('\t', "\\t");
            format!("'{}'", escaped)
        }
        other => other.to_string(),
    }
}

/// Map OMNI binary operator name to Dart/Flutter operator.
