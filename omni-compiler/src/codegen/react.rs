//! React codegen: IR -> React TSX components + CSS modules + store hooks.
//!
//! Each component generates a `.tsx` React functional component with hooks
//! and a `.module.css` CSS module file. Each store generates a `useXxx.ts`
//! custom hook file.

use std::collections::HashMap;

use crate::ir::*;
use super::{CodeWriter, Codegen, CompileOutput, CompiledFile};

pub struct ReactCodegen;

impl Codegen for ReactCodegen {
    fn generate(&self, ir: &IRProgram, _source_files: &HashMap<String, String>) -> CompileOutput {
        let mut files = Vec::new();

        for (name, comp) in ir.all_components() {
            // .tsx
            let tsx = self.gen_component_tsx(name, comp, ir);
            files.push(CompiledFile {
                path: format!("{}.tsx", name),
                content: tsx,
            });

            // .module.css
            let css = self.gen_component_css(name, comp);
            files.push(CompiledFile {
                path: format!("{}.module.css", name),
                content: css,
            });
        }

        for (name, store) in ir.all_stores() {
            let hook = self.gen_store_hook(name, store);
            files.push(CompiledFile {
                path: format!("use{}.ts", name),
                content: hook,
            });
        }

        CompileOutput::success(files)
    }
}

impl ReactCodegen {
    /// Generate a React functional component .tsx file.
    fn gen_component_tsx(&self, name: &str, comp: &ComponentIR, ir: &IRProgram) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang — React target");
        w.emit("");

        // Imports
        w.emit("import React, { useState, useEffect, useMemo } from 'react';");
        w.emit(&format!("import styles from './{}.module.css';", name));
        w.emit("");

        // Props interface
        if !comp.props.is_empty() {
            w.emit(&format!("interface {}Props {{", name));
            for (prop_name, prop_type) in &comp.props {
                let ts_type = super::javascript::js_type(&prop_type.kind, &prop_type.type_args, true);
                w.emit(&format!("  {}: {};", prop_name, ts_type));
            }
            w.emit("}");
            w.emit("");
        }

        // Store hook imports
        let mut store_hook_imports = Vec::new();
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                store_hook_imports.push(format!(
                    "import {{ {} }} from './use{}';",
                    hook_name, store_ref
                ));
            }
        }
        for import_line in &store_hook_imports {
            w.emit(import_line);
        }
        if !store_hook_imports.is_empty() {
            w.emit("");
        }

        // Component function signature
        if comp.props.is_empty() {
            w.emit(&format!("export function {}() {{", name));
        } else {
            let prop_list: Vec<&str> = comp.props.keys().map(|s| s.as_str()).collect();
            w.emit(&format!(
                "export function {}({{ {} }}: {}Props) {{",
                name,
                prop_list.join(", "),
                name
            ));
        }
        w.indent();

        // Store hooks
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                w.emit(&format!("const {} = {}();", store_ref, hook_name));
            }
        }

        // State hooks (useState)
        for state in &comp.states {
            let init_val = format_expr_ir_tsx(&state.initial_value);
            let setter = format!("set{}", capitalize_first(&state.name));
            w.emit(&format!("const [{}, {}] = useState({});", state.name, setter, init_val));
        }

        // Effects (useEffect)
        for effect in &comp.effects {
            let deps: Vec<&str> = effect.deps.iter().map(|d| d.as_str()).collect();
            w.emit("useEffect(() => {");
            w.indent();
            for stmt in &effect.body.statements {
                generate_statement_tsx(&mut w, stmt);
            }
            w.dedent();
            w.emit(&format!("}}, [{}]);", deps.join(", ")));
        }

        // Lifecycles (mount/unmount)
        for lc in &comp.lifecycles {
            match lc.kind.as_str() {
                "mount" => {
                    w.emit("useEffect(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_tsx(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("}, []);");
                }
                "unmount" => {
                    w.emit("useEffect(() => {");
                    w.indent();
                    w.emit("return () => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_tsx(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("};");
                    w.dedent();
                    w.emit("}, []);");
                }
                _ => {
                    w.emit(&format!("// TODO: lifecycle '{}'", lc.kind));
                }
            }
        }

        // Computed values (useMemo)
        for computed in &comp.computeds {
            let deps: Vec<&str> = computed.deps.iter().map(|d| d.as_str()).collect();
            w.emit(&format!("const {} = useMemo(() => {{", computed.name));
            w.indent();
            w.emit(&format!("return {};", format_expr_ir_tsx(&computed.body)));
            w.dedent();
            w.emit(&format!("}}, [{}]);", deps.join(", ")));
        }

        w.emit("");

        // Render return (JSX view tree)
        w.emit("return (");
        w.indent();
        if let Some(view) = &comp.view {
            gen_view_node_tsx(&mut w, view);
        } else {
            w.emit(&format!("<div className={{styles.container}}>"));
            w.indent();
            w.emit(&format!("<h1>{{'{0}'}}</h1>", name));
            w.dedent();
            w.emit("</div>");
        }
        w.dedent();
        w.emit(");");
        w.dedent();
        w.emit("}");
        w.emit("");

        w.into_string()
    }

    /// Generate a CSS module file from component styles.
    fn gen_component_css(&self, name: &str, comp: &ComponentIR) -> String {
        let mut w = CodeWriter::new();
        w.emit(&format!("/* Styles for {} */", name));
        if comp.styles.is_empty() {
            w.emit(".container {");
            w.indent();
            w.emit("display: flex;");
            w.emit("flex-direction: column;");
            w.emit("padding: 16px;");
            w.dedent();
            w.emit("}");
        } else {
            for style in &comp.styles {
                w.emit(&format!(".{} {{", style.class_name));
                for (prop, value) in &style.properties {
                    let css_val = format_css_value(value);
                    w.emit(&format!("  {}: {};", to_css_prop(prop), css_val));
                }
                w.emit("}");
            }
        }
        w.into_string()
    }

    /// Generate a custom store hook (useStoreName.ts).
    fn gen_store_hook(&self, name: &str, store: &StoreIR) -> String {
        let mut w = CodeWriter::new();
        w.emit(&format!("// Generated by OmniLang — Store hook: use{}", name));
        w.emit("import { useState, useCallback } from 'react';");
        w.emit("");

        w.emit(&format!("export function use{}() {{", name));
        w.indent();

        // Signals as state variables
        for (sig_name, sig_type) in &store.signals {
            let init = store
                .signal_defaults
                .get(sig_name)
                .map(format_json_value_tsx)
                .unwrap_or_else(|| "null".into());
            let setter = format!("set{}", capitalize_first(sig_name));
            let ts_type =
                super::javascript::js_type(&sig_type.kind, &sig_type.type_args, true);
            w.emit(&format!(
                "const [{}, {}] = useState<{}>({});",
                sig_name, setter, ts_type, init
            ));
        }

        // Getters as memoized values
        for (getter_name, getter_expr) in &store.getters {
            w.emit(&format!(
                "const {} = useCallback(() => {{ return {}; }}, []);",
                getter_name,
                format_expr_ir_tsx(getter_expr)
            ));
        }

        // Return value
        let mut return_keys: Vec<String> = Vec::new();
        for (sig_name, _) in &store.signals {
            return_keys.push(sig_name.clone());
        }
        for (getter_name, _) in &store.getters {
            return_keys.push(getter_name.clone());
        }
        w.emit(&format!("return {{ {} }};", return_keys.join(", ")));

        w.dedent();
        w.emit("}");
        w.into_string()
    }
}

// ═══════════════════════════════════════════════════════════
// View tree generation (JSX)
// ═══════════════════════════════════════════════════════════

fn gen_view_node_tsx(w: &mut CodeWriter, node: &ViewTree) {
    match node {
        ViewTree::Element(el) => {
            // Build attribute list from props, bindings, events
            let mut attrs: Vec<String> = Vec::new();

            // Static props
            for (prop_name, prop_value) in &el.props {
                let jsx_attr = to_jsx_attr(prop_name);
                match prop_value {
                    ExprIR::LiteralExpr { value } if value.is_string() => {
                        attrs.push(format!(
                            "{}=\"{}\"",
                            jsx_attr,
                            value.as_str().unwrap()
                        ));
                    }
                    _ => {
                        let jsx_val = format_expr_ir_tsx(prop_value);
                        attrs.push(format!("{}={{{}}}", jsx_attr, jsx_val));
                    }
                }
            }

            // Signal bindings
            for (bind_name, signal_ref) in &el.bindings {
                let jsx_attr = to_jsx_attr(bind_name);
                attrs.push(format!("{}={{{}}}", jsx_attr, signal_ref.name));
            }

            // Events
            for (event_name, handler) in &el.events {
                let react_event = to_react_event(event_name);
                match handler.kind.as_str() {
                    "fn_ref" => {
                        if let Some(ref fn_name) = handler.r#ref {
                            attrs.push(format!("{}={{{}}}", react_event, fn_name));
                        }
                    }
                    "inline_fn" => {
                        if let Some(ref body) = handler.body {
                            let handler_str = format_inline_handler(body);
                            attrs.push(format!("{}={{{}}}", react_event, handler_str));
                        }
                    }
                    "store_action" => {
                        if let Some(ref action) = handler.r#ref {
                            attrs.push(format!(
                                "{}={{() => {{ /* TODO: action {} */ }}}}",
                                react_event, action
                            ));
                        }
                    }
                    _ => {
                        attrs.push(format!(
                            "{}={{/* TODO: handler kind '{}' */}}",
                            react_event,
                            handler.kind
                        ));
                    }
                }
            }

            // Style classes from view
            if let Some(ref classes) = el.style_classes {
                if let Some(classes_str) = classes.as_str() {
                    attrs.push(format!("className={{styles['{}']}}", classes_str));
                }
            }

            // Inline style
            if el.inline_style.is_some() {
                attrs.push("style={{ /* TODO: inline style */ }}".into());
            }

            // Emit opening tag
            if attrs.is_empty() && el.children.is_empty() {
                // Self-closing tag
                w.emit(&format!("<{} />", el.tag));
                return;
            }

            if attrs.is_empty() {
                w.emit(&format!("<{}>", el.tag));
            } else {
                w.emit(&format!("<{}", el.tag));
                w.indent();
                for attr in &attrs {
                    w.emit(&format!("{}", attr));
                }
                if el.children.is_empty() {
                    w.dedent();
                    w.emit("/>");
                    return;
                }
                w.dedent();
                w.emit(">");
            }

            // Children
            w.indent();
            for child in &el.children {
                gen_view_node_tsx(w, child);
            }
            w.dedent();

            // Closing tag
            w.emit(&format!("</{}>", el.tag));
        }
        ViewTree::Conditional(cond) => {
            let branches = &cond.branches;
            let fallback = &cond.fallback;

            if branches.is_empty() {
                if let Some(ref fb) = fallback {
                    gen_view_node_tsx(w, fb);
                }
                return;
            }

            // Single branch without fallback → {condition && (...)}
            if branches.len() == 1 && fallback.is_none() {
                w.emit("{");
                w.indent();
                let cond_str = format_expr_ir_tsx(&branches[0].condition);
                w.emit(&format!("{} && (", cond_str));
                w.indent();
                if let Some(ref body) = branches[0].body {
                    gen_view_node_tsx(w, body);
                }
                w.dedent();
                w.emit(")");
                w.dedent();
                w.emit("}");
                return;
            }

            // Multiple branches or fallback → nested ternary
            w.emit("{");
            w.indent();
            for (i, branch) in branches.iter().enumerate() {
                if i > 0 {
                    w.emit(": (");
                    w.indent();
                }
                let cond_str = format_expr_ir_tsx(&branch.condition);
                w.emit(&format!("{} ? (", cond_str));
                w.indent();
                if let Some(ref body) = branch.body {
                    gen_view_node_tsx(w, body);
                }
                w.dedent();
            }
            // Fallback or null
            if let Some(ref fb) = fallback {
                w.emit(") : (");
                w.indent();
                gen_view_node_tsx(w, fb);
                w.dedent();
                w.emit(")");
                // Close all open parenthesis from chained ternary
                for _ in 0..branches.len() {
                    w.emit(")");
                }
                w.dedent();
                w.emit("}");
                return;
            } else {
                w.emit(") : null");
                // Close all open parenthesis
                for _ in 1..branches.len() {
                    w.emit(")");
                }
                // Close the open indent for branch 0
                w.dedent();
                w.emit("}");
                return;
            }
        }
        ViewTree::ListRendering(list) => {
            let iterable_str = format_expr_ir_tsx(&list.iterable);
            let item_name = &list.item_binding.name;
            w.emit("{");
            w.indent();
            w.emit(&format!("{}.map(({}, index) => (", iterable_str, item_name));
            w.indent();
            if let Some(ref body) = list.body {
                gen_view_node_tsx(w, body);
            }
            w.dedent();
            w.emit("))");
            w.dedent();
            w.emit("}");
        }
        ViewTree::Text(text) => {
            if text.starts_with('{') && text.ends_with('}') {
                // Interpolation expression like {name} or {param:xxx}
                let inner = &text[1..text.len() - 1];
                w.emit(&format!("{{{}}}", inner));
            } else {
                // Plain text
                let escaped = text.replace('\'', "\\'");
                w.emit(&format!("{{'{}'}}", escaped));
            }
        }
    }
}

/// Build an inline arrow function string from a BlockIR.
fn format_inline_handler(body: &BlockIR) -> String {
    if body.statements.is_empty() {
        return "(e) => {}".to_string();
    }
    let mut hw = CodeWriter::new();
    for stmt in &body.statements {
        generate_statement_tsx(&mut hw, stmt);
    }
    let content = hw.into_string();
    // Build a multi-line arrow function
    let mut result = String::from("(e) => {\n");
    for line in content.lines() {
        result.push_str(&format!("        {}\n", line));
    }
    result.push_str("      }");
    result
}

// ═══════════════════════════════════════════════════════════
// Statement generation (TSX)
// ═══════════════════════════════════════════════════════════

fn generate_statement_tsx(w: &mut CodeWriter, stmt: &StatementIR) {
    match stmt {
        StatementIR::LetStmtIR {
            name,
            value,
            r#type,
        } => {
            let rhs = value
                .as_ref()
                .map(format_expr_ir_tsx)
                .unwrap_or_else(|| "null".into());
            let type_hint = r#type
                .as_ref()
                .map(|t| {
                    let ann =
                        super::javascript::js_type(&t.kind, &t.type_args, true);
                    if ann.is_empty() {
                        String::new()
                    } else {
                        format!(": {}", ann)
                    }
                })
                .unwrap_or_default();
            w.emit(&format!("const {}{} = {};", name, type_hint, rhs));
        }
        StatementIR::IfStmtIR {
            condition,
            then_body,
            else_body,
        } => {
            let cond = format_expr_ir_tsx(condition);
            w.emit(&format!("if ({}) {{", cond));
            w.indent();
            for s in &then_body.statements {
                generate_statement_tsx(w, s);
            }
            w.dedent();
            if let Some(else_blk) = else_body {
                if !else_blk.statements.is_empty() {
                    w.emit("} else {");
                    w.indent();
                    for s in &else_blk.statements {
                        generate_statement_tsx(w, s);
                    }
                    w.dedent();
                }
            }
            w.emit("}");
        }
        StatementIR::ReturnStmtIR { value } => {
            let rhs = value
                .as_ref()
                .map(format_expr_ir_tsx)
                .unwrap_or_else(|| "null".into());
            w.emit(&format!("return {};", rhs));
        }
        StatementIR::MutationStmt { intent } => {
            if let Some(mut_intent) = intent {
                let target = &mut_intent.target.name;
                let amount = mut_intent
                    .amount
                    .as_ref()
                    .map(format_expr_ir_tsx)
                    .unwrap_or_else(|| "0".into());
                let setter = format!("set{}", capitalize_first(target));
                match mut_intent.operation.as_str() {
                    "direct_assign" => {
                        w.emit(&format!("{}({});", setter, amount));
                    }
                    "increment" => {
                        w.emit(&format!("{}(prev => prev + {});", setter, amount));
                    }
                    "decrement" => {
                        w.emit(&format!("{}(prev => prev - {});", setter, amount));
                    }
                    other => {
                        w.emit(&format!(
                            "// TODO: mutation operation '{}' on {}",
                            other, target
                        ));
                    }
                }
            }
        }
        StatementIR::ExprStmtIR { expr } => {
            let line = format_expr_ir_tsx(expr);
            if line != "null" {
                w.emit(&format!("{};", line));
            }
        }
        StatementIR::EventEmitStmtIR { event_name, args } => {
            let arg_str = if args.is_empty() {
                String::new()
            } else {
                let formatted: Vec<String> =
                    args.iter().map(format_expr_ir_tsx).collect();
                format!("({})", formatted.join(", "))
            };
            w.emit(&format!("// emit event: {}{}", event_name, arg_str));
        }
    }
}

// ═══════════════════════════════════════════════════════════
// Expression formatting (TSX)
// ═══════════════════════════════════════════════════════════

fn format_expr_ir_tsx(expr: &ExprIR) -> String {
    match expr {
        ExprIR::LiteralExpr { value } => format_json_value_tsx(value),
        ExprIR::IdentifierExpr { name } => name.clone(),
        ExprIR::FieldAccessExpr { object, field } => {
            format!("{}.{}", format_expr_ir_tsx(object), field)
        }
        ExprIR::BinaryOpExpr { op, left, right } => {
            let js_op = binary_op_to_tsx(op);
            let lhs = format_expr_ir_tsx(left);
            let rhs = format_expr_ir_tsx(right);
            format!("{} {} {}", lhs, js_op, rhs)
        }
        ExprIR::UnaryOpExpr { op, operand } => {
            let js_op = match op.as_str() {
                "not" => "!",
                "neg" => "-",
                _ => op,
            };
            format!("{}{}", js_op, format_expr_ir_tsx(operand))
        }
        ExprIR::TernaryIR {
            cond,
            then_expr,
            else_expr,
        } => {
            let c = format_expr_ir_tsx(cond);
            let t = format_expr_ir_tsx(then_expr);
            let e = format_expr_ir_tsx(else_expr);
            format!("{} ? {} : {}", c, t, e)
        }
        ExprIR::StoreFieldAccessExpr {
            store_alias,
            field_name,
            call_args,
        } => {
            let args: Vec<String> = call_args.iter().map(format_expr_ir_tsx).collect();
            let arg_str = if args.is_empty() {
                String::new()
            } else {
                format!("({})", args.join(", "))
            };
            format!("{}.{}{}", store_alias, field_name, arg_str)
        }
    }
}

// ═══════════════════════════════════════════════════════════
// Helpers
// ═══════════════════════════════════════════════════════════

fn capitalize_first(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        None => String::new(),
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
    }
}

fn format_json_value_tsx(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::Null => "null".into(),
        serde_json::Value::Bool(b) => b.to_string(),
        serde_json::Value::Number(n) => n.to_string(),
        serde_json::Value::String(s) => {
            let escaped = s
                .replace('\\', "\\\\")
                .replace('"', "\\\"")
                .replace('\n', "\\n")
                .replace('\r', "\\r")
                .replace('\t', "\\t");
            format!("\"{}\"", escaped)
        }
        serde_json::Value::Array(arr) => {
            let items: Vec<_> = arr.iter().map(format_json_value_tsx).collect();
            format!("[{}]", items.join(", "))
        }
        serde_json::Value::Object(obj) => {
            let items: Vec<_> = obj
                .iter()
                .map(|(k, v)| format!("{}: {}", k, format_json_value_tsx(v)))
                .collect();
            format!("{{ {} }}", items.join(", "))
        }
    }
}

fn binary_op_to_tsx(op: &str) -> &str {
    match op {
        "add" => "+",
        "sub" => "-",
        "mul" => "*",
        "div" => "/",
        "mod" => "%",
        "eq" => "===",
        "neq" => "!==",
        "lt" => "<",
        "gt" => ">",
        "lteq" => "<=",
        "gteq" => ">=",
        "and" => "&&",
        "or" => "||",
        "assign" => "=",
        "addassign" => "+=",
        "subassign" => "-=",
        "mulassign" => "*=",
        "divassign" => "/=",
        "modassign" => "%=",
        _ => op,
    }
}

fn format_css_value(value: &ExprIR) -> String {
    match value {
        ExprIR::LiteralExpr { value } => match value {
            serde_json::Value::String(s) => s.clone(),
            serde_json::Value::Number(n) => format!("{}px", n),
            _ => format!("{}", value),
        },
        _ => String::new(),
    }
}

fn to_css_prop(omni_prop: &str) -> String {
    let mut result = String::new();
    for c in omni_prop.chars() {
        if c.is_uppercase() {
            result.push('-');
            result.push(c.to_ascii_lowercase());
        } else {
            result.push(c);
        }
    }
    result
}

/// Map OmniView attribute names to JSX attribute names.
fn to_jsx_attr(prop_name: &str) -> String {
    match prop_name {
        "class" | "className" => "className".into(),
        "for" | "htmlFor" => "htmlFor".into(),
        "tabindex" => "tabIndex".into(),
        "readonly" => "readOnly".into(),
        "maxlength" => "maxLength".into(),
        "minlength" => "minLength".into(),
        "autocomplete" => "autoComplete".into(),
        "autofocus" => "autoFocus".into(),
        "autoplay" => "autoPlay".into(),
        "enctype" => "encType".into(),
        "formaction" => "formAction".into(),
        "formenctype" => "formEncType".into(),
        "formmethod" => "formMethod".into(),
        "formnovalidate" => "formNoValidate".into(),
        "formtarget" => "formTarget".into(),
        _ => prop_name.to_string(),
    }
}

/// Map OmniView event names to React event handler prop names.
fn to_react_event(event_name: &str) -> String {
    match event_name {
        "click" => "onClick".into(),
        "change" => "onChange".into(),
        "input" => "onInput".into(),
        "submit" => "onSubmit".into(),
        "focus" => "onFocus".into(),
        "blur" => "onBlur".into(),
        "keydown" => "onKeyDown".into(),
        "keyup" => "onKeyUp".into(),
        "keypress" => "onKeyPress".into(),
        "mouseenter" => "onMouseEnter".into(),
        "mouseleave" => "onMouseLeave".into(),
        "mousedown" => "onMouseDown".into(),
        "mouseup" => "onMouseUp".into(),
        "mousemove" => "onMouseMove".into(),
        "mouseover" => "onMouseOver".into(),
        "mouseout" => "onMouseOut".into(),
        "dblclick" => "onDoubleClick".into(),
        "scroll" => "onScroll".into(),
        "wheel" => "onWheel".into(),
        "touchstart" => "onTouchStart".into(),
        "touchend" => "onTouchEnd".into(),
        "touchmove" => "onTouchMove".into(),
        "contextmenu" => "onContextMenu".into(),
        "drag" => "onDrag".into(),
        "dragstart" => "onDragStart".into(),
        "dragend" => "onDragEnd".into(),
        "dragover" => "onDragOver".into(),
        "dragleave" => "onDragLeave".into(),
        "drop" => "onDrop".into(),
        _ => format!("on{}", capitalize_first(event_name)),
    }
}

