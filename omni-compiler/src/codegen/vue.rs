//! Vue codegen: IR -> Vue SFC (.vue) + store composables (.ts).
//!
//! Each component generates a `.vue` Single File Component with
//! `<template>`, `<script setup lang="ts">`, and `<style scoped>` sections.
//! Each store generates a `useXxx.ts` composable using Vue's Composition API.

use std::collections::HashMap;

use super::{CodeWriter, Codegen, CompileOutput, CompiledFile};
use crate::ir::*;

pub struct VueCodegen;

impl Codegen for VueCodegen {
    fn generate(&self, ir: &IRProgram, _source_files: &HashMap<String, String>) -> CompileOutput {
        let mut files = Vec::new();

        // Each component -> .vue SFC
        for (name, comp) in ir.all_components() {
            let sfc = self.gen_component_sfc(name, comp, ir);
            files.push(CompiledFile {
                path: format!("{}.vue", name),
                content: sfc,
            });
        }

        // Each store -> useXxx.ts composable
        for (name, store) in ir.all_stores() {
            let hook = self.gen_store_hook(name, store);
            files.push(CompiledFile {
                path: format!("use{}.ts", name),
                content: hook,
            });
        }

        CompileOutput::success(files)
    }
}

impl VueCodegen {
    /// Generate a Vue SFC (.vue) file for a component.
    fn gen_component_sfc(&self, name: &str, comp: &ComponentIR, ir: &IRProgram) -> String {
        let mut w = CodeWriter::new();
        w.emit("<!-- Generated by OmniLang -- Vue target -->");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <template>
        // ═══════════════════════════════════════════════════════
        w.emit("<template>");
        w.indent();
        if let Some(view) = &comp.view {
            gen_template_node(&mut w, view);
        } else {
            w.emit("<div class=\"container\">");
            w.indent();
            w.emit(&format!("<h1>{{ '{}' }}</h1>", name));
            w.dedent();
            w.emit("</div>");
        }
        w.dedent();
        w.emit("</template>");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <script setup lang="ts">
        // ═══════════════════════════════════════════════════════
        w.emit("<script setup lang=\"ts\">");
        w.indent();

        // Determine which Vue imports are needed
        let mut vue_imports: Vec<String> = Vec::new();
        vue_imports.push("ref".into());
        if (!comp.computeds.is_empty() || !comp.store_refs.is_empty())
            && !vue_imports.contains(&"computed".into())
        {
            vue_imports.push("computed".into());
        }
        if !comp.effects.is_empty() {
            vue_imports.push("watchEffect".into());
        }
        let has_mount = comp.lifecycles.iter().any(|lc| lc.kind == "mount");
        let has_unmount = comp.lifecycles.iter().any(|lc| lc.kind == "unmount");
        if has_mount {
            vue_imports.push("onMounted".into());
        }
        if has_unmount {
            vue_imports.push("onUnmounted".into());
        }

        w.emit(&format!(
            "import {{ {} }} from 'vue';",
            vue_imports.join(", ")
        ));
        w.emit("");

        // Store hook imports
        let mut store_hook_imports = Vec::new();
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                store_hook_imports.push(format!(
                    "import {{ {} }} from './use{}';",
                    hook_name, store_ref
                ));
            }
        }
        for import_line in &store_hook_imports {
            w.emit(import_line);
        }
        if !store_hook_imports.is_empty() {
            w.emit("");
        }

        // Props interface + defineProps
        if !comp.props.is_empty() {
            w.emit("const props = defineProps<{");
            w.indent();
            for (prop_name, prop_type) in &comp.props {
                let ts_type =
                    super::javascript::js_type(&prop_type.kind, &prop_type.type_args, true);
                w.emit(&format!("  {}: {};", prop_name, ts_type));
            }
            w.dedent();
            w.emit("}>();");
            w.emit("");
        }

        // Store composable calls
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                w.emit(&format!("const {} = {}();", store_ref, hook_name));
            }
        }

        // State (ref declarations)
        for state in &comp.states {
            let init_val = format_expr_vue(&state.initial_value);
            let ts_type =
                super::javascript::js_type(&state.r#type.kind, &state.r#type.type_args, true);
            if ts_type.is_empty() {
                w.emit(&format!("const {} = ref({});", state.name, init_val));
            } else {
                w.emit(&format!(
                    "const {} = ref<{}>({});",
                    state.name, ts_type, init_val
                ));
            }
        }

        // Effects (watchEffect)
        for effect in &comp.effects {
            w.emit("watchEffect(() => {");
            w.indent();
            for stmt in &effect.body.statements {
                generate_statement_vue(&mut w, stmt);
            }
            w.dedent();
            w.emit("});");
        }

        // Lifecycles (onMounted / onUnmounted)
        for lc in &comp.lifecycles {
            match lc.kind.as_str() {
                "mount" => {
                    w.emit("onMounted(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_vue(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                "unmount" => {
                    w.emit("onUnmounted(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_vue(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                _ => {
                    w.emit(&format!("// TODO: lifecycle '{}'", lc.kind));
                }
            }
        }

        // Computed values
        for computed in &comp.computeds {
            w.emit(&format!("const {} = computed(() => {{", computed.name));
            w.indent();
            w.emit(&format!("  return {};", format_expr_vue(&computed.body)));
            w.dedent();
            w.emit("});");
        }

        // Functions
        for func in &comp.fns {
            generate_function_vue(&mut w, func);
        }

        w.dedent();
        w.emit("</script>");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <style scoped>
        // ═══════════════════════════════════════════════════════
        w.emit("<style scoped>");
        w.indent();
        if comp.styles.is_empty() {
            w.emit(".container {");
            w.indent();
            w.emit("  display: flex;");
            w.emit("  flex-direction: column;");
            w.emit("  padding: 16px;");
            w.dedent();
            w.emit("}");
        } else {
            for style in &comp.styles {
                w.emit(&format!(".{} {{", style.class_name));
                for (prop, value) in &style.properties {
                    let css_val = format_css_value(value);
                    w.emit(&format!("  {}: {};", to_css_prop(prop), css_val));
                }
                w.emit("}");
            }
        }
        w.dedent();
        w.emit("</style>");
        w.emit("");

        w.into_string()
    }

    /// Generate a store composable (useXxx.ts).
    fn gen_store_hook(&self, name: &str, store: &StoreIR) -> String {
        let mut w = CodeWriter::new();
        w.emit(&format!(
            "// Generated by OmniLang -- Store composable: use{}",
            name
        ));
        w.emit("import { ref, computed } from 'vue';");
        w.emit("");

        w.emit(&format!("export function use{}() {{", name));
        w.indent();

        // Signals as refs
        for (sig_name, sig_type) in &store.signals {
            let init = store
                .signal_defaults
                .get(sig_name)
                .map(format_json_value_vue)
                .unwrap_or_else(|| "null".into());
            let ts_type = super::javascript::js_type(&sig_type.kind, &sig_type.type_args, true);
            if ts_type.is_empty() {
                w.emit(&format!("const {} = ref({});", sig_name, init));
            } else {
                w.emit(&format!("const {} = ref<{}>({});", sig_name, ts_type, init));
            }
        }

        // Getters as computed
        for (getter_name, getter_expr) in &store.getters {
            w.emit(&format!("const {} = computed(() => {{", getter_name));
            w.indent();
            w.emit(&format!("  return {};", format_expr_vue(getter_expr)));
            w.dedent();
            w.emit("});");
        }

        // Return value (refs are returned directly; templates auto-unwrap)
        let mut return_keys: Vec<String> = Vec::new();
        for sig_name in store.signals.keys() {
            return_keys.push(sig_name.clone());
        }
        for getter_name in store.getters.keys() {
            return_keys.push(getter_name.clone());
        }
        w.emit(&format!("return {{ {} }};", return_keys.join(", ")));

        w.dedent();
        w.emit("}");
        w.into_string()
    }
}

// ═══════════════════════════════════════════════════════════
// Vue template node generation
// ═══════════════════════════════════════════════════════════

fn gen_template_node(w: &mut CodeWriter, node: &ViewTree) {
    match node {
        ViewTree::Element(el) => {
            let mut attrs: Vec<String> = Vec::new();

            // Static props -> plain HTML attributes
            for (prop_name, prop_value) in &el.props {
                let vue_attr = to_vue_attr(prop_name);
                match prop_value {
                    ExprIR::LiteralExpr { value } if value.is_string() => {
                        let s = value.as_str().unwrap();
                        // Escape quotes for HTML attribute
                        let escaped = s.replace('"', "&quot;");
                        attrs.push(format!("{}=\"{}\"", vue_attr, escaped));
                    }
                    _ => {
                        let vue_val = format_expr_vue(prop_value);
                        attrs.push(format!(":{}={}", vue_attr, vue_val));
                    }
                }
            }

            // Signal bindings -> :prop="signalRef"
            for (bind_name, signal_ref) in &el.bindings {
                let vue_attr = to_vue_attr(bind_name);
                attrs.push(format!(":{}={}", vue_attr, signal_ref.name));
            }

            // Events -> @event="handler"
            for (event_name, handler) in &el.events {
                let vue_event = to_vue_event(event_name);
                match handler.kind.as_str() {
                    "fn_ref" => {
                        if let Some(ref fn_name) = handler.r#ref {
                            attrs.push(format!("@{}=\"{}\"", vue_event, fn_name));
                        }
                    }
                    "inline_fn" => {
                        if let Some(ref body) = handler.body {
                            let handler_str = format_inline_handler_vue(body);
                            attrs.push(format!("@{}=\"{}\"", vue_event, handler_str));
                        }
                    }
                    "store_action" => {
                        if let Some(ref action) = handler.r#ref {
                            attrs.push(format!("@{}=\"/* TODO: action {} */\"", vue_event, action));
                        }
                    }
                    _ => {
                        attrs.push(format!(
                            "@{}=\"/* TODO: handler kind '{}' */\"",
                            vue_event, handler.kind
                        ));
                    }
                }
            }

            // Style classes from view
            if let Some(ref classes) = el.style_classes {
                if let Some(classes_str) = classes.as_str() {
                    attrs.push(format!(":class=\"{}\"", classes_str));
                }
            }

            // Inline style
            if el.inline_style.is_some() {
                attrs.push(":style=\"{ /* TODO: inline style */ }\"".into());
            }

            // Emit opening tag
            if attrs.is_empty() && el.children.is_empty() {
                w.emit(&format!("<{} />", el.tag));
                return;
            }

            if attrs.is_empty() {
                w.emit(&format!("<{}>", el.tag));
            } else {
                w.emit(&format!("<{}", el.tag));
                w.indent();
                for attr in &attrs {
                    w.emit(&attr.to_string());
                }
                if el.children.is_empty() {
                    w.dedent();
                    w.emit("/>");
                    return;
                }
                w.dedent();
                w.emit(">");
            }

            // Children
            w.indent();
            for child in &el.children {
                gen_template_node(w, child);
            }
            w.dedent();

            // Closing tag
            w.emit(&format!("</{}>", el.tag));
        }

        ViewTree::Conditional(cond) => {
            let branches = &cond.branches;
            let fallback = &cond.fallback;

            if branches.is_empty() {
                if let Some(ref fb) = fallback {
                    gen_template_node(w, fb);
                }
                return;
            }

            // Single branch without fallback ->
            //   <template v-if="condition">
            //     ...body...
            //   </template>
            if branches.len() == 1 && fallback.is_none() {
                let cond_str = format_expr_vue(&branches[0].condition);
                let cond_safe = cond_str.replace('"', "&quot;");
                w.emit(&format!("<template v-if=\"{}\">", cond_safe));
                w.indent();
                if let Some(ref body) = branches[0].body {
                    gen_template_node(w, body);
                }
                w.dedent();
                w.emit("</template>");
                return;
            }

            // Multiple branches or with fallback
            for (i, branch) in branches.iter().enumerate() {
                let cond_str = format_expr_vue(&branch.condition);
                let cond_safe = cond_str.replace('"', "&quot;");
                if i == 0 {
                    w.emit(&format!("<template v-if=\"{}\">", cond_safe));
                } else {
                    w.emit(&format!("<template v-else-if=\"{}\">", cond_safe));
                }
                w.indent();
                if let Some(ref body) = branch.body {
                    gen_template_node(w, body);
                }
                w.dedent();
                w.emit("</template>");
            }

            if let Some(ref fb) = fallback {
                w.emit("<template v-else>");
                w.indent();
                gen_template_node(w, fb);
                w.dedent();
                w.emit("</template>");
            }
        }

        ViewTree::ListRendering(list) => {
            let iterable_str = format_expr_vue(&list.iterable);
            let item_name = &list.item_binding.name;
            w.emit(&format!(
                "<template v-for=\"({}, index) in {}\" :key=\"index\">",
                item_name, iterable_str
            ));
            w.indent();
            if let Some(ref body) = list.body {
                gen_template_node(w, body);
            }
            w.dedent();
            w.emit("</template>");
        }

        ViewTree::Text(text) => {
            if text.starts_with('{') && text.ends_with('}') {
                // Interpolation expression like {name} or {param:xxx}
                // In Vue, use {{ }} for interpolation
                let inner = &text[1..text.len() - 1];
                w.emit(&format!("{{{{ {} }}}}", inner));
            } else {
                // Plain text — escape Vue template delimiters and HTML-significant chars
                let safe = text
                    .replace('&', "&amp;")
                    .replace('<', "&lt;")
                    .replace('>', "&gt;")
                    .replace("{{", "\\{\\{")
                    .replace("}}", "\\}\\}");
                w.emit(&safe);
            }
        }
        ViewTree::Interpolation(_expr) => {
            w.emit("{{ }}");
        }
        ViewTree::Slot(_) => {
            // slots not supported in Vue codegen — emit placeholder
        }
    }
}

/// Build an inline arrow function string from a BlockIR for Vue event handlers.
fn format_inline_handler_vue(body: &BlockIR) -> String {
    if body.statements.is_empty() {
        return "() => {}".to_string();
    }
    let mut hw = CodeWriter::new();
    for stmt in &body.statements {
        generate_statement_vue(&mut hw, stmt);
    }
    let content = hw.into_string();
    let mut result = String::from("() => {\n");
    for line in content.lines() {
        result.push_str(&format!("        {}\n", line));
    }
    result.push_str("      }");
    result
}

// ═══════════════════════════════════════════════════════════
// Function generation (Vue script setup)
// ═══════════════════════════════════════════════════════════

fn generate_function_vue(w: &mut CodeWriter, func: &FunctionIR) {
    let mut param_strs = Vec::new();
    for p in &func.params {
        let mut s = p.name.clone();
        if let Some(ref ty) = p.r#type {
            let ann = super::javascript::js_type(&ty.kind, &ty.type_args, true);
            if !ann.is_empty() {
                s.push_str(&format!(": {}", ann));
            }
        }
        param_strs.push(s);
    }

    let ret_ann = func
        .return_type
        .as_ref()
        .map(|rt| {
            let ann = super::javascript::js_type(&rt.kind, &rt.type_args, true);
            if ann.is_empty() {
                String::new()
            } else {
                format!(": {}", ann)
            }
        })
        .unwrap_or_default();

    let all_params = param_strs.join(", ");
    let async_kw = if func.is_async { "async " } else { "" };
    w.emit(&format!(
        "{}function {}({}){} {{",
        async_kw, func.name, all_params, ret_ann
    ));
    w.indent();

    for stmt in &func.body.statements {
        generate_statement_vue(w, stmt);
    }

    w.dedent();
    w.emit("}");
}

// ═══════════════════════════════════════════════════════════
// Statement generation (Vue script setup)
// ═══════════════════════════════════════════════════════════

fn generate_statement_vue(w: &mut CodeWriter, stmt: &StatementIR) {
    match stmt {
        StatementIR::LetStmtIR {
            name,
            value,
            r#type,
        } => {
            let rhs = value
                .as_ref()
                .map(format_expr_vue)
                .unwrap_or_else(|| "null".into());
            let type_hint = r#type
                .as_ref()
                .map(|t| {
                    let ann = super::javascript::js_type(&t.kind, &t.type_args, true);
                    if ann.is_empty() {
                        String::new()
                    } else {
                        format!(": {}", ann)
                    }
                })
                .unwrap_or_default();
            w.emit(&format!("const {}{} = {};", name, type_hint, rhs));
        }
        StatementIR::IfStmtIR {
            condition,
            then_body,
            else_ifs,
            else_body,
        } => {
            let cond = format_expr_vue(condition);
            w.emit(&format!("if ({}) {{", cond));
            w.indent();
            for s in &then_body.statements {
                generate_statement_vue(w, s);
            }
            w.dedent();
            for (elif_cond, elif_body) in else_ifs {
                let elif_js = format_expr_vue(elif_cond);
                w.emit(&format!("}} else if ({}) {{", elif_js));
                w.indent();
                for s in &elif_body.statements {
                    generate_statement_vue(w, s);
                }
                w.dedent();
            }
            if let Some(else_blk) = else_body {
                if !else_blk.statements.is_empty() {
                    w.emit("} else {");
                    w.indent();
                    for s in &else_blk.statements {
                        generate_statement_vue(w, s);
                    }
                    w.dedent();
                }
            }
            w.emit("}");
        }
        StatementIR::ReturnStmtIR { value } => {
            let rhs = value
                .as_ref()
                .map(format_expr_vue)
                .unwrap_or_else(|| "null".into());
            w.emit(&format!("return {};", rhs));
        }
        StatementIR::MutationStmt { intent: None } => {}
        StatementIR::MutationStmt {
            intent: Some(mut_intent),
        } => {
            let target = &mut_intent.target.name;
            let amount = mut_intent
                .amount
                .as_ref()
                .map(format_expr_vue)
                .unwrap_or_else(|| "0".into());
            match mut_intent.operation.as_str() {
                "direct_assign" => {
                    w.emit(&format!("{}.value = {};", target, amount));
                }
                "increment" => {
                    w.emit(&format!("{}.value += {};", target, amount));
                }
                "decrement" => {
                    w.emit(&format!("{}.value -= {};", target, amount));
                }
                "multiply" => {
                    w.emit(&format!("{}.value *= {};", target, amount));
                }
                "divide" => {
                    w.emit(&format!("{}.value /= {};", target, amount));
                }
                "modulo" => {
                    w.emit(&format!("{}.value %= {};", target, amount));
                }
                other => {
                    w.emit(&format!(
                        "// TODO: mutation operation '{}' on {}",
                        other, target
                    ));
                }
            }
        }
        StatementIR::ExprStmtIR { expr } => {
            let line = format_expr_vue(expr);
            if line != "null" {
                w.emit(&format!("{};", line));
            }
        }
        StatementIR::EventEmitStmtIR { event_name, args } => {
            let arg_str = if args.is_empty() {
                String::new()
            } else {
                let formatted: Vec<String> = args.iter().map(format_expr_vue).collect();
                format!("({})", formatted.join(", "))
            };
            w.emit(&format!("// emit event: {}{}", event_name, arg_str));
        }
        StatementIR::WhileStmtIR { condition, body } => {
            let cond = format_expr_vue(condition);
            w.emit(&format!("while ({}) {{", cond));
            w.indent();
            for s in &body.statements {
                generate_statement_vue(w, s);
            }
            w.dedent();
            w.emit("}");
        }
        StatementIR::ForInStmtIR {
            var_name,
            iterable,
            body,
        } => {
            let iter = format_expr_vue(iterable);
            w.emit(&format!("for (const {} of {}) {{", var_name, iter));
            w.indent();
            for s in &body.statements {
                generate_statement_vue(w, s);
            }
            w.dedent();
            w.emit("}");
        }
        StatementIR::BreakStmtIR => {
            w.emit("break;");
        }
        StatementIR::ContinueStmtIR => {
            w.emit("continue;");
        }
        _ => {}
    }
}

fn format_block_as_vue_expr(block: &BlockIR) -> String {
    if let Some(last) = block.statements.last() {
        match last {
            StatementIR::ExprStmtIR { expr } => format_expr_vue(expr),
            StatementIR::ReturnStmtIR { value } => value
                .as_ref()
                .map(|e| format_expr_vue(e))
                .unwrap_or_else(|| "undefined".into()),
            _ => "undefined".into(),
        }
    } else {
        "undefined".into()
    }
}

// ═══════════════════════════════════════════════════════════
// Expression formatting (Vue)
// ═══════════════════════════════════════════════════════════

fn format_expr_vue(expr: &ExprIR) -> String {
    match expr {
        ExprIR::LiteralExpr { value } => format_json_value_vue(value),
        ExprIR::IdentifierExpr { name } => name.clone(),
        ExprIR::FieldAccessExpr { object, field } => {
            format!("{}.{}", format_expr_vue(object), field)
        }
        ExprIR::OptionalChainExpr { object, field } => {
            format!("{}.{}", format_expr_vue(object), field)
        }
        ExprIR::BinaryOpExpr { op, left, right } => {
            let js_op = binary_op_to_vue(op);
            let lhs = format_expr_vue(left);
            let rhs = format_expr_vue(right);
            format!("{} {} {}", lhs, js_op, rhs)
        }
        ExprIR::UnaryOpExpr { op, operand } => {
            let js_op = match op.as_str() {
                "not" => "!",
                "neg" => "-",
                _ => op,
            };
            format!("{}{}", js_op, format_expr_vue(operand))
        }
        ExprIR::TernaryIR {
            cond,
            then_expr,
            else_expr,
        } => {
            let c = format_expr_vue(cond);
            let t = format_expr_vue(then_expr);
            let e = format_expr_vue(else_expr);
            format!("{} ? {} : {}", c, t, e)
        }
        ExprIR::CallExpr { name, args } => {
            let arg_strs: Vec<String> = args.iter().map(format_expr_vue).collect();
            format!("{}({})", name, arg_strs.join(", "))
        }
        ExprIR::StoreFieldAccessExpr {
            store_alias,
            field_name,
            call_args,
        } => {
            let args: Vec<String> = call_args.iter().map(format_expr_vue).collect();
            let arg_str = if args.is_empty() {
                String::new()
            } else {
                format!("({})", args.join(", "))
            };
            format!("{}.{}{}", store_alias, field_name, arg_str)
        }
        ExprIR::ArrayExpr { elements } => {
            let items: Vec<String> = elements.iter().map(format_expr_vue).collect();
            format!("[{}]", items.join(", "))
        }
        ExprIR::StructExpr { fields, .. } => {
            let entries: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("\"{}\": {}", k, format_expr_vue(v)))
                .collect();
            format!("{{{}}}", entries.join(", "))
        }
        ExprIR::VariantLiteral {
            variant, fields, ..
        } => {
            let mut entries: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("\"{}\": {}", k, format_expr_vue(v)))
                .collect();
            entries.insert(0, format!("\"_variant\": \"{}\"", variant));
            format!("{{{}}}", entries.join(", "))
        }
        ExprIR::MethodCallExpr {
            object,
            method,
            args,
            ..
        } => {
            let obj = format_expr_vue(object);
            let arg_strs: Vec<String> = args.iter().map(|a| format_expr_vue(a)).collect();
            format!("{}.{}({})", obj, method, arg_strs.join(", "))
        }
        ExprIR::BlockExpr {
            statements: _,
            tail,
        } => {
            // Only tail expression emitted; preceding statements preserved in IR for future codegen
            format_expr_vue(tail)
        }
        ExprIR::IndexExpr { object, index } => {
            let obj = format_expr_vue(object);
            let idx = format_expr_vue(index);
            format!("({obj})[{idx}]")
        }
        ExprIR::AwaitExpr { operand } => {
            format!("await {}", format_expr_vue(operand))
        }
        ExprIR::MatchExpr { matched, arms } => {
            let m = format_expr_vue(matched);
            let cases: Vec<String> = arms
                .iter()
                .map(|arm| {
                    let body = format_block_as_vue_expr(&arm.body);
                    match &arm.pattern.kind {
                        MatchPatternKindIR::Variant { name, .. } => {
                            format!("if (_v._variant === \"{}\") {{ return {}; }}", name, body)
                        }
                        MatchPatternKindIR::Wildcard => {
                            format!("return {};", body)
                        }
                        MatchPatternKindIR::Literal { value } => {
                            let v = format_json_value_vue(value);
                            format!("if (_v._variant === {}) {{ return {}; }}", v, body)
                        }
                    }
                })
                .collect();
            format!("(() => {{ const _v = {}; {} }})()", m, cases.join(" "))
        }
        ExprIR::ClosureExpr { params, body } => {
            let p = params.join(", ");
            let b = format_expr_vue(body);
            format!("(({p}) => ({b}))")
        }
    }
}

