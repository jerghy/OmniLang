pub struct DioxusCodegen;

impl PerComponentCodegen for DioxusCodegen {
    fn gen_component_file(
        &self,
        name: &str,
        comp: &ComponentIR,
        ir: &IRProgram,
    ) -> Vec<CompiledFile> {
        vec![CompiledFile {
            path: format!("{}.rs", name),
            content: self.gen_component_rs(name, comp, ir),
        }]
    }
    fn gen_store_file(&self, name: &str, store: &StoreIR) -> Vec<CompiledFile> {
        vec![CompiledFile {
            path: format!("{}.rs", to_snake_case(name)),
            content: self.gen_store_module(name, store),
        }]
    }
}

impl Codegen for DioxusCodegen {
    fn generate(&self, ir: &IRProgram, _source_files: &HashMap<String, String>) -> CompileOutput {
        generate_per_component(self, ir)
    }
}

impl DioxusCodegen {
    /// Generate a Dioxus component .rs file.
    fn gen_component_rs(&self, name: &str, comp: &ComponentIR, ir: &IRProgram) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang -- Dioxus target");
        w.emit("");

        // Imports
        w.emit("use dioxus::prelude::*;");
        w.emit("");

        // Props struct
        if !comp.props.is_empty() {
            w.emit("#[derive(Props, PartialEq, Clone)]");
            w.emit_fmt(format_args!("struct {}Props {{", name));
            w.indent();
            for (prop_name, prop_type) in &comp.props {
                let rs_ty = super::rust::rs_type(&prop_type.kind.as_str(), &prop_type.type_args);
                w.emit_fmt(format_args!("{}: {},", prop_name, rs_ty));
            }
            w.dedent();
            w.emit("}");
            w.emit("");
        }

        // Component function
        if comp.props.is_empty() {
            w.emit("#[allow(non_snake_case)]");
            w.emit("#[component]");
            w.emit_fmt(format_args!("pub fn {}() -> Element {{", name));
        } else {
            w.emit("#[allow(non_snake_case)]");
            w.emit("#[component]");
            w.emit_fmt(format_args!(
                "pub fn {}(props: {}Props) -> Element {{",
                name, name
            ));
        }
        w.indent();

        // Store module imports
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let snake = to_snake_case(store_ref);
                w.emit_fmt(format_args!("mod {};", snake));
            }
        }
        if !comp.store_refs.is_empty() {
            w.emit("");
        }

        // Store hook calls
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let snake = to_snake_case(store_ref);
                w.emit_fmt(format_args!(
                    "let {} = {}::use_{}();",
                    store_ref, snake, snake
                ));
            }
        }

        // State signals (use_signal)
        for state in &comp.states {
            let init_val = format_expr_ir_dioxus(&state.initial_value);
            w.emit_fmt(format_args!(
                "let mut {} = use_signal(|| {});",
                state.name, init_val
            ));
        }

        // Effects (use_effect)
        for effect in &comp.effects {
            w.emit("use_effect(move || async move {");
            w.indent();
            for stmt in &effect.body.statements {
                generate_statement_dioxus(&mut w, stmt);
            }
            w.dedent();
            w.emit("});");
        }

        // Lifecycles (mount/unmount)
        for lc in &comp.lifecycles {
            match lc.kind {
                LifecycleKind::Mount => {
                    w.emit("use_effect(move || async move {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_dioxus(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                LifecycleKind::Unmount => {
                    w.emit("use_effect(move || {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_dioxus(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                LifecycleKind::Effect => {
                    w.emit("use_effect(move || async move {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_dioxus(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
            }
        }

        // Computed values (use_memo)
        for computed in &comp.computeds {
            w.emit_fmt(format_args!("let {} = use_memo(move || {{", computed.name));
            w.indent();
            w.emit(&format_expr_ir_dioxus(&computed.body).to_string());
            w.dedent();
            w.emit("});");
        }

        w.emit("");

        // Render return (rsx! view tree)
        w.emit("rsx! {");
        w.indent();
        if let Some(view) = &comp.view {
            gen_view_node_dioxus(&mut w, view, true);
        } else {
            w.emit("div {");
            w.indent();
            w.emit_fmt(format_args!("\"{}\"", name));
            w.dedent();
            w.emit("},");
        }
        w.dedent();
        w.emit("}");

        w.dedent();
        w.emit("}");
        w.emit("");

        w.into_string()
    }

    /// Generate a store module file with a hook function.
    fn gen_store_module(&self, name: &str, store: &StoreIR) -> String {
        let mut w = CodeWriter::new();
        w.emit_fmt(format_args!(
            "// Generated by OmniLang -- Store module: {}",
            name
        ));
        w.emit("use dioxus::prelude::*;");
        w.emit("");

        if store.signals.is_empty() {
            w.emit_fmt(format_args!("pub struct {};", name));
            w.emit("");
            let hook_name = format!("use_{}", to_snake_case(name));
            w.emit_fmt(format_args!("pub fn {}() -> {} {{", hook_name, name));
            w.indent();
            w.emit(name);
            w.dedent();
            w.emit("}");
            return w.into_string();
        }

        // Struct with Signal<T> fields
        w.emit_fmt(format_args!("pub struct {} {{", name));
        w.indent();
        for (sig_name, sig_type) in &store.signals {
            let rs_ty = super::rust::rs_type(&sig_type.kind.as_str(), &sig_type.type_args);
            w.emit_fmt(format_args!("pub {}: Signal<{}>,", sig_name, rs_ty));
        }
        w.dedent();
        w.emit("}");
        w.emit("");

        // Hook function
        let hook_name = format!("use_{}", to_snake_case(name));
        w.emit_fmt(format_args!("pub fn {}() -> {} {{", hook_name, name));
        w.indent();
        w.emit_fmt(format_args!("{} {{", name));
        w.indent();
        for sig_name in store.signals.keys() {
            let default = store
                .signal_defaults
                .get(sig_name)
                .map(|v| format_json_value(v, &JSON_DIOXUS))
                .unwrap_or_else(|| "Default::default()".into());
            w.emit_fmt(format_args!("{}: use_signal(|| {}),", sig_name, default));
        }
        w.dedent();
        w.emit("}");
        w.dedent();
        w.emit("}");

        // Getters -- skipped for now; too dependent on component context
        if !store.getters.is_empty() {
            w.emit("");
            w.emit("// Getters: implement as methods if needed");
        }

        w.into_string()
    }
}

