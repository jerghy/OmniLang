pub struct FlutterCodegen;

impl Codegen for FlutterCodegen {
    fn generate(&self, ir: &IRProgram, source_files: &FxHashMap<String, String>) -> CompileOutput {
        self.generate_per_component(ir, source_files)
    }

    fn gen_component_file(
        &self,
        name: &str,
        comp: &ComponentIR,
        ir: &IRProgram,
    ) -> Vec<CompiledFile> {
        let component_map = build_component_map(ir);
        vec![CompiledFile {
            path: format!("{}.dart", name),
            content: self.gen_component_dart(name, comp, ir, &component_map),
        }]
    }
    fn gen_store_file(&self, name: &str, store: &StoreIR) -> Vec<CompiledFile> {
        vec![CompiledFile {
            path: format!("{}_store.dart", name),
            content: self.gen_store_dart(name, store),
        }]
    }
}

impl FlutterCodegen {
    /// Generate a complete .dart file for a component as a StatefulWidget.
    fn gen_component_dart(
        &self,
        name: &str,
        comp: &ComponentIR,
        ir: &IRProgram,
        component_map: &FxHashMap<&str, &ComponentIR>,
    ) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang \u{2014} Flutter target");
        w.emit("");
        w.emit("import 'package:flutter/material.dart';");
        w.emit("");

        // Store imports
        for store_ref in &comp.store_refs {
            if ir.has_store(store_ref.as_str()) {
                w.emit_fmt(format_args!("import './{}_store.dart';", store_ref));
            }
        }
        if !comp.store_refs.is_empty() {
            w.emit("import 'package:flutter_riverpod/flutter_riverpod.dart';");
            w.emit("");
        }
        if !comp.store_refs.is_empty() {
            w.emit("");
        }

        let state_name = format!("_{}State", name);

        // Determine widget/state base classes
        let (widget_base, state_base) = if comp.store_refs.is_empty() {
            ("StatefulWidget", "State")
        } else {
            ("ConsumerStatefulWidget", "ConsumerState")
        };

        // ── Widget class ──
        w.emit_fmt(format_args!("class {} extends {} {{", name, widget_base));
        w.indent();

        if comp.props.is_empty() {
            w.emit_fmt(format_args!("const {}({{super.key}});", name));
        } else {
            // Constructor with named parameters for props
            w.emit("const {");
            w.indent();
            w.emit("super.key,");
            for prop_name in comp.props.keys() {
                w.emit_fmt(format_args!("required this.{},", prop_name));
            }
            w.dedent();
            w.emit("});");

            // Field declarations for props
            w.emit("");
            for (prop_name, prop_type) in &comp.props {
                let ann = super::dart::dart_type(prop_type.kind.as_str(), &prop_type.type_args);
                w.emit_fmt(format_args!("final {} {};", ann, prop_name));
            }
        }

        w.emit("");
        w.emit("@override");
        w.emit_fmt(format_args!(
            "{}<{}> createState() => {}();",
            state_base, name, state_name
        ));

        w.dedent();
        w.emit("}");
        w.emit("");

        // ── State class ──
        let state_mixin = if ir.modules.values().all(|m| m.motions.is_empty()) {
            String::new()
        } else {
            " with TickerProviderStateMixin".to_string()
        };
        w.emit_fmt(format_args!(
            "class {} extends {}<{}>{} {{",
            state_name, state_base, name, state_mixin
        ));
        w.indent();

        // State variables as class fields
        for state in &comp.signals {
            let ann = super::dart::dart_type(state.r#type.kind.as_str(), &state.r#type.type_args);
            let init = format_expr_ir_flutter(&state.initial_value);
            w.emit_fmt(format_args!("{} {} = {};", ann, state.name, init));
        }
        if !comp.signals.is_empty() {
            w.emit("");
        }

        // AnimationController/Animation field declarations for motion animations
        for motion in ir.modules.values().flat_map(|m| &m.motions) {
            let ctrl_name = format!("_{}Controller", motion.name);
            let anim_name = format!("_{}Animation", motion.name);
            w.emit_fmt(format_args!(
                "late final AnimationController {};",
                ctrl_name
            ));
            w.emit_fmt(format_args!("late final Animation<double> {};", anim_name));
        }
        if !ir.modules.values().all(|m| m.motions.is_empty()) {
            w.emit("");
        }

        // Computed properties as getters
        for computed in &comp.computeds {
            let ret_type =
                super::dart::dart_type(computed.r#type.kind.as_str(), &computed.r#type.type_args);
            w.emit_fmt(format_args!("{} get {} {{", ret_type, computed.name));
            w.indent();
            w.emit_fmt(format_args!(
                "return {};",
                format_expr_ir_flutter(&computed.body)
            ));
            w.dedent();
            w.emit("}");
            w.emit("");
        }

        // initState (for mount lifecycle, effects, and motion animations)
        let has_mount = comp
            .lifecycles
            .iter()
            .any(|lc| lc.kind == LifecycleKind::Mount);
        let has_effects = !comp.effects.is_empty();
        let has_motions = !ir.modules.values().all(|m| m.motions.is_empty());
        if has_mount || has_effects || has_motions {
            w.emit("@override");
            w.emit("void initState() {");
            w.indent();
            w.emit("super.initState();");

            // Determine which motions have @enter triggers (forward on mount)
            let enter_motions: Vec<String> = comp
                .view
                .as_ref()
                .map(find_enter_motions)
                .unwrap_or_default();

            // Create AnimationController and Animation for each motion
            for motion in ir.modules.values().flat_map(|m| &m.motions) {
                let ctrl_name = format!("_{}Controller", motion.name);
                let anim_name = format!("_{}Animation", motion.name);
                let MotionBodyIR::Keyframe(kf) = &motion.body;
                let duration_ms = extract_duration_ms(&kf.over);
                let ease_str = format_easing_flutter(&kf.ease);
                let properties = extract_keyframe_properties(kf);
                let primary_prop = properties.first().map(|s| s.as_str()).unwrap_or("opacity");
                let begin = extract_tween_begin(kf, primary_prop);
                let end = extract_tween_end(kf, primary_prop);
                let has_enter = enter_motions.contains(&motion.name);

                // Create AnimationController
                w.emit_fmt(format_args!(
                    "{0} = AnimationController(\n  duration: Duration(milliseconds: {1}),\n  vsync: this,\n);",
                    ctrl_name, duration_ms
                ));
                // Create Animation with Tween + Curve
                w.emit_fmt(format_args!(
                    "{0} = Tween<double>(begin: {1}, end: {2}).chain(CurveTween(curve: {3})).animate({4});",
                    anim_name, begin, end, ease_str, ctrl_name
                ));

                // @enter trigger: play animation on mount
                if has_enter {
                    w.emit_fmt(format_args!("{}.forward();", ctrl_name));
                }
            }

            // Mount lifecycle
            for lc in &comp.lifecycles {
                if lc.kind == LifecycleKind::Mount {
                    for stmt in &lc.body.statements {
                        generate_statement_flutter(&mut w, stmt);
                    }
                }
            }
            // Effects
            for (i, effect) in comp.effects.iter().enumerate() {
                let method_name = format!("_runEffect_{}", i);
                w.emit_fmt(format_args!("{}();", method_name));
                for stmt in &effect.body.statements {
                    generate_statement_flutter(&mut w, stmt);
                }
                w.emit("// @effect: re-executes on setState");
            }
            w.dedent();
            w.emit("}");
            w.emit("");
        }

        // dispose (for unmount lifecycle and motion controllers)
        let has_unmount = comp
            .lifecycles
            .iter()
            .any(|lc| lc.kind == LifecycleKind::Unmount);
        if has_unmount || has_motions {
            w.emit("@override");
            w.emit("void dispose() {");
            w.indent();
            for lc in &comp.lifecycles {
                if lc.kind == LifecycleKind::Unmount {
                    for stmt in &lc.body.statements {
                        generate_statement_flutter(&mut w, stmt);
                    }
                }
            }
            // Dispose motion AnimationControllers
            for motion in ir.modules.values().flat_map(|m| &m.motions) {
                let ctrl_name = format!("_{}Controller", motion.name);
                w.emit_fmt(format_args!("{}.dispose();", ctrl_name));
            }
            w.emit("super.dispose();");
            w.dedent();
            w.emit("}");
            w.emit("");
        }

        // Functions as methods on State
        for func in &comp.fns {
            generate_function_flutter(&mut w, func);
            w.emit("");
        }

        // Build method
        w.emit("@override");
        w.emit("Widget build(BuildContext context) {");
        w.indent();

        if let Some(view) = &comp.view {
            let tree_expr = format_view_tree(
                view,
                &ir.modules
                    .values()
                    .flat_map(|m| &m.motions)
                    .cloned()
                    .collect::<Vec<_>>(),
                component_map,
            );
            w.emit_fmt(format_args!("return {};", tree_expr));
        } else {
            // Default widget tree
            w.emit("return Container(");
            w.indent();
            w.emit_fmt(format_args!("child: Text('{}'),", name));
            w.dedent();
            w.emit(");");
        }

        w.dedent();
        w.emit("}");

        w.dedent();
        w.emit("}");

        // ── Emit helper widget classes for InView and Scroll triggers if needed ──
        if let Some(ref view) = comp.view {
            if has_trigger_kind_in_view(view) {
                w.emit("");
                emit_inview_widget_class(&mut w);
            }
            if has_trigger_kind_scroll(view) {
                w.emit("");
                emit_scroll_widget_class(&mut w);
            }
            if has_trigger_kind_drag(view) {
                w.emit("");
                emit_drag_widget_class(&mut w);
            }
        }

        w.into_string()
    }

    /// Generate a store .dart file with Riverpod providers.
    ///
    /// Each signal becomes a `StateProvider<T>`, each getter becomes a derived
    /// `Provider<dynamic>`, and each action becomes a standalone function taking
    /// `WidgetRef ref` as its first parameter.
    fn gen_store_dart(&self, name: &str, store: &StoreIR) -> String {
        let mut w = CodeWriter::new();
        w.emit_fmt(format_args!(
            "// Generated by OmniLang \u{2014} Store: {}",
            name
        ));
        w.emit("");

        if store.signals.is_empty() && store.getters.is_empty() {
            w.emit("import 'package:flutter_riverpod/flutter_riverpod.dart';");
            w.emit("");
            w.emit("// Empty store \u{2014} no signals, getters, or actions to emit");
            return w.into_string();
        }

        w.emit("import 'package:flutter_riverpod/flutter_riverpod.dart';");
        w.emit("");

        let lower = |s: &str| {
            let mut c = s.chars();
            match c.next() {
                None => String::new(),
                Some(first) => first.to_lowercase().to_string() + c.as_str(),
            }
        };
        let store_prefix = lower(name);

        // -- Signal providers --
        if !store.signals.is_empty() {
            w.emit("// \u{2014} Signal providers \u{2014}");
            for (sig_name, sig_type) in &store.signals {
                let provider_name =
                    format!("{}{}Provider", store_prefix, capitalize_first(sig_name));
                let ann = super::dart::dart_type(sig_type.kind.as_str(), &sig_type.type_args);
                let default_val = store
                    .signal_defaults
                    .get(sig_name)
                    .map(|v| format_json_value(v, &JSON_FLUTTER))
                    .unwrap_or_else(|| "null".into());
                w.emit_fmt(format_args!(
                    "final {} = StateProvider<{}>((ref) => {});",
                    provider_name, ann, default_val
                ));
            }
            w.emit("");
        }

        // -- Getter providers --
        for (getter_name, getter_expr) in &store.getters {
            let provider_name =
                format!("{}{}Provider", store_prefix, capitalize_first(getter_name));
            let body_dart = format_expr_ir_flutter(getter_expr);
            w.emit_fmt(format_args!(
                "final {} = Provider<dynamic>((ref) {{",
                provider_name
            ));
            w.indent();
            // Watch each signal and bind it to a local variable
            for sig_name in store.signals.keys() {
                let sig_provider =
                    format!("{}{}Provider", store_prefix, capitalize_first(sig_name));
                w.emit_fmt(format_args!(
                    "final {} = ref.watch({});",
                    sig_name, sig_provider
                ));
            }
            w.emit_fmt(format_args!("return {};", body_dart));
            w.dedent();
            w.emit("});");
            w.emit("");
        }

        // -- Action functions --
        if !store.actions.is_empty() {
            w.emit("// \u{2014} Action functions \u{2014}");
            for action in &store.actions {
                let action_name = format!("{}{}", store_prefix, capitalize_first(&action.name));
                let mut params: Vec<String> = vec!["WidgetRef ref".to_string()];
                for p in &action.params {
                    let ty = p
                        .r#type
                        .as_ref()
                        .map(|t| super::dart::dart_type(t.kind.as_str(), &t.type_args))
                        .unwrap_or_else(|| "dynamic".into());
                    params.push(format!("{} {}", ty, p.name));
                }
                let prefix = if action.is_async {
                    "Future<void>"
                } else {
                    "void"
                };
                w.emit_fmt(format_args!(
                    "{} {}({}) {{",
                    prefix,
                    action_name,
                    params.join(", ")
                ));
                w.indent();
                for stmt in &action.body.statements {
                    generate_store_action_stmt(&mut w, stmt, name);
                }
                w.dedent();
                w.emit("}");
                w.emit("");
            }
        }

        w.into_string()
    }
}
