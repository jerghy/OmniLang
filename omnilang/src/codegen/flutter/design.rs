// Spec §10.3 layout diagnostics — display:grid / float / cursor
// ═══════════════════════════════════════════════════════════════

/// Scan one design's classes (incl. pseudo states) and variants (base +
/// branches) for the spec §10.3 Flutter layout diagnostics:
///
/// - `display: grid` → **error** 「Flutter 不支持 CSS grid」
/// - `float` (any value) → **error** 「Flutter widget 布局无 float 概念」
/// - `cursor` (any value) → **warning** 「cursor 在 Flutter 中无效果」
///
/// Errors and warnings carry the design's source span (the block's span —
/// class properties have no finer granularity in the IR) and the design's
/// source file when known.
fn collect_layout_diagnostics(
    design: &DesignIR,
    warnings: &mut Vec<String>,
    errors: &mut Vec<Diagnostic>,
) {
    let mut check = |context: &str, prop: &str, value: &str| match css_prop_to_camel(prop).as_str()
    {
        "display" if value.trim() == "grid" => {
            errors.push(layout_diagnostic(
                design,
                Severity::Error,
                format!(
                    "[flutter][design] {context} property 'display' value 'grid': \
                         Flutter 不支持 CSS grid"
                ),
            ));
        }
        "float" => {
            errors.push(layout_diagnostic(
                design,
                Severity::Error,
                format!(
                    "[flutter][design] {context} property 'float' value '{}': \
                         Flutter widget 布局无 float 概念",
                    value.trim()
                ),
            ));
        }
        "cursor" => {
            warnings.push(format!(
                "[flutter][design] {context} property 'cursor' value '{}': \
                     cursor 在 Flutter 中无效果",
                value.trim()
            ));
        }
        _ => {}
    };
    for class in &design.classes {
        let class_ctx = format!("design class '{}'", class.name);
        for (prop, value) in &class.properties {
            check(&class_ctx, prop, value);
        }
        for pseudo in &class.pseudo_states {
            for (prop, value) in &pseudo.properties {
                check(&class_ctx, prop, value);
            }
        }
    }
    for variant in &design.variants {
        let variant_ctx = format!("variant '{}'", variant.name);
        for (prop, value) in &variant.base {
            check(&variant_ctx, prop, value);
        }
        for branch in &variant.branches {
            for (prop, value) in &branch.properties {
                check(&variant_ctx, prop, value);
            }
        }
    }
}

/// One codegen error/warning diagnostic anchored at the design block's span.
fn layout_diagnostic(design: &DesignIR, severity: Severity, message: String) -> Diagnostic {
    let (line, col) = design
        .source_span
        .map(|s| (s.line, s.col))
        .unwrap_or((0, 0));
    Diagnostic {
        severity,
        kind: DiagnosticKind::ECodegen,
        message,
        file: design.source_file.clone(),
        line,
        col,
        end_line: None,
        end_col: None,
        suggestion: None,
    }
}

