/// Emit `design.dart` — the merged design outputs for every design block in
/// the program.
///
/// Returns `(files, warnings, errors)`: an empty vec when the program declares
/// no designs; warnings carry every token/class/variant value that could not
/// be mapped onto Dart plus the spec §10.3 warning rows (ZIndex token, CSS
/// `cursor`); errors carry the spec §10.3 error rows (CSS `display: grid`,
/// CSS `float`) — unmappable design values must never be dropped silently.
pub fn gen_design_files(ir: &IRProgram) -> (Vec<CompiledFile>, Vec<String>, Vec<Diagnostic>) {
    let mut designs: Vec<&DesignIR> = ir.modules.values().flat_map(|m| &m.designs).collect();
    if designs.is_empty() {
        return (vec![], vec![], vec![]);
    }
    let mut warnings = Vec::new();
    let mut errors = Vec::new();
    // Deterministic order: designs sorted by name.
    designs.sort_by(|a, b| a.name.cmp(&b.name));
    (
        vec![CompiledFile {
            path: "design.dart".to_string(),
            content: emit_design_dart(&designs, ir, &mut warnings, &mut errors),
        }],
        warnings,
        errors,
    )
}

/// Emit the full `design.dart` content for a group of design blocks.
fn emit_design_dart(
    designs: &[&DesignIR],
    ir: &IRProgram,
    warnings: &mut Vec<String>,
    errors: &mut Vec<Diagnostic>,
) -> String {
    let mut w = CodeWriter::new();
    w.emit("// Generated by OmniLang \u{2014} Flutter design system");
    w.emit("");
    w.emit("import 'package:flutter/material.dart';");

    let has_themes = designs.iter().any(|d| !d.themes.is_empty());
    let has_dynamic_tokens = designs.iter().any(|d| {
        d.tokens
            .values()
            .any(|t| matches!(t.value, TokenValueIR::Dynamic(_)))
    });
    // Riverpod 3.0: `Provider` (dynamic token bridge) and
    // `Notifier`/`NotifierProvider` (ThemeModeNotifier) live on the plain
    // entrypoint — the legacy.dart StateProvider import is gone (Task 4.2).
    if has_themes || has_dynamic_tokens {
        w.emit("import 'package:flutter_riverpod/flutter_riverpod.dart';");
    }
    // lerpDouble is used by ThemeExtension `lerp` implementations (only when
    // a variant declares a double-typed property).
    let needs_lerp_double = designs.iter().any(|d| {
        d.variants.iter().any(|v| {
            v.base
                .iter()
                .chain(v.branches.iter().flat_map(|b| b.properties.iter()))
                .any(|(p, _)| matches!(css_prop_to_camel(p).as_str(), "borderRadius" | "fontSize"))
        })
    });
    if needs_lerp_double {
        w.emit("import 'dart:ui' show lerpDouble;");
    }
    // Store imports: stores referenced by dynamic token expressions plus the
    // @theme-marked store (Task 4.2 D1 — the ThemeModeNotifier watches it).
    let all_stores = ir.all_stores();
    let mut store_names: FxHashSet<String> = FxHashSet::default();
    if has_dynamic_tokens {
        for design in designs {
            for token in design.tokens.values() {
                if let TokenValueIR::Dynamic(expr) = &token.value {
                    collect_store_refs(expr, &all_stores, &mut store_names);
                }
            }
        }
    }
    if let Some(path) = designs.iter().find_map(|d| d.theme_signal.as_deref()) {
        if let Some((store_name, signal_name)) = path.split_once('.') {
            if all_stores
                .get(store_name)
                .is_some_and(|s| s.signals.contains_key(signal_name))
            {
                store_names.insert(store_name.to_string());
            }
        }
    }
    let mut known_stores: Vec<String> = store_names
        .iter()
        .filter(|n| all_stores.contains_key(n.as_str()))
        .cloned()
        .collect();
    known_stores.sort();
    for store in &known_stores {
        w.emit_fmt(format_args!("import './{}_store.dart';", store));
    }
    w.emit("");

    for design in designs {
        collect_layout_diagnostics(design, warnings, errors);
        emit_tokens_class(&mut w, design, warnings);
        emit_design_class(&mut w, design, warnings);
        emit_theme_variant_class(&mut w, design, warnings);
    }
    if has_themes {
        emit_theme_switch(&mut w, designs, ir, warnings);
    }
    if has_dynamic_tokens {
        emit_dynamic_token_provider(&mut w, designs, ir);
        emit_apply_dynamic_tokens(&mut w, designs);
    }
    w.into_string()
}

