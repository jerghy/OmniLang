//! Flutter design codegen: `DesignIR` → `design.dart`.
//!
//! The Flutter backend has no CSS custom-property runtime, so design blocks
//! compile to typed Dart instead of CSS:
//!
//! - `{Design}Tokens` — one `static const` per static token, typed by
//!   `TokenTypeIR` (`Color`, `double`, `Duration`, `FontWeight`, `Curve`, …),
//!   plus per-theme constants (`primaryDark`) for tokens with theme overrides.
//! - `{Design}Design` — a `BoxDecoration` factory method per design class
//!   whose properties map onto decoration fields (color, borderRadius,
//!   boxShadow, border). Layout-only properties are skipped.
//! - `{Design}ThemeVariant` — a `ThemeExtension` per design (with variants):
//!   nullable fields per mappable variant property, `copyWith` + `lerp`, and
//!   a `static const` per variant branch value (base ∪ matching branches).
//! - Theme switching — a Riverpod 3.0 `ThemeModeNotifier` +
//!   `NotifierProvider<ThemeMode>` (`themeModeProvider`) plus one
//!   `ThemeData` builder per declared theme. When a store signal is marked
//!   `@theme` (v2 D1) the notifier watches that store, and a generated
//!   `main.dart` app shell wires `MaterialApp(themeMode:)` (see
//!   `gen_theme_app_shell`). Task 3.6: designs declaring MORE than
//!   light/dark switch to a `themeDataProvider` (`Provider<ThemeData>`
//!   selecting the active builder across ALL declared themes — Flutter's
//!   native `ThemeMode` is two-state) and warn about that platform floor.
//!   Color tokens map to `ColorScheme` slots by exact token name.
//! - Dynamic tokens — a `Provider<Map<String, Object>>`
//!   (`dynamicTokensProvider`) mirroring the React `useDesignTokens()` hook:
//!   store signal values keyed by token name, plus `applyDynamicTokens`,
//!   which overrides matched `ColorScheme` slots from the provider map.
//!
//! All design blocks of a program are merged into a single `design.dart` at
//! the output root (matching the flat file layout of the Flutter backend).
//! Every generated class is namespaced by the design block name, so multiple
//! design blocks do not collide.

