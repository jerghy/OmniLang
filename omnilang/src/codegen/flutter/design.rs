/// Emit `design.dart` — the merged design outputs for every design block in
/// the program. Returns an empty vec when the program declares no designs.
pub fn gen_design_files(ir: &IRProgram) -> Vec<CompiledFile> {
    let mut designs: Vec<&DesignIR> = ir.modules.values().flat_map(|m| &m.designs).collect();
    if designs.is_empty() {
        return vec![];
    }
    // Deterministic order: designs sorted by name.
    designs.sort_by(|a, b| a.name.cmp(&b.name));
    vec![CompiledFile {
        path: "design.dart".to_string(),
        content: emit_design_dart(&designs, ir),
    }]
}

/// Emit the full `design.dart` content for a group of design blocks.
fn emit_design_dart(designs: &[&DesignIR], ir: &IRProgram) -> String {
    let mut w = CodeWriter::new();
    w.emit("// Generated by OmniLang \u{2014} Flutter design system");
    w.emit("");
    w.emit("import 'package:flutter/material.dart';");

    let has_themes = designs.iter().any(|d| !d.themes.is_empty());
    let has_dynamic_tokens = designs.iter().any(|d| {
        d.tokens
            .values()
            .any(|t| matches!(t.value, TokenValueIR::Dynamic(_)))
    });
    // StateProvider lives behind the Riverpod 3 legacy entrypoint; the plain
    // entrypoint still provides `Provider` for the dynamic token bridge.
    if has_themes {
        w.emit("import 'package:flutter_riverpod/legacy.dart';");
    }
    if has_dynamic_tokens {
        w.emit("import 'package:flutter_riverpod/flutter_riverpod.dart';");
    }
    // lerpDouble is used by ThemeExtension `lerp` implementations (only when
    // a variant declares a double-typed property).
    let needs_lerp_double = designs.iter().any(|d| {
        d.variants.iter().any(|v| {
            v.base
                .iter()
                .chain(v.branches.iter().flat_map(|b| b.properties.iter()))
                .any(|(p, _)| matches!(css_prop_to_camel(p).as_str(), "borderRadius" | "fontSize"))
        })
    });
    if needs_lerp_double {
        w.emit("import 'dart:ui' show lerpDouble;");
    }
    if has_dynamic_tokens {
        // Import the stores referenced by dynamic token expressions (only
        // stores the program actually compiles).
        let all_stores = ir.all_stores();
        let mut store_names: FxHashSet<String> = FxHashSet::default();
        for design in designs {
            for token in design.tokens.values() {
                if let TokenValueIR::Dynamic(expr) = &token.value {
                    collect_store_refs(expr, &all_stores, &mut store_names);
                }
            }
        }
        let mut known_stores: Vec<String> = store_names
            .iter()
            .filter(|n| all_stores.contains_key(n.as_str()))
            .cloned()
            .collect();
        known_stores.sort();
        for store in &known_stores {
            w.emit_fmt(format_args!("import './{}_store.dart';", store));
        }
    }
    w.emit("");

    for design in designs {
        emit_tokens_class(&mut w, design);
        emit_design_class(&mut w, design);
        emit_theme_variant_class(&mut w, design);
    }
    if has_themes {
        emit_theme_switch(&mut w, designs);
    }
    if has_dynamic_tokens {
        emit_dynamic_token_provider(&mut w, designs, ir);
        emit_apply_dynamic_tokens(&mut w, designs);
    }
    w.into_string()
}

