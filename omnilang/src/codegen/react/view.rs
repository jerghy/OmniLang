// ═══════════════════════════════════════════════════════════
// View tree generation (JSX)
// ═══════════════════════════════════════════════════════════

use std::collections::{HashMap, HashSet};

use crate::codegen::CodeWriter;
use crate::ir::*;

use super::super::capitalize_first;
use super::expr::{format_expr_ir_tsx, generate_statement_tsx};
use super::utils::{emit_event_object_react, to_jsx_attr, to_react_event, to_react_tag};

pub(super) fn gen_view_node_tsx(
    w: &mut CodeWriter,
    node: &ViewTree,
    component_map: &HashMap<String, ComponentIR>,
    signal_names: &HashSet<String>,
    motion_names: &HashSet<String>,
) {
    match node {
        ViewTree::Element(el) => {
            // Fragment tag -> React fragment shorthand
            if el.tag == "fragment" {
                if el.children.is_empty() {
                    return;
                }
                for child in &el.children {
                    gen_view_node_tsx(w, child, component_map, signal_names, motion_names);
                }
                return;
            }

            // Component composition: check if tag is a known component
            if let Some(_child_comp) = component_map.get(&el.tag) {
                let mut comp_attrs: Vec<String> = Vec::new();
                for (prop_name, prop_value) in &el.props {
                    let js_val = format_expr_ir_tsx(prop_value);
                    comp_attrs.push(format!("{}={{{}}}", prop_name, js_val));
                }
                for (event_name, handler) in &el.events {
                    let jsx_event = to_react_event(event_name);
                    match handler.kind {
                        EventHandlerKind::FnRef => {
                            if let Some(ref fn_name) = handler.r#ref {
                                comp_attrs.push(format!("{}={{{}}}", jsx_event, fn_name));
                            }
                        }
                        EventHandlerKind::InlineFn => {
                            if let Some(ref body) = handler.body {
                                let handler_str =
                                    format_inline_handler(body, signal_names, &handler.params);
                                comp_attrs.push(format!("{}={{{}}}", jsx_event, handler_str));
                            }
                        }
                        EventHandlerKind::StoreAction => {
                            if let Some(ref action) = handler.r#ref {
                                let action_fn = action.split('.').next_back().unwrap_or(action);
                                comp_attrs.push(format!(
                                    "{}={{() => {{ {}(); }}}}",
                                    jsx_event, action_fn
                                ));
                            }
                        }
                    }
                }
                let attrs_str = comp_attrs.join(" ");
                if el.children.is_empty() {
                    w.emit_fmt(format_args!("<{} {}/>", el.tag, attrs_str));
                } else {
                    w.emit_fmt(format_args!("<{} {}>", el.tag, attrs_str));
                    w.indent();
                    for child in &el.children {
                        gen_view_node_tsx(w, child, component_map, signal_names, motion_names);
                    }
                    w.dedent();
                    w.emit_fmt(format_args!("</{}>", el.tag));
                }
                return; // IMPORTANT: skip HTML element handling
            }
            // Otherwise, fall through to existing HTML element handling
            // Normalize OmniView custom tags (Button→button, Card→div, etc.)
            let html_tag = to_react_tag(&el.tag);
            // Build attribute list from props, bindings, events
            let mut attrs: Vec<String> = Vec::new();

            // Collect binding attr names for dedup with static props
            let bound_attr_names: HashSet<String> = el
                .bindings
                .keys()
                .map(|bind_name| to_jsx_attr(bind_name))
                .collect();

            // Collect class_map_binding names so we can exclude them from static className
            let binding_names: std::collections::HashSet<&str> = el
                .class_map_bindings
                .keys()
                .map(|cls| cls.as_str())
                .collect();

            // Static props — skip names that will be populated by bindings
            for (prop_name, prop_value) in &el.props {
                let jsx_attr = to_jsx_attr(prop_name);
                // Skip if this attr name will be generated by a binding (e.g., value= vs bind:value)
                if bound_attr_names.contains(&jsx_attr) {
                    continue;
                }
                match prop_value {
                    ExprIR::LiteralExpr { value } if value.is_string() => {
                        let s = value
                            .as_str()
                            .unwrap_or_default(); // defense-in-depth fallback
                        // Use CSS module syntax for className props
                        if jsx_attr == "className" {
                            // Split multi-class names: "browserTab tabActive" → styles['browserTab'] + ' ' + styles['tabActive']
                            // Exclude class names that are handled by class_map_bindings
                            let classes: Vec<&str> = s
                                .split_whitespace()
                                .filter(|c| !binding_names.contains(c))
                                .collect();
                            if classes.is_empty() {
                                // All classes are handled by bindings — skip static className
                            } else if classes.len() > 1 {
                                let parts: Vec<String> =
                                    classes.iter().map(|c| format!("styles['{}']", c)).collect();
                                attrs.push(format!("className={{{}}}", parts.join(" + ' ' + ")));
                            } else {
                                attrs.push(format!("className={{styles['{}']}}", classes[0]));
                            }
                        } else {
                            let escaped = s.replace('\\', "\\\\").replace('"', "\\\"");
                            attrs.push(format!("{}=\"{}\"", jsx_attr, escaped));
                        }
                    }
                    _ => {
                        let jsx_val = format_expr_ir_tsx(prop_value);
                        attrs.push(format!("{}={{{}}}", jsx_attr, jsx_val));
                    }
                }
            }

            // Two-way bindings: value={x}, collect binding event setters for dedup with user events
            let mut binding_events_map: HashMap<String, String> = HashMap::new();
            for (bind_name, signal_ref) in &el.bindings {
                let jsx_attr = to_jsx_attr(bind_name);
                let setter = format!("set{}", capitalize_first(&signal_ref.name));
                attrs.push(format!("{}={{{}}}", jsx_attr, signal_ref.name));
                match bind_name.as_str() {
                    "value" => {
                        binding_events_map.insert(
                            "onChange".to_string(),
                            format!("{}(e.target.value)", setter),
                        );
                    }
                    "checked" => {
                        binding_events_map.insert(
                            "onChange".to_string(),
                            format!("{}(e.target.checked)", setter),
                        );
                    }
                    _ => {}
                }
            }

            // Motion triggers — add data-motion-enter for @enter effects, inline handlers for interactive
            for trigger in &el.motion_triggers {
                match trigger.kind {
                    TriggerKind::Enter => {
                        attrs.push("data-motion-enter=\"true\"".into());
                        if let Some(ref motion_name) = trigger.motion_ref {
                            attrs.push(format!("data-motion-name=\"{}\"", motion_name));
                        }
                    }
                    TriggerKind::Hover => {
                        attrs.push("onMouseEnter={(e) => { e.currentTarget.animate([{ opacity: 0 }, { opacity: 1 }], { duration: 300, easing: 'ease-out' }); }}".into());
                        attrs.push("onMouseLeave={(e) => { e.currentTarget.animate([{ opacity: 1 }, { opacity: 0 }], { duration: 300, easing: 'ease-out' }); }}".into());
                    }
                    TriggerKind::Press => {
                        attrs.push("onMouseDown={(e) => { e.currentTarget.animate([{ scale: 1 }, { scale: 0.95 }], { duration: 150, easing: 'ease-out', fill: 'both' }); }}".into());
                        attrs.push("onMouseUp={(e) => { e.currentTarget.animate([{ scale: 0.95 }, { scale: 1 }], { duration: 150, easing: 'ease-out', fill: 'both' }); }}".into());
                    }
                    TriggerKind::Focus => {
                        attrs.push("onFocus={(e) => { e.currentTarget.animate([{ boxShadow: '0 0 0 0 rgba(59,130,246,0)' }, { boxShadow: '0 0 0 3px rgba(59,130,246,0.5)' }], { duration: 200, easing: 'ease-out', fill: 'both' }); }}".into());
                        attrs.push("onBlur={(e) => { e.currentTarget.animate([{ boxShadow: '0 0 0 3px rgba(59,130,246,0.5)' }, { boxShadow: '0 0 0 0 rgba(59,130,246,0)' }], { duration: 200, easing: 'ease-out', fill: 'both' }); }}".into());
                    }
                    TriggerKind::InView => {
                        let threshold_val = match &el.in_view_threshold {
                            Some(expr) => format_expr_ir_tsx(expr),
                            None => "0".to_string(),
                        };
                        attrs.push("data-motion-inview=\"true\"".into());
                        attrs.push(format!("data-inview-threshold=\"{}\"", threshold_val));
                    }
                    TriggerKind::Scroll => {
                        let scroll_start_str = el.scroll_start.as_deref().unwrap_or("top 80%");
                        let scroll_end_str = el.scroll_end.as_deref().unwrap_or("bottom 20%");
                        let scrub_val = match &el.scroll_scrub {
                            Some(expr) => format_expr_ir_tsx(expr),
                            None => "0".to_string(),
                        };
                        attrs.push("data-motion-scroll=\"true\"".into());
                        attrs.push(format!("data-scroll-start=\"{}\"", scroll_start_str));
                        attrs.push(format!("data-scroll-end=\"{}\"", scroll_end_str));
                        attrs.push(format!("data-scroll-scrub=\"{}\"", scrub_val));
                    }
                    TriggerKind::DragHorizontal | TriggerKind::DragVertical => {
                        let is_horizontal = matches!(trigger.kind, TriggerKind::DragHorizontal);
                        let axis_str = if is_horizontal { "x" } else { "y" };
                        let constraints_str = el.drag_constraints.as_deref().unwrap_or("");
                        let elastic_val = match &el.drag_elastic {
                            Some(expr) => format_expr_ir_tsx(expr),
                            None => "0".to_string(),
                        };
                        let threshold_val = match &el.drag_threshold {
                            Some(expr) => format_expr_ir_tsx(expr),
                            None => "0".to_string(),
                        };
                        let velocity_max_val = match &el.drag_velocity_max {
                            Some(expr) => format_expr_ir_tsx(expr),
                            None => "2000".to_string(),
                        };
                        attrs.push(format!("data-motion-drag=\"{}\"", axis_str));
                        attrs.push(format!("data-drag-constraints=\"{}\"", constraints_str));
                        attrs.push(format!("data-drag-elastic=\"{}\"", elastic_val));
                        attrs.push(format!("data-drag-threshold=\"{}\"", threshold_val));
                        attrs.push(format!("data-drag-velocity-max=\"{}\"", velocity_max_val));
                    }
                    _ => {}
                }
            }

            // @driven-by — external progress control marker attribute
            if let Some(ref driven_expr) = el.driven_by {
                let driven_js = format_expr_ir_tsx(driven_expr);
                attrs.push(format!("data-driven-by={{{}}}", driven_js));
            }

            // Events — with dedup for binding conflicts and motion name filtering
            for (event_name, handler) in &el.events {
                let react_event = to_react_event(event_name);
                match handler.kind {
                    EventHandlerKind::FnRef => {
                        if let Some(ref fn_name) = handler.r#ref {
                            // Skip motion names — they're animation references, not functions
                            if motion_names.contains(fn_name.as_str()) {
                                continue;
                            }
                            if let Some(setter_call) = binding_events_map.remove(&react_event) {
                                if handler.event_data.is_some() {
                                    let event_obj = emit_event_object_react(
                                        &handler.event_data,
                                        &handler.used_fields,
                                        "e",
                                    );
                                    attrs.push(format!(
                                        "{}={{(e) => {{ {}; {}({}); }}}}",
                                        react_event, setter_call, fn_name, event_obj
                                    ));
                                } else {
                                    attrs.push(format!(
                                        "{}={{(e) => {{ {}; {}(e); }}}}",
                                        react_event, setter_call, fn_name
                                    ));
                                }
                            } else if handler.event_data.is_some() {
                                let event_obj = emit_event_object_react(
                                    &handler.event_data,
                                    &handler.used_fields,
                                    "e",
                                );
                                attrs.push(format!(
                                    "{}={{(e) => {{ {}({}) }}}}",
                                    react_event, fn_name, event_obj
                                ));
                            } else {
                                attrs.push(format!("{}={{{}}}", react_event, fn_name));
                            }
                        }
                    }
                    EventHandlerKind::InlineFn => {
                        if let Some(ref body) = handler.body {
                            if let Some(setter_call) = binding_events_map.remove(&react_event) {
                                // Generate body with binding setter prepended
                                let mut merged_hw = CodeWriter::new();
                                merged_hw.emit_fmt(format_args!("{};", setter_call));
                                for stmt in &body.statements {
                                    generate_statement_tsx(&mut merged_hw, stmt, signal_names);
                                }
                                let content = merged_hw.into_string();
                                let params_str = if handler.params.is_empty() {
                                    "e".to_string()
                                } else {
                                    handler.params.join(", ")
                                };
                                let mut result = format!("({}) => {{\n", params_str);
                                for line in content.lines() {
                                    result.push_str(&format!("        {}\n", line));
                                }
                                result.push_str("      }");
                                attrs.push(format!("{}={{{}}}", react_event, result));
                            } else {
                                let handler_str =
                                    format_inline_handler(body, signal_names, &handler.params);
                                attrs.push(format!("{}={{{}}}", react_event, handler_str));
                            }
                        }
                    }
                    EventHandlerKind::StoreAction => {
                        if let Some(ref action) = handler.r#ref {
                            let action_fn = action.split('.').next_back().unwrap_or(action);
                            if let Some(setter_call) = binding_events_map.remove(&react_event) {
                                attrs.push(format!(
                                    "{}={{(e) => {{ {}; {}(); }}}}",
                                    react_event, setter_call, action_fn
                                ));
                            } else {
                                attrs.push(format!(
                                    "{react_event}={{() => {{ {action_fn}(); }}}}",
                                    react_event = react_event,
                                    action_fn = action_fn
                                ));
                            }
                        }
                    }
                }
            }

            // Add remaining binding events that weren't merged with user events
            for (event_name, setter_call) in &binding_events_map {
                attrs.push(format!("{}={{(e) => {{ {}; }}}}", event_name, setter_call));
            }

            // Style classes from view
            if let Some(ref classes) = el.style_classes {
                if let Some(classes_str) = classes.as_str() {
                    let class_parts: Vec<&str> = classes_str.split_whitespace().collect();
                    if class_parts.len() > 1 {
                        let parts: Vec<String> = class_parts
                            .iter()
                            .map(|c| format!("styles['{}']", c))
                            .collect();
                        attrs.push(format!("className={{{}}}", parts.join(" + ' ' + ")));
                    } else {
                        attrs.push(format!("className={{styles['{}']}}", classes_str));
                    }
                }
            }

            // Inline style
            if let Some(ref style_json) = el.inline_style {
                if let Some(obj) = style_json.as_object() {
                    let mut pairs: Vec<String> = Vec::new();
                    for (prop, val) in obj {
                        let js_prop = format_style_prop_key(prop);
                        let js_val = format_style_value_expr(val);
                        pairs.push(format!("{}: {}", js_prop, js_val));
                    }
                    if !pairs.is_empty() {
                        attrs.push(format!("style={{{{ {} }}}}", pairs.join(", ")));
                    }
                }
            }

            // Dynamic class bindings: class:active={isOpen} → className using CSS module syntax
            if !el.class_map_bindings.is_empty() {
                let mut static_classes: Vec<String> = Vec::new();
                let mut dynamic_parts: Vec<String> = Vec::new();
                for (cls, expr) in &el.class_map_bindings {
                    match expr {
                        ExprIR::LiteralExpr { value } if value.as_bool() == Some(true) => {
                            static_classes.push(format!("styles['{}']", cls));
                        }
                        ExprIR::LiteralExpr { value } if value.as_bool() == Some(false) => {
                            // skip — class not applied
                        }
                        _ => {
                            let cond = format_expr_ir_tsx(expr);
                            dynamic_parts.push(format!("${{{cond} ? styles['{cls}'] : ''}}"));
                        }
                    }
                }
                // Merge into existing className attribute, or create a new one
                let mut new_class = String::new();
                if !static_classes.is_empty() {
                    new_class = static_classes.join(" + ' ' + ");
                }
                if !dynamic_parts.is_empty() {
                    if !new_class.is_empty() {
                        new_class =
                            format!("({}) + ' ' + `{}`", new_class, dynamic_parts.join(" "));
                    } else {
                        new_class = format!("`{}`", dynamic_parts.join(" "));
                    }
                }
                if !new_class.is_empty() {
                    if let Some(pos) = attrs.iter().position(|a| a.starts_with("className=")) {
                        // Merge: prepend the pre-existing static class name if it exists
                        let old = &attrs[pos];
                        // Extract the value from existing className={...}
                        if let Some(inner) = old.strip_prefix("className={") {
                            if let Some(existing) = inner.strip_suffix("}") {
                                // Prepend existing static class to the new_class
                                let merged = if !static_classes.is_empty() {
                                    // class_map_bindings already provided static classes
                                    format!("{existing} + ' ' + ({new_class})")
                                } else {
                                    // Static class from props + dynamic from bindings
                                    format!("{existing} + ' ' + {new_class}")
                                };
                                attrs[pos] = format!("className={{{merged}}}");
                            } else {
                                attrs[pos] = format!("className={{{new_class}}}");
                            }
                        } else {
                            attrs[pos] = format!("className={{{new_class}}}");
                        }
                    } else {
                        attrs.push(format!("className={{{}}}", new_class));
                    }
                }
            }

            // Emit opening tag
            if attrs.is_empty() && el.children.is_empty() {
                // Self-closing tag
                w.emit_fmt(format_args!("<{} />", html_tag));
                return;
            }

            if attrs.is_empty() {
                w.emit_fmt(format_args!("<{}>", html_tag));
            } else {
                w.emit_fmt(format_args!("<{}", html_tag));
                w.indent();
                for attr in &attrs {
                    w.emit(&attr.to_string());
                }
                if el.children.is_empty() {
                    w.dedent();
                    w.emit("/>");
                    return;
                }
                w.dedent();
                w.emit(">");
            }

            // Children
            w.indent();
            for child in &el.children {
                gen_view_node_tsx(w, child, component_map, signal_names, motion_names);
            }
            w.dedent();

            // Closing tag
            w.emit_fmt(format_args!("</{}>", html_tag));
        }
        ViewTree::Conditional(cond) => {
            let branches = &cond.branches;
            let fallback = &cond.fallback;

            if branches.is_empty() {
                if let Some(ref fb) = fallback {
                    gen_view_node_tsx(w, fb, component_map, signal_names, motion_names);
                }
                return;
            }

            // Single branch without fallback → {condition && (...)}
            if branches.len() == 1 && fallback.is_none() {
                w.emit("{");
                w.indent();
                let cond_str = format_expr_ir_tsx(&branches[0].condition);
                w.emit_fmt(format_args!("{} && (", cond_str));
                w.indent();
                if let Some(ref body) = branches[0].body {
                    gen_view_node_tsx(w, body, component_map, signal_names, motion_names);
                }
                w.dedent();
                w.emit(")");
                w.dedent();
                w.emit("}");
                return;
            }

            // Multiple branches or fallback → nested ternary
            // Clean structure: each branch closes `? (` before the next `: (`
            // Remaining `: (` from branches 1..N get closed after fallback/null.
            w.emit("{");
            w.indent();

            if let Some((first_branch, rest)) = branches.split_first() {
                // First branch: `cond ? ( body )`
                let cond_str = format_expr_ir_tsx(&first_branch.condition);
                w.emit_fmt(format_args!("{} ? (", cond_str));
                w.indent();
                if let Some(ref body) = first_branch.body {
                    gen_view_node_tsx(w, body, component_map, signal_names, motion_names);
                }
                w.dedent();

                // Remaining branches: `) : ( cond ? ( body )`
                for branch in rest {
                    w.emit(") : (");
                    w.indent();
                    let cond_str = format_expr_ir_tsx(&branch.condition);
                    w.emit_fmt(format_args!("{} ? (", cond_str));
                    w.indent();
                    if let Some(ref body) = branch.body {
                        gen_view_node_tsx(w, body, component_map, signal_names, motion_names);
                    }
                    w.dedent();
                }

                // Fallback or null
                if let Some(ref fb) = fallback {
                    w.emit(") : (");
                    w.indent();
                    gen_view_node_tsx(w, fb, component_map, signal_names, motion_names);
                    w.dedent();
                    w.emit(")");
                } else {
                    w.emit(") : null");
                }
                // Close each `: (` from rest branches
                for _ in 0..rest.len() {
                    w.emit(")");
                }
            } else if let Some(ref fb) = fallback {
                // No branches, just fallback
                gen_view_node_tsx(w, fb, component_map, signal_names, motion_names);
            }

            w.dedent();
            w.emit("}");
        }
        ViewTree::ListRendering(list) => {
            let iterable_str = format_expr_ir_tsx(&list.iterable);
            let item_name = &list.item_binding.name;
            let key_attr = if let Some(ref ke) = list.key_expr {
                format!(" key={{{}}}", format_expr_ir_tsx(ke))
            } else {
                " key={index}".to_string()
            };
            if list.empty_body.is_some() {
                w.emit("{");
                w.indent();
                w.emit_fmt(format_args!(
                    "({} && {}.length === 0) ? (",
                    iterable_str, iterable_str
                ));
                w.indent();
                if let Some(ref empty_body) = list.empty_body {
                    gen_view_node_tsx(w, empty_body, component_map, signal_names, motion_names);
                }
                w.dedent();
                w.emit_fmt(format_args!(
                    ") : ({}.map(({}, index) => (",
                    iterable_str, item_name
                ));
            } else {
                w.emit("{");
                w.indent();
                w.emit_fmt(format_args!(
                    "{}.map(({}, index) => (",
                    iterable_str, item_name
                ));
            }
            w.indent();
            w.emit_fmt(format_args!("<React.Fragment{}>", key_attr));
            w.indent();
            if let Some(ref body) = list.body {
                gen_view_node_tsx(w, body, component_map, signal_names, motion_names);
            }
            w.dedent();
            w.emit("</React.Fragment>");
            w.dedent();
            w.emit("))");
            w.dedent();
            if list.empty_body.is_some() {
                w.emit(")}");
            } else {
                w.emit("}");
            }
        }
        ViewTree::Text(text) => {
            // Skip empty text nodes and text containing only syntax artifacts from IR lowering
            let text_trimmed = text.trim();
            if text_trimmed.is_empty()
                || text_trimmed
                    .chars()
                    .all(|c| c.is_ascii_punctuation() || c.is_ascii_whitespace())
            {
                return;
            }
            if text.starts_with('{') && text.ends_with('}') {
                // Interpolation expression like {name} or {param:xxx}
                let inner = &text[1..text.len() - 1];
                w.emit_fmt(format_args!("{{{}}}", inner));
            } else {
                // Plain text — escape JSX-significant characters
                let escaped = text
                    .replace('\\', "\\\\")
                    .replace('\'', "\\'")
                    .replace('<', "&lt;")
                    .replace('>', "&gt;")
                    .replace('&', "&amp;");
                w.emit_fmt(format_args!("{{'{}'}}", escaped));
            }
        }
        ViewTree::Interpolation(expr) => {
            let js_expr = format_expr_ir_tsx(expr);
            w.emit_fmt(format_args!("{{{}}}", js_expr));
        }
        ViewTree::Slot(_) => {
            // slots not supported in React — emit placeholder
        }
    }
}

/// Format a CSS property key for use in a JSX style object.
/// Quotes the key if it starts with `--` (custom property) or contains hyphens.
pub(crate) fn format_style_prop_key(key: &str) -> String {
    if key.starts_with("--") || key.contains('-') {
        format!("'{}'", key)
    } else {
        key.to_string()
    }
}

/// Translate an inline style value from the IR JSON representation into a TSX expression.
/// Handles $signal, $call, and $concat meta-objects.
pub(crate) fn format_style_value_expr(val: &serde_json::Value) -> String {
    match val {
        // Static string: 'value'
        serde_json::Value::String(s) => format!("'{}'", s),
        // Static number: 42 (with px suffix for numbers)
        serde_json::Value::Number(n) => {
            if let Some(f) = n.as_f64() {
                format!("{}", f)
            } else {
                format!("{}", n)
            }
        }
        // $signal: { "$signal": "name" } -> accentColor (bare identifier, no braces)
        // $call:   { "$call": { "name": "fnName", "args": [...] } } -> fnName(arg1, arg2)
        // $concat: { "$concat": [part1, part2, ...] } -> `part1${part2}`
        serde_json::Value::Object(obj) => {
            if let Some(sig_name) = obj.get("$signal").and_then(|v| v.as_str()) {
                return sig_name.to_string();
            }
            // $call
            if let Some(call_obj) = obj.get("$call").and_then(|v| v.as_object()) {
                let fn_name = call_obj.get("name").and_then(|v| v.as_str()).unwrap_or("");
                let args_str = if let Some(args) = call_obj.get("args").and_then(|v| v.as_array()) {
                    let translated: Vec<String> =
                        args.iter().map(format_style_value_expr).collect();
                    translated.join(", ")
                } else {
                    String::new()
                };
                return format!("{}({})", fn_name, args_str);
            }
            // $concat
            if let Some(parts) = obj.get("$concat").and_then(|v| v.as_array()) {
                let mut template_parts: Vec<String> = Vec::new();
                for part in parts {
                    match part {
                        serde_json::Value::String(s) => {
                            let escaped = s
                                .replace('\\', "\\\\")
                                .replace('`', "\\`")
                                .replace("${", "\\${");
                            template_parts.push(escaped);
                        }
                        _ => {
                            // Dynamic part — resolve to expression and wrap in ${...}
                            let inner = format_style_value_expr(part);
                            template_parts.push(format!("${{{}}}", inner));
                        }
                    }
                }
                return format!("`{}`", template_parts.join(""));
            }
            // Unknown object — emit as-is by serializing
            serde_json::to_string(val).unwrap_or_default()
        }
        // Boolean, null
        serde_json::Value::Bool(b) => b.to_string(),
        serde_json::Value::Null => "null".into(),
        // Array (unlikely in style context)
        serde_json::Value::Array(arr) => {
            let items: Vec<_> = arr.iter().map(format_style_value_expr).collect();
            format!("[{}]", items.join(", "))
        }
    }
}

/// Build an inline arrow function string from a BlockIR.
/// Uses the declared params from the Omni source (e.g., `(text)` or `(e)`) instead of hardcoding `e`,
/// so that the handler body which references the parameter by name works correctly.
fn format_inline_handler(
    body: &BlockIR,
    signal_names: &HashSet<String>,
    params: &[String],
) -> String {
    let params_str = if params.is_empty() {
        "e".to_string()
    } else {
        params.join(", ")
    };
    if body.statements.is_empty() {
        return format!("({}) => {{}}", params_str);
    }
    let mut hw = CodeWriter::new();
    for stmt in &body.statements {
        generate_statement_tsx(&mut hw, stmt, signal_names);
    }
    let content = hw.into_string();
    // Build a multi-line arrow function
    let mut result = format!("({}) => {{\n", params_str);
    for line in content.lines() {
        result.push_str(&format!("        {}\n", line));
    }
    result.push_str("      }");
    result
}
