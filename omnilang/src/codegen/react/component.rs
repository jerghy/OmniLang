// ═══════════════════════════════════════════════════════════
// Component codegen: .tsx + .module.css generation
// ═══════════════════════════════════════════════════════════

use super::{escape_js_ident, CodeWriter, ReactCodegen};
use super::{expr, motion, utils, view};
use crate::codegen::capitalize_first;
use crate::codegen::shared::types::{FormatType, JsTypeFormatter};
use crate::ir::*;
use rustc_hash::FxHashMap;
use rustc_hash::FxHashSet;

impl ReactCodegen {
    /// Generate a React functional component .tsx file.
    pub(super) fn gen_component_tsx(
        &self,
        name: &str,
        comp: &ComponentIR,
        ir: &IRProgram,
        component_map: &FxHashMap<String, ComponentIR>,
    ) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang — React target");
        w.emit("");

        // Determine which React hooks are actually needed
        let has_computeds = !comp.computeds.is_empty();
        let has_fn_form_computed = comp.computeds.iter().any(|c| {
            matches!(&c.body, ExprIR::BlockExpr { statements, .. }
                if statements.iter().any(|s| matches!(s, StatementIR::ReturnStmtIR { .. })))
        });
        let has_effects_or_lifecycles = !comp.effects.is_empty() || !comp.lifecycles.is_empty();
        let has_motion = comp.view.as_ref().is_some_and(|v| view_has_motion_or_effects(v));

        // Scan all code paths for signal mutations and function calls
        // Compute called_fns first — mutations only tracked for called functions
        let called_fns = collect_called_local_fns(comp);
        let mutated_signals = collect_signal_mutations(comp, &called_fns);

        // Build comprehensive read-signals set: signals referenced in view, computeds,
        // effects, lifecycles, and called local functions. States not read anywhere
        // are skipped to avoid unused-variable warnings.
        let mut read_signals = comp.view.as_ref()
            .map(|v| collect_view_read_signals(v))
            .unwrap_or_default();
        for computed in &comp.computeds {
            collect_expr_identifiers(&computed.body, &mut read_signals);
        }
        for effect in &comp.effects {
            for stmt in &effect.body.statements {
                collect_stmt_identifiers(stmt, &mut read_signals);
            }
        }
        for lc in &comp.lifecycles {
            for stmt in &lc.body.statements {
                collect_stmt_identifiers(stmt, &mut read_signals);
            }
        }
        for fun in &comp.fns {
            if called_fns.contains(&fun.name) {
                for stmt in &fun.body.statements {
                    collect_stmt_identifiers(stmt, &mut read_signals);
                }
            }
        }
        // Also scan inline event handler bodies in the view tree
        if let Some(ref view) = comp.view {
            collect_view_inline_handler_reads(view, &mut read_signals);
        }

        // Determine if any state actually needs useState (has active setter)
        let has_mutable_states = comp.states.iter().any(|s| {
            read_signals.contains(&s.name) && mutated_signals.contains(&s.name)
        });
        let mut hooks: Vec<&str> = Vec::new();
        if has_mutable_states { hooks.push("useState"); }
        if has_computeds { hooks.push("useMemo"); }
        if has_fn_form_computed { hooks.push("useCallback"); }
        if has_effects_or_lifecycles || has_motion { hooks.push("useEffect"); }

        // Imports
        if !hooks.is_empty() {
            w.emit_fmt(format_args!("import React, {{ {} }} from 'react';", hooks.join(", ")));
        }
        // Only import styles if the component has style rules AND at least one
        // CSS class is actually referenced in the view via class: or classMap:
        let used_style_classes = comp.view.as_ref()
            .map(|v| collect_used_style_classes(v))
            .unwrap_or_default();
        let has_styles = !comp.styles.is_empty() && used_style_classes.iter()
            .any(|c| comp.styles.iter().any(|s| &s.class_name == c));
        if has_styles {
            w.emit_fmt(format_args!("import styles from './{}.module.css';", name));
        }
        if !hooks.is_empty() || has_styles {
            w.emit("");
        }

        // Props interface — regular props + event callbacks
        let has_props = !comp.props.is_empty() || !comp.event_names.is_empty();
        if has_props {
            w.emit_fmt(format_args!("interface {}Props {{", name));
            for (prop_name, prop_type) in &comp.props {
                let ts_type =
                    JsTypeFormatter.format_type(prop_type.kind.as_str(), &prop_type.type_args);
                let optional = if comp.prop_defaults.contains_key(prop_name) {
                    "?"
                } else {
                    ""
                };
                w.emit_fmt(format_args!("  {}{}: {};", prop_name, optional, ts_type));
            }
            for event_name in &comp.event_names {
                w.emit_fmt(format_args!("  {}?: (value: any) => void;", event_name));
            }
            w.emit("}");
            w.emit("");
        }

        // Store hook imports — use relative paths based on source directories.
        // Only import stores whose signals are actually referenced in the component.
        let all_stores = ir.all_stores();
        let used_store_signals = collect_used_store_signals(comp);

        // Build set of local names (component states + props) that may shadow store signal names.
        // This prevents confusing a component prop `items` with a store signal `items`.
        let local_names: FxHashSet<String> = comp.states.iter().map(|s| s.name.clone())
            .chain(comp.props.keys().cloned())
            .chain(comp.fns.iter().map(|f| f.name.clone()))
            .collect();

        let mut used_store_refs: FxHashSet<String> = FxHashSet::default();
        for store_ref in &comp.store_refs {
            // Include store if: its ref name is referenced (e.g. `NotificationStore.clear`),
            // or any of its signals are referenced and NOT shadowed by local names
            if used_store_signals.contains(store_ref.as_str()) {
                used_store_refs.insert(store_ref.clone());
                continue;
            }
            if let Some(store) = all_stores.get(store_ref.as_str()) {
                for sig_name in store.signals.keys() {
                    if !local_names.contains(sig_name) && used_store_signals.contains(sig_name) {
                        used_store_refs.insert(store_ref.clone());
                        break;
                    }
                }
            }
        }

        let mut store_hook_imports = Vec::new();
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            if let Some(store) = all_stores.get(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                let module_name = format!("use{}", store_ref);
                let import_path = super::relative_import_path(
                    comp.source_file.as_deref(),
                    store.source_file.as_deref(),
                    &module_name,
                );
                store_hook_imports.push(format!("import {{ {} }} from '{}';", hook_name, import_path));
            }
        }
        for import_line in &store_hook_imports {
            w.emit(import_line);
        }

        // Build set of all signal names (component state + store signals + computeds)
        // so mutations use setter calls instead of direct assignment.
        let mut signal_names: FxHashSet<String> =
            comp.states.iter().map(|s| s.name.clone()).collect();
        // Also include store-ref aliases + their signal names
        // Build a map from bare store signal name → qualified StoreName.signalName
        let mut store_signal_map: FxHashMap<String, String> = FxHashMap::default();
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            signal_names.insert(store_ref.clone());
            if let Some(store) = ir.all_stores().get(store_ref.as_str()) {
                for sig_name in store.signals.keys() {
                    signal_names.insert(sig_name.clone());
                    store_signal_map
                        .insert(sig_name.clone(), format!("{}.{}", store_ref, sig_name));
                }
            }
        }

        // Motion animation names — used to filter motion refs from event handlers
        // Include both component-level and module-level motions
        let mut motion_names: FxHashSet<String> =
            comp.motions.iter().map(|m| m.name.clone()).collect();
        for module in ir.modules.values() {
            for motion in &module.motions {
                motion_names.insert(motion.name.clone());
            }
        }

        // Child component imports
        let child_comps: FxHashSet<String> = if let Some(ref view) = comp.view {
            collect_view_child_components(view, component_map)
        } else {
            FxHashSet::default()
        };
        let mut child_comp_names: Vec<&String> = child_comps.iter().collect();
        child_comp_names.sort();
        for child_name in &child_comp_names {
            let child_source = component_map
                .get(child_name.as_str())
                .and_then(|c| c.source_file.as_deref());
            let import_path = super::relative_import_path(
                comp.source_file.as_deref(),
                child_source,
                child_name,
            );
            w.emit_fmt(format_args!(
                "import {{ {} }} from '{}';",
                child_name, import_path
            ));
        }

        if !store_hook_imports.is_empty() || !child_comps.is_empty() {
            w.emit("");
        }

        // Collect all identifier references from the component to determine
        // which library functions are actually needed.
        let mut used_fn_names: FxHashSet<String> = FxHashSet::default();
        // From computeds
        for computed in &comp.computeds {
            collect_expr_identifiers(&computed.body, &mut used_fn_names);
        }
        // From effects
        for effect in &comp.effects {
            for stmt in &effect.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        // From lifecycles
        for lc in &comp.lifecycles {
            for stmt in &lc.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        // From component fns
        for fun in &comp.fns {
            for stmt in &fun.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        // From view tree
        if let Some(ref view) = comp.view {
            collect_view_identifiers(view, &mut used_fn_names);
        }
        // From motion triggers (they may reference lib fns)
        if let Some(ref view) = comp.view {
            collect_motion_identifiers(view, &mut used_fn_names);
        }

        // Library-level functions (pub fn from lib.omni, etc.)
        // Only emit functions that are actually referenced by the component.
        let all_lib_fns: Vec<&FunctionIR> = ir.all_functions();
        let lib_fns: Vec<&&FunctionIR> = all_lib_fns
            .iter()
            .filter(|f| used_fn_names.contains(&f.name))
            .collect();
        for fun in &lib_fns {
            // Build param renames for JS reserved words
            let param_names: Vec<(String, bool)> = fun
                .params
                .iter()
                .map(|p| {
                    let escaped = escape_js_ident(&p.name);
                    let needs_rename = escaped != p.name;
                    (escaped, needs_rename)
                })
                .collect();
            let param_escaped: Vec<&str> = param_names.iter().map(|(n, _)| n.as_str()).collect();
            let params_str = param_escaped.join(", ");
            let is_async = fun.is_async || fun.body.statements.iter().any(stmt_contains_await);
            let async_prefix = if is_async { "async " } else { "" };
            w.emit_fmt(format_args!(
                "const {} = {}({}) => {{",
                fun.name, async_prefix, params_str
            ));
            w.indent();
            // Emit body into a temp writer for post-processing
            let mut body_w = crate::codegen::CodeWriter::new();
            body_w.indent();
            for stmt in &fun.body.statements {
                expr::generate_statement_tsx_with_mode(&mut body_w, stmt, &FxHashSet::default(), self.store_mode);
            }
            let mut body_str = body_w.into_string();
            // Rename reserved word identifiers in the body
            for (i, (new_name, needs_rename)) in param_names.iter().enumerate() {
                if *needs_rename {
                    let old_name = &fun.params[i].name;
                    body_str = body_str.replace(old_name, new_name);
                }
            }
            // Emit the already-indented body lines
            for line in body_str.lines() {
                w.emit(line);
            }
            w.dedent();
            w.emit("};");
        }
        if !lib_fns.is_empty() {
            w.emit("");
        }

        // Component function signature
        if !has_props {
            w.emit_fmt(format_args!("export function {}() {{", name));
        } else {
            let mut prop_list: Vec<String> = comp
                .props
                .keys()
                .map(|prop_name| {
                    if let Some(default_val) = comp.prop_defaults.get(prop_name) {
                        let default_tsx = expr::format_expr_ir_tsx(default_val);
                        format!("{} = {}", prop_name, default_tsx)
                    } else {
                        prop_name.clone()
                    }
                })
                .collect();
            // Include event callbacks as destructured props — only for
            // events that are actually called as functions (not emitted via `emit`).
            for event_name in &comp.event_names {
                if read_signals.contains(event_name.as_str()) {
                    prop_list.push(event_name.clone());
                }
            }
            // If all props were filtered out, use a non-destructured signature
            // to avoid invalid `({  }: Props)` syntax.
            if prop_list.is_empty() {
                w.emit_fmt(format_args!(
                    "export function {}(_props: {}Props) {{",
                    name, name
                ));
            } else {
                w.emit_fmt(format_args!(
                    "export function {}({{ {} }}: {}Props) {{",
                    name,
                    prop_list.join(", "),
                    name
                ));
            }
        }
        w.indent();

        // Store hooks — only for stores whose signals are actually used
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                w.emit_fmt(format_args!("const {} = {}();", store_ref, hook_name));
            }
        }

        // Build set of function names for conflict detection with state setters
        let fn_names: FxHashSet<String> = comp.fns.iter().map(|f| f.name.clone()).collect();

        // State hooks (useState) — only generate setter if signal is mutated;
        // non-mutated signals use plain const for cleaner code.
        // Skip states that are never read in view/computeds/effects/lifecycles/called-fns.
        for state in &comp.states {
            if !read_signals.contains(&state.name) {
                continue;
            }
            let init_val = expr::format_expr_ir_tsx(&state.initial_value);
            if mutated_signals.contains(&state.name) {
                let setter_base = format!("set{}", capitalize_first(&state.name));
                let setter = if fn_names.contains(&setter_base) {
                    format!("__{}", setter_base)
                } else {
                    setter_base
                };
                w.emit_fmt(format_args!(
                    "const [{}, {}] = useState({});",
                    state.name, setter, init_val
                ));
            } else {
                w.emit_fmt(format_args!(
                    "const {} = {};",
                    state.name, init_val
                ));
            }
        }

        // Effects (useEffect) — wrap in async IIFE if body contains await
        for effect in &comp.effects {
            // Resolve store signal deps to qualified names (e.g., "notifications" → "NotificationStore.notifications")
            let deps: Vec<String> = effect
                .deps
                .iter()
                .map(|d| {
                    store_signal_map
                        .get(d)
                        .cloned()
                        .unwrap_or_else(|| d.clone())
                })
                .collect();
            let deps_str = deps.join(", ");
            let body_has_await = effect.body.statements.iter().any(stmt_contains_await);
            if body_has_await {
                w.emit("useEffect(() => {");
                w.indent();
                w.emit("(async () => {");
                w.indent();
                for stmt in &effect.body.statements {
                    expr::generate_statement_tsx_with_mode(&mut w, stmt, &signal_names, self.store_mode);
                }
                w.dedent();
                w.emit("})();");
                w.dedent();
                w.emit_fmt(format_args!("}}, [{}]);", deps_str));
            } else {
                w.emit("useEffect(() => {");
                w.indent();
                for stmt in &effect.body.statements {
                    expr::generate_statement_tsx_with_mode(&mut w, stmt, &signal_names, self.store_mode);
                }
                w.dedent();
                w.emit_fmt(format_args!("}}, [{}]);", deps_str));
            }
        }

        // Lifecycles (mount/unmount)
        for lc in &comp.lifecycles {
            match lc.kind {
                LifecycleKind::Mount => {
                    let body_has_await = lc.body.statements.iter().any(stmt_contains_await);
                    if body_has_await {
                        w.emit("useEffect(() => {");
                        w.indent();
                        w.emit("(async () => {");
                        w.indent();
                        for stmt in &lc.body.statements {
                            expr::generate_statement_tsx_with_mode(&mut w, stmt, &signal_names, self.store_mode);
                        }
                        w.dedent();
                        w.emit("})();");
                        w.dedent();
                        w.emit("}, []);");
                    } else {
                        w.emit("useEffect(() => {");
                        w.indent();
                        for stmt in &lc.body.statements {
                            expr::generate_statement_tsx_with_mode(&mut w, stmt, &signal_names, self.store_mode);
                        }
                        w.dedent();
                        w.emit("}, []);");
                    }
                }
                LifecycleKind::Unmount => {
                    w.emit("useEffect(() => {");
                    w.indent();
                    w.emit("return () => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        expr::generate_statement_tsx_with_mode(&mut w, stmt, &signal_names, self.store_mode);
                    }
                    w.dedent();
                    w.emit("};");
                    w.dedent();
                    w.emit("}, []);");
                }
                LifecycleKind::Effect => {
                    let body_has_await = lc.body.statements.iter().any(stmt_contains_await);
                    if body_has_await {
                        w.emit("useEffect(() => {");
                        w.indent();
                        w.emit("(async () => {");
                        w.indent();
                        for stmt in &lc.body.statements {
                            expr::generate_statement_tsx_with_mode(&mut w, stmt, &signal_names, self.store_mode);
                        }
                        w.dedent();
                        w.emit("})();");
                        w.dedent();
                        w.emit("});");
                    } else {
                        w.emit("useEffect(() => {");
                        w.indent();
                        for stmt in &lc.body.statements {
                            expr::generate_statement_tsx_with_mode(&mut w, stmt, &signal_names, self.store_mode);
                        }
                        w.dedent();
                        w.emit("});");
                    }
                }
            }
        }

        // Computed values (useMemo)
        // Build a list of "signal-like" identifiers (state vars, store refs, other computeds)
        let mut known_signal_names: Vec<String> =
            comp.states.iter().map(|s| s.name.clone()).collect();
        known_signal_names.extend(comp.store_refs.iter().cloned());
        known_signal_names.extend(comp.computeds.iter().map(|c| c.name.clone()));

        for computed in &comp.computeds {
            let mut deps_list: Vec<&str> = Vec::new();
            for sig_name in &known_signal_names {
                if utils::getter_expr_contains_ident(&computed.body, sig_name) {
                    deps_list.push(sig_name.as_str());
                }
            }

            // Function-form computed: `computed name() -> Type { ... }` → useCallback
            // (detected by BlockExpr with ReturnStmtIR in statements)
            let is_fn_form = match &computed.body {
                ExprIR::BlockExpr { statements, .. } => statements
                    .iter()
                    .any(|s| matches!(s, StatementIR::ReturnStmtIR { .. })),
                _ => false,
            };

            if is_fn_form {
                w.emit_fmt(format_args!(
                    "const {} = useCallback(() => {{",
                    computed.name
                ));
            } else {
                w.emit_fmt(format_args!("const {} = useMemo(() => {{", computed.name));
            }
            w.indent();
            if let ExprIR::BlockExpr { statements, tail } = &computed.body {
                // Render preceding statements (let declarations, if/return, etc.)
                for stmt in statements {
                    expr::generate_statement_tsx_with_mode(&mut w, stmt, &signal_names, self.store_mode);
                }
                // Render tail as return value if non-null
                // (null tail means the block has explicit return statements)
                if !matches!(
                    tail.as_ref(),
                    ExprIR::LiteralExpr { value } if value == &serde_json::Value::Null
                ) {
                    w.emit_fmt(format_args!("return {};", expr::format_expr_ir_tsx(tail)));
                }
            } else {
                w.emit_fmt(format_args!(
                    "return {};",
                    expr::format_expr_ir_tsx(&computed.body)
                ));
            }
            w.dedent();
            w.emit_fmt(format_args!("}}, [{}]);", deps_list.join(", ")));
        }

        // Component-local functions (fn declarations in the component body)
        // Only generate functions that are actually called from the view/effects/lifecycles
        for fun in &comp.fns {
            if !called_fns.contains(&fun.name) {
                continue;
            }
            let param_names: Vec<(String, bool)> = fun
                .params
                .iter()
                .map(|p| {
                    let escaped = escape_js_ident(&p.name);
                    let needs_rename = escaped != p.name;
                    (escaped, needs_rename)
                })
                .collect();
            let param_escaped: Vec<&str> = param_names.iter().map(|(n, _)| n.as_str()).collect();
            let params_str = param_escaped.join(", ");
            let is_async = fun.is_async || fun.body.statements.iter().any(stmt_contains_await);
            let async_prefix = if is_async { "async " } else { "" };
            w.emit_fmt(format_args!(
                "const {} = {}({}) => {{",
                fun.name, async_prefix, params_str
            ));
            w.indent();
            // Emit body into temp writer for post-processing
            let mut body_w = crate::codegen::CodeWriter::new();
            body_w.indent();
            for stmt in &fun.body.statements {
                expr::generate_statement_tsx_with_mode(&mut body_w, stmt, &signal_names, self.store_mode);
            }
            // Build setter renames for states whose setters conflict with function names
            let setter_renames: Vec<(String, String)> = comp
                .states
                .iter()
                .filter_map(|s| {
                    let setter_name = format!("set{}", capitalize_first(&s.name));
                    if fn_names.contains(&setter_name) {
                        Some((setter_name.clone(), format!("__{}", setter_name)))
                    } else {
                        None
                    }
                })
                .collect();

            let mut body_str = body_w.into_string();
            // Apply param renames (reserved words)
            for (i, (new_name, needs_rename)) in param_names.iter().enumerate() {
                if *needs_rename {
                    let old_name = &fun.params[i].name;
                    body_str = body_str.replace(old_name, new_name);
                }
            }
            // Apply setter renames (conflict with function names)
            for (old_setter, new_setter) in &setter_renames {
                body_str = body_str.replace(old_setter, new_setter);
            }
            for line in body_str.lines() {
                w.emit(line);
            }
            w.dedent();
            w.emit("};");
        }
        if !comp.fns.is_empty() {
            w.emit("");
        }

        // Motion animation effects — emit hooks for @enter/@hover/@press/@focus triggers
        if let Some(ref view) = comp.view {
            // Build complete motion definition map (component-level + module-level)
            let mut motion_map: FxHashMap<String, MotionBodyIR> = FxHashMap::default();
            for m in &comp.motions {
                motion_map.insert(m.name.clone(), m.body.clone());
            }
            for module in ir.modules.values() {
                for m in &module.motions {
                    motion_map
                        .entry(m.name.clone())
                        .or_insert_with(|| m.body.clone());
                }
            }
            motion::emit_motion_effects_tsx(&mut w, view, &motion_map, &signal_names);
        }

        // @driven-by effects — emit reactive hooks for external progress control
        if let Some(ref view) = comp.view {
            motion::emit_driven_by_effects_tsx(&mut w, view);
        }

        // @in-view effects — IntersectionObserver for entrance animations
        if let Some(ref view) = comp.view {
            motion::emit_inview_effects_tsx(&mut w, view);
        }

        // @scroll effects — scroll-driven animation progress
        if let Some(ref view) = comp.view {
            motion::emit_scroll_effects_tsx(&mut w, view);
        }

        // @drag-horizontal / @drag-vertical effects — gesture-driven animation progress
        if let Some(ref view) = comp.view {
            motion::emit_drag_effects_tsx(&mut w, view);
        }

        w.emit("");

        // Render return (JSX view tree)
        w.emit("return (");
        w.indent();
        if let Some(view) = &comp.view {
            view::gen_view_node_tsx(&mut w, view, component_map, &signal_names, &motion_names);
        } else {
            w.emit("<div className={styles.container}>");
            w.indent();
            w.emit_fmt(format_args!("<h1>{{'{0}'}}</h1>", name));
            w.dedent();
            w.emit("</div>");
        }
        w.dedent();
        w.emit(");");
        w.dedent();
        w.emit("}");
        w.emit("");

        w.into_string()
    }

    /// Generate a CSS module file from component styles.
    pub(super) fn gen_component_css(&self, name: &str, comp: &ComponentIR) -> String {
        let mut w = CodeWriter::new();
        w.emit_fmt(format_args!("/* Styles for {} */", name));
        crate::codegen::generate_css_style_block(&mut w, &comp.styles);
        w.into_string()
    }
}

