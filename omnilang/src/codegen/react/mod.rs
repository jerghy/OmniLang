//! React codegen: IR -> React TSX components + CSS modules + store hooks.
//!
//! Each component generates a `.tsx` React functional component with hooks
//! and a `.module.css` CSS module file. Each store generates a `useXxx.ts`
//! custom hook file.

use std::collections::HashMap;

use super::{CodeWriter, Codegen, CompileOutput, CompiledFile};
use crate::ir::*;

pub(super) mod expr;
pub(super) mod tests;
pub(super) mod utils;
pub(super) mod view;

pub struct ReactCodegen;

impl Codegen for ReactCodegen {
    fn generate(&self, ir: &IRProgram, _source_files: &HashMap<String, String>) -> CompileOutput {
        let mut files = Vec::new();

        for (name, comp) in ir.all_components() {
            // .tsx
            let tsx = self.gen_component_tsx(name, comp, ir);
            files.push(CompiledFile {
                path: format!("{}.tsx", name),
                content: tsx,
            });

            // .module.css
            let css = self.gen_component_css(name, comp);
            files.push(CompiledFile {
                path: format!("{}.module.css", name),
                content: css,
            });
        }

        for (name, store) in ir.all_stores() {
            let hook = self.gen_store_hook(name, store);
            files.push(CompiledFile {
                path: format!("use{}.ts", name),
                content: hook,
            });
        }

        CompileOutput::success(files)
    }
}

impl ReactCodegen {
    /// Generate a React functional component .tsx file.
    fn gen_component_tsx(&self, name: &str, comp: &ComponentIR, ir: &IRProgram) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang — React target");
        w.emit("");

        // Imports
        w.emit("import React, { useState, useEffect, useMemo, useRef } from 'react';");
        w.emit(&format!("import styles from './{}.module.css';", name));
        w.emit("");

        // Props interface
        if !comp.props.is_empty() {
            w.emit(&format!("interface {}Props {{", name));
            for (prop_name, prop_type) in &comp.props {
                let ts_type =
                    super::javascript::js_type(&prop_type.kind, &prop_type.type_args, true);
                w.emit(&format!("  {}: {};", prop_name, ts_type));
            }
            w.emit("}");
            w.emit("");
        }

        // Store hook imports
        let mut store_hook_imports = Vec::new();
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                store_hook_imports.push(format!(
                    "import {{ {} }} from './use{}';",
                    hook_name, store_ref
                ));
            }
        }
        for import_line in &store_hook_imports {
            w.emit(import_line);
        }
        if !store_hook_imports.is_empty() {
            w.emit("");
        }

        // Component map for composition references
        let component_map: HashMap<String, ComponentIR> = ir
            .all_components()
            .into_iter()
            .map(|(n, c)| (n.to_string(), c.clone()))
            .collect();

        // Component function signature
        if comp.props.is_empty() {
            w.emit(&format!("export function {}() {{", name));
        } else {
            let prop_list: Vec<&str> = comp.props.keys().map(|s| s.as_str()).collect();
            w.emit(&format!(
                "export function {}({{ {} }}: {}Props) {{",
                name,
                prop_list.join(", "),
                name
            ));
        }
        w.indent();

        // Store hooks
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                w.emit(&format!("const {} = {}();", store_ref, hook_name));
            }
        }

        // State hooks (useState)
        for state in &comp.states {
            let init_val = expr::format_expr_ir_tsx(&state.initial_value);
            let setter = format!("set{}", utils::capitalize_first(&state.name));
            w.emit(&format!(
                "const [{}, {}] = useState({});",
                state.name, setter, init_val
            ));
        }

        // Effects (useEffect)
        for effect in &comp.effects {
            let deps: Vec<&str> = effect.deps.iter().map(|d| d.as_str()).collect();
            w.emit("useEffect(() => {");
            w.indent();
            for stmt in &effect.body.statements {
                expr::generate_statement_tsx(&mut w, stmt);
            }
            w.dedent();
            w.emit(&format!("}}, [{}]);", deps.join(", ")));
        }

        // Lifecycles (mount/unmount)
        for lc in &comp.lifecycles {
            match lc.kind.as_str() {
                "mount" => {
                    w.emit("useEffect(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        expr::generate_statement_tsx(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("}, []);");
                }
                "unmount" => {
                    w.emit("useEffect(() => {");
                    w.indent();
                    w.emit("return () => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        expr::generate_statement_tsx(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("};");
                    w.dedent();
                    w.emit("}, []);");
                }
                _ => {
                    w.emit(&format!("// TODO: lifecycle '{}'", lc.kind));
                }
            }
        }

        // Computed values (useMemo)
        for computed in &comp.computeds {
            let deps: Vec<&str> = computed.deps.iter().map(|d| d.as_str()).collect();
            w.emit(&format!("const {} = useMemo(() => {{", computed.name));
            w.indent();
            w.emit(&format!(
                "return {};",
                expr::format_expr_ir_tsx(&computed.body)
            ));
            w.dedent();
            w.emit(&format!("}}, [{}]);", deps.join(", ")));
        }

        // Motion animation effects — emit hooks for @enter/@hover/@press/@focus triggers
        if let Some(ref view) = comp.view {
            let mut ref_counter = 0u32;
            view::emit_motion_effects_tsx(&mut w, view, &mut ref_counter, name);
        }

        // @driven-by effects — emit reactive hooks for external progress control
        if let Some(ref view) = comp.view {
            view::emit_driven_by_effects_tsx(&mut w, view);
        }

        // @in-view effects — IntersectionObserver for entrance animations
        if let Some(ref view) = comp.view {
            view::emit_inview_effects_tsx(&mut w, view);
        }

        // @scroll effects — scroll-driven animation progress
        if let Some(ref view) = comp.view {
            view::emit_scroll_effects_tsx(&mut w, view);
        }

        // @drag-horizontal / @drag-vertical effects — gesture-driven animation progress
        if let Some(ref view) = comp.view {
            view::emit_drag_effects_tsx(&mut w, view);
        }

        w.emit("");

        // Render return (JSX view tree)
        w.emit("return (");
        w.indent();
        if let Some(view) = &comp.view {
            view::gen_view_node_tsx(&mut w, view, &component_map);
        } else {
            w.emit("<div className={styles.container}>");
            w.indent();
            w.emit(&format!("<h1>{{'{0}'}}</h1>", name));
            w.dedent();
            w.emit("</div>");
        }
        w.dedent();
        w.emit(");");
        w.dedent();
        w.emit("}");
        w.emit("");

        w.into_string()
    }

    /// Generate a CSS module file from component styles.
    fn gen_component_css(&self, name: &str, comp: &ComponentIR) -> String {
        let mut w = CodeWriter::new();
        w.emit(&format!("/* Styles for {} */", name));
        if comp.styles.is_empty() {
            w.emit(".container {");
            w.indent();
            w.emit("display: flex;");
            w.emit("flex-direction: column;");
            w.emit("padding: 16px;");
            w.dedent();
            w.emit("}");
        } else {
            for style in &comp.styles {
                let prefix = if style.is_tag_selector { "" } else { "." };
                w.emit(&format!("{}{} {{", prefix, style.class_name));
                for (prop, value) in &style.properties {
                    let css_val = utils::format_css_value(value);
                    w.emit(&format!("  {}: {};", utils::to_css_prop(prop), css_val));
                }
                w.emit("}");
            }
        }
        w.into_string()
    }

    /// Generate a custom store hook (useStoreName.ts).
    fn gen_store_hook(&self, name: &str, store: &StoreIR) -> String {
        let mut w = CodeWriter::new();
        w.emit(&format!(
            "// Generated by OmniLang — Store hook: use{}",
            name
        ));
        w.emit("import { useState, useCallback } from 'react';");
        w.emit("");

        w.emit(&format!("export function use{}() {{", name));
        w.indent();

        // Signals as state variables
        for (sig_name, sig_type) in &store.signals {
            let init = store
                .signal_defaults
                .get(sig_name)
                .map(utils::format_json_value_tsx)
                .unwrap_or_else(|| "null".into());
            let setter = format!("set{}", utils::capitalize_first(sig_name));
            let ts_type = super::javascript::js_type(&sig_type.kind, &sig_type.type_args, true);
            w.emit(&format!(
                "const [{}, {}] = useState<{}>({});",
                sig_name, setter, ts_type, init
            ));
        }

        // Getters as memoized values
        for (getter_name, getter_expr) in &store.getters {
            let deps: Vec<String> = store
                .signals
                .keys()
                .filter(|sig| utils::getter_expr_contains_ident(getter_expr, sig))
                .cloned()
                .collect();
            let deps_str = deps.join(", ");
            w.emit(&format!(
                "const {} = useCallback(() => {{ return {}; }}, [{}]);",
                getter_name,
                expr::format_expr_ir_tsx(getter_expr),
                deps_str
            ));
        }

        // Actions: each becomes a useCallback function calling signal setters
        let mut return_keys: Vec<String> = Vec::new();
        for action in &store.actions {
            let params: Vec<String> = action.params.iter().map(|p| p.name.clone()).collect();
            let params_str = params.join(", ");
            w.emit(&format!(
                "const {} = useCallback(({}) => {{",
                action.name, params_str
            ));
            w.indent();
            for stmt in &action.body.statements {
                expr::generate_statement_tsx(&mut w, stmt);
            }
            w.dedent();
            w.emit("}, []);");
            return_keys.push(action.name.clone());
        }

        // Return value
        for sig_name in store.signals.keys() {
            return_keys.push(sig_name.clone());
        }
        for getter_name in store.getters.keys() {
            return_keys.push(getter_name.clone());
        }
        w.emit(&format!("return {{ {} }};", return_keys.join(", ")));

        w.dedent();
        w.emit("}");
        w.into_string()
    }
}
