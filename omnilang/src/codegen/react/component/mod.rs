pub(super) mod computed;
pub(super) mod effect;
pub(super) mod function;
pub(super) mod imports;
pub(super) mod jsx;
pub(super) mod motion_effects;
pub(super) mod state;

use super::expr;
use super::{escape_js_ident, CodeWriter, ReactCodegen};
use crate::ir::*;
use rustc_hash::FxHashMap;
use rustc_hash::FxHashSet;

impl ReactCodegen {
    /// Generate a React functional component .tsx file.
    pub(super) fn gen_component_tsx(
        &self,
        name: &str,
        comp: &ComponentIR,
        ir: &IRProgram,
        component_map: &FxHashMap<&str, &ComponentIR>,
    ) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang — React target");
        w.emit("");

        // ADR-053 D5: body-level `@slot` declarations surface in the view as
        // `{name}` interpolations — materialize them into `ViewTree::Slot`
        // nodes (carrying the declared fallbacks) ONCE so every view
        // consumer below (motion / ref / signal collection and JSX
        // rendering) sees the fallback content, exactly like view-level
        // `@slot` directives. Fast path: components without body slots keep
        // the original view (no tree clone).
        let materialized_view: Option<ViewTree> = comp
            .view
            .as_ref()
            .filter(|_| !comp.slots.is_empty())
            .map(|v| materialize_view_slots(v, comp, &slot_collision_names(comp)));
        // All view consumers borrow the materialized tree when body slots
        // exist, otherwise the original view.
        let view = materialized_view.as_ref().or(comp.view.as_ref());

        // Determine which React hooks are actually needed
        let has_computeds = !comp.computeds.is_empty();
        let has_fn_form_computed = comp.computeds.iter().any(|c| {
            matches!(&c.body, ExprIR::BlockExpr { statements, .. }
                if statements.iter().any(|s| matches!(s, StatementIR::ReturnStmtIR { .. })))
        });
        let has_effects_or_lifecycles = !comp.effects.is_empty() || !comp.lifecycles.is_empty();
        let has_motion = view.is_some_and(effect::view_has_motion_or_effects);
        let has_semantic_bindings = view.is_some_and(state::view_has_semantic_bindings);

        // Motion elements without a user @ref get synthesized `__el_N` refs.
        // Collected here (DFS pre-order over motion elements) so useRef
        // imports and declarations exist for them; the JSX emitter and the
        // motion effect emitter derive the same names from the same order.
        let mut motion_internal_refs: Vec<(String, String)> = Vec::new(); // (ref_name, tag)
        if let Some(view) = view {
            super::motion::walk_motion_elements(view, component_map, |el, idx| {
                if el.ref_binding.is_none() {
                    motion_internal_refs.push((format!("__el_{}", idx), el.tag.clone()));
                }
            });
        }
        // @hover/@press emit useCallback handlers wired into the JSX
        let has_interactive_motion =
            view.is_some_and(|v| super::motion::view_has_interactive_triggers(v, component_map));

        // Scan all code paths for signal mutations and function calls
        let called_fns = function::collect_called_local_fns(comp);
        let mutated_signals = state::collect_signal_mutations(comp, &called_fns);

        // Build comprehensive read-signals set: signals referenced in view, computeds,
        // effects, lifecycles, and called local functions.
        let mut read_signals = view
            .map(state::collect_view_read_signals)
            .unwrap_or_default();
        for computed in &comp.computeds {
            collect_expr_identifiers(&computed.body, &mut read_signals);
        }
        for effect in &comp.effects {
            // Effect dep arrays are emitted verbatim (`useEffect(..., [username, fontSize])`)
            // — a signal referenced ONLY as a dep must still get its hook,
            // or the emitted dep name is undeclared (TS2304).
            for dep in &effect.deps {
                read_signals.insert(dep.clone());
            }
            for stmt in &effect.body.statements {
                collect_stmt_identifiers(stmt, &mut read_signals);
            }
        }
        for lc in &comp.lifecycles {
            for stmt in &lc.body.statements {
                collect_stmt_identifiers(stmt, &mut read_signals);
            }
        }
        for fun in &comp.fns {
            if called_fns.contains(&fun.name) {
                for stmt in &fun.body.statements {
                    collect_stmt_identifiers(stmt, &mut read_signals);
                }
            }
        }
        if let Some(view) = view {
            state::collect_view_inline_handler_reads(view, &mut read_signals);
        }

        // Determine if any state actually needs useState (has active setter)
        let has_mutable_states = comp
            .signals
            .iter()
            .any(|s| read_signals.contains(&s.name) && mutated_signals.contains(&s.name));
        let mut hooks: Vec<String> = Vec::new();
        if has_mutable_states {
            hooks.push("useState".to_string());
        }
        if has_computeds {
            hooks.push("useMemo".to_string());
        }
        if has_fn_form_computed || has_interactive_motion {
            hooks.push("useCallback".to_string());
        }
        if has_effects_or_lifecycles || has_motion || has_semantic_bindings {
            hooks.push("useEffect".to_string());
        }

        // Ref declarations → useRef (user @refs + synthesized motion refs)
        let has_refs = !comp.refs.is_empty() || !motion_internal_refs.is_empty();
        if has_refs {
            hooks.push("useRef".to_string());
        }

        // Design context — design classes/variant classes are global CSS in
        // design.css and are emitted as literal class names (HIGH #1); the
        // CSS module import is only needed for component-local classes.
        let design_ctx = super::design::DesignCtx::new(ir);
        let used_style_classes = view
            .map(jsx::collect_used_style_classes)
            .unwrap_or_default();
        let local_style_classes: FxHashSet<String> = used_style_classes
            .difference(&design_ctx.global_class_names)
            .cloned()
            .collect();
        // `@if mode: "fade"` renders branches inside a wrapper div carrying
        // the CSS-module `.omni-if-fade` class — forces the stylesheet
        // import so the fade rules (emitted by gen_component_css) exist.
        // The same predicate gates the CSS rules (gen_component_css), so the
        // import and the rules can never diverge.
        let has_if_fade = component_has_fade_conditional(comp);
        let has_styles = !local_style_classes.is_empty()
            || (!comp.styles.is_empty()
                && local_style_classes
                    .iter()
                    .any(|c| comp.styles.iter().any(|s| &s.class_name == c)))
            || has_if_fade;

        // Props interface check — slot declarations also become props
        // (`children` for the unnamed slot, same-named props for named
        // slots). Body-level `@slot` declarations (ADR-053 D5) plus
        // view-level directives (back-compat).
        let declared_slots = jsx::component_declared_slots(comp, component_map);
        let has_props =
            !comp.props.is_empty() || !comp.events.is_empty() || !declared_slots.is_empty();

        // ── Store-related computation ──
        let all_stores = ir.all_stores();
        let used_store_signals = state::collect_used_store_signals(comp);

        let local_names: FxHashSet<String> = comp
            .signals
            .iter()
            .map(|s| s.name.clone())
            .chain(comp.props.keys().cloned())
            .chain(comp.fns.iter().map(|f| f.name.clone()))
            .collect();

        let mut used_store_refs: FxHashSet<String> = FxHashSet::default();
        for store_ref in &comp.store_refs {
            if used_store_signals.contains(store_ref.as_str()) {
                used_store_refs.insert(store_ref.clone());
                continue;
            }
            if let Some(store) = all_stores.get(store_ref.as_str()) {
                for sig_name in store.signals.keys() {
                    if !local_names.contains(sig_name) && used_store_signals.contains(sig_name) {
                        used_store_refs.insert(store_ref.clone());
                        break;
                    }
                }
            }
        }

        // Build signal_names (all state + store aliases), store_signal_map
        // (signal → "StoreRef.signal" for effect deps) and store_signal_owners
        // (signal → "StoreRef" for setState mutations, C7).
        let mut signal_names: FxHashSet<String> =
            comp.signals.iter().map(|s| s.name.clone()).collect();
        let mut store_signal_map: FxHashMap<String, String> = FxHashMap::default();
        let mut store_signal_owners: FxHashMap<String, String> = FxHashMap::default();
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            signal_names.insert(store_ref.clone());
            if let Some(store) = ir.all_stores().get(store_ref.as_str()) {
                for sig_name in store.signals.keys() {
                    signal_names.insert(sig_name.clone());
                    store_signal_map
                        .insert(sig_name.clone(), format!("{}.{}", store_ref, sig_name));
                    store_signal_owners.insert(sig_name.clone(), store_ref.clone());
                }
            }
        }

        // Build ref_names set for expression translation (ADR-036 Phase 2)
        let ref_names: FxHashSet<String> = comp.refs.iter().map(|r| r.name.clone()).collect();

        // Ref name → element tag map (typing useRef declarations) — scanned
        // from the view because RefDeclIR.element_tag is not populated by
        // lowering yet.
        let ref_tags = state::collect_ref_tags(view);

        // Motion animation names — used to filter motion refs from event handlers
        let motion_names: FxHashSet<String> = ir
            .modules
            .values()
            .flat_map(|m| &m.motions)
            .map(|m| m.name.clone())
            .collect();

        // ── Design runtime wiring (root component only) ──
        // The root component mounts the design system: it imports and calls
        // the `useDesignTokens` hooks (dynamic token effects) and imports
        // `useThemeStore` (side effect: data-theme subscription) so design
        // runtime behavior activates with the app (HIGH #2).
        let is_root = super::design::is_root_component(name, ir);
        let design_wiring = if is_root {
            super::design::root_design_wiring(ir, comp.source_file.as_deref())
        } else {
            super::design::DesignWiring {
                import_lines: Vec::new(),
                hook_calls: Vec::new(),
            }
        };

        // ── Emit imports ──
        let comp_imports = imports::collect_component_imports(
            comp,
            ir,
            component_map,
            &used_store_refs,
            &hooks,
            has_styles,
            &design_wiring.import_lines,
        );
        comp_imports.emit(&mut w, name, comp, has_props);

        // ── Library functions ──
        let mut used_fn_names: FxHashSet<String> = FxHashSet::default();
        for computed in &comp.computeds {
            collect_expr_identifiers(&computed.body, &mut used_fn_names);
        }
        for effect in &comp.effects {
            for stmt in &effect.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        for lc in &comp.lifecycles {
            for stmt in &lc.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        for fun in &comp.fns {
            for stmt in &fun.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        if let Some(view) = view {
            jsx::collect_view_identifiers(view, &mut used_fn_names);
        }
        if let Some(view) = view {
            jsx::collect_motion_identifiers(view, &mut used_fn_names);
        }

        let all_lib_fns: Vec<&FunctionIR> = ir.all_functions();
        // Transitive closure: a lib fn used from the view may delegate to
        // other lib fns — every callee referenced by an emitted body needs
        // a declaration too (previously only the view-referenced entry was
        // emitted → TS2304 on the inner call).
        let mut prev_len = 0;
        while used_fn_names.len() > prev_len {
            prev_len = used_fn_names.len();
            for fun in &all_lib_fns {
                if used_fn_names.contains(&fun.name) {
                    for stmt in &fun.body.statements {
                        collect_stmt_identifiers(stmt, &mut used_fn_names);
                    }
                }
            }
        }
        let lib_fns: Vec<&&FunctionIR> = all_lib_fns
            .iter()
            .filter(|f| used_fn_names.contains(&f.name))
            .collect();
        for fun in &lib_fns {
            let param_names: Vec<(String, bool)> = fun
                .params
                .iter()
                .map(|p| {
                    let escaped = escape_js_ident(&p.name);
                    let needs_rename = escaped != p.name;
                    (escaped, needs_rename)
                })
                .collect();
            let params_str = function::format_fn_params(fun);
            let is_async =
                fun.is_async || fun.body.statements.iter().any(effect::stmt_contains_await);
            let async_prefix = if is_async { "async " } else { "" };
            w.emit_fmt(format_args!(
                "const {} = {}({}) => {{",
                fun.name, async_prefix, params_str
            ));
            w.indent();
            let mut body_w = crate::codegen::CodeWriter::new();
            body_w.indent();
            for stmt in &fun.body.statements {
                expr::generate_statement_tsx(
                    &mut body_w,
                    stmt,
                    &FxHashSet::default(),
                    &store_signal_owners,
                    &ref_names,
                );
            }
            let mut body_str = body_w.into_string();
            for (i, (new_name, needs_rename)) in param_names.iter().enumerate() {
                if *needs_rename {
                    let old_name = &fun.params[i].name;
                    body_str = body_str.replace(old_name, new_name);
                }
            }
            for line in body_str.lines() {
                w.emit(line);
            }
            w.dedent();
            w.emit("};");
        }
        if !lib_fns.is_empty() {
            w.emit("");
        }

        // Component function signature
        if !has_props {
            w.emit_fmt(format_args!("export function {}() {{", name));
        } else {
            let mut prop_list: Vec<String> = comp
                .props
                .keys()
                .map(|prop_name| {
                    if let Some(default_val) = comp.prop_defaults.get(prop_name) {
                        let default_tsx = expr::format_expr_ir_tsx(default_val, &ref_names);
                        format!("{} = {}", prop_name, default_tsx)
                    } else {
                        prop_name.clone()
                    }
                })
                .collect();
            for event in &comp.events {
                if read_signals.contains(event.name.as_str()) {
                    prop_list.push(event.name.clone());
                }
            }
            // Slot props must be destructured so `{children}` / `{header}`
            // render correctly in the JSX body. A slot whose prop name
            // collides with a signal/computed/function is skipped — the
            // semantic layer warns on the collision, and the hook/function
            // declaration would shadow (or duplicate) the destructured name.
            let slot_collides: FxHashSet<&str> = comp
                .signals
                .iter()
                .map(|s| s.name.as_str())
                .chain(comp.computeds.iter().map(|c| c.name.as_str()))
                .chain(comp.fns.iter().map(|f| f.name.as_str()))
                .collect();
            for (slot_name, _) in &declared_slots {
                let slot_prop = slot_name.as_deref().unwrap_or("children").to_string();
                if !prop_list.iter().any(|p| p == &slot_prop)
                    && !slot_collides.contains(slot_prop.as_str())
                {
                    prop_list.push(slot_prop);
                }
            }
            if prop_list.is_empty() {
                w.emit_fmt(format_args!(
                    "export function {}(_props: {}Props) {{",
                    name, name
                ));
            } else {
                w.emit_fmt(format_args!(
                    "export function {}({{ {} }}: {}Props) {{",
                    name,
                    prop_list.join(", "),
                    name
                ));
            }
        }
        w.indent();

        // Store hooks — only for stores whose signals are actually used
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            if ir.has_store(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                w.emit_fmt(format_args!("const {} = {}();", store_ref, hook_name));
            }
        }

        // Design system hooks — called from the root component so the
        // dynamic-token effects and theme subscription activate (HIGH #2).
        if is_root {
            for hook_call in &design_wiring.hook_calls {
                w.emit_fmt(format_args!("{}();", hook_call));
            }
        }

        // State hooks + effects
        let fn_names: FxHashSet<String> = comp.fns.iter().map(|f| f.name.clone()).collect();
        self.gen_state_hooks(&mut w, comp, &read_signals, &mutated_signals, &fn_names);
        state::gen_ref_hooks(&mut w, comp, &ref_tags, &motion_internal_refs);
        self.gen_effects(
            &mut w,
            comp,
            &store_signal_map,
            &store_signal_owners,
            &signal_names,
            &ref_names,
        );
        state::gen_semantic_binding_effects(&mut w, view, &store_signal_map, &ref_names);

        // Computed values (useMemo / useCallback)
        let mut known_signal_names: Vec<String> =
            comp.signals.iter().map(|s| s.name.clone()).collect();
        known_signal_names.extend(comp.store_refs.iter().cloned());
        known_signal_names.extend(comp.computeds.iter().map(|c| c.name.clone()));
        computed::gen_computed_values(
            &mut w,
            comp,
            &known_signal_names,
            &signal_names,
            &store_signal_owners,
            &ref_names,
        );

        // Component-local function declarations
        self.gen_functions(
            &mut w,
            comp,
            &called_fns,
            &signal_names,
            &store_signal_owners,
            &fn_names,
            &ref_names,
        );

        // Motion animation effects — per-ref native effects (all triggers)
        if let Some(view) = view {
            motion_effects::gen_motion_effects(&mut w, view, ir, component_map);
        }

        w.emit("");

        // Render return (JSX view tree) — the materialized view (body-slot
        // declarations already converted to `ViewTree::Slot` nodes).
        let mut motion_counter = 0usize;
        self.gen_jsx_return(
            &mut w,
            view,
            component_map,
            &design_ctx,
            &signal_names,
            &store_signal_owners,
            &motion_names,
            name,
            &ref_names,
            &mut motion_counter,
        );
        w.dedent();
        w.emit("}");
        w.emit("");

        w.into_string()
    }

    /// Generate a CSS module file from component styles.
    pub(super) fn gen_component_css(&self, name: &str, comp: &ComponentIR) -> String {
        let mut w = CodeWriter::new();
        w.emit_fmt(format_args!("/* Styles for {} */", name));
        crate::codegen::generate_css_style_block(&mut w, &comp.styles);
        // `@if mode: "fade"` — wrapper class + keyframes. Defined and
        // referenced within the same CSS module so the bundler scopes the
        // class name and the keyframe name consistently.
        if component_has_fade_conditional(comp) {
            w.emit("");
            w.emit(".omni-if-fade {");
            w.indent();
            w.emit("opacity: 0;");
            w.emit("animation: omni-if-fade 300ms ease-out forwards;");
            w.dedent();
            w.emit("}");
            w.emit("@keyframes omni-if-fade {");
            w.indent();
            w.emit("from { opacity: 0; }");
            w.emit("to { opacity: 1; }");
            w.dedent();
            w.emit("}");
            // prefers-reduced-motion: skip the animation, show content
            // immediately (never hide it).
            w.emit("@media (prefers-reduced-motion: reduce) {");
            w.indent();
            w.emit(".omni-if-fade {");
            w.indent();
            w.emit("animation: none;");
            w.emit("opacity: 1;");
            w.dedent();
            w.emit("}");
            w.dedent();
            w.emit("}");
        }
        w.into_string()
    }
}

/// Whether the component declares any `@if mode: "fade"` conditional — in
/// the view itself (including view-level `@slot` fallbacks, which are
/// already `ViewTree::Slot` nodes) or inside a body-declared slot fallback
/// (which the JSX emitter sees after slot materialization).
///
/// This single predicate gates BOTH the CSS-module import (`has_styles` →
/// `import styles`, component/imports.rs) and the fade rules in the CSS
/// module (`gen_component_css`) — the two must never diverge: a component
/// whose only fade sits in a body-slot fallback would otherwise reference
/// `styles['omni-if-fade']` with no import, producing `styles` undefined in
/// the generated TSX.
fn component_has_fade_conditional(comp: &ComponentIR) -> bool {
    comp.view
        .as_ref()
        .is_some_and(super::motion::view_has_fade_conditional)
        || comp.slots.iter().any(|s| {
            s.fallback
                .iter()
                .any(super::motion::view_has_fade_conditional)
        })
}

// ═══════════════════════════════════════════════════════════
// Shared identifier collection — used to determine which
// library functions to emit and which React hooks are needed.
// ═══════════════════════════════════════════════════════════

/// Collect identifier references from an ExprIR.
fn collect_expr_identifiers(expr: &ExprIR, acc: &mut FxHashSet<String>) {
    match expr {
        ExprIR::IdentifierExpr { name, .. } => {
            acc.insert(name.clone());
        }
        ExprIR::BinaryOpExpr { left, right, .. } => {
            collect_expr_identifiers(left, acc);
            collect_expr_identifiers(right, acc);
        }
        ExprIR::UnaryOpExpr { operand, .. } => {
            collect_expr_identifiers(operand, acc);
        }
        ExprIR::CallExpr { name, args, .. } => {
            acc.insert(name.clone());
            for arg in args {
                collect_expr_identifiers(arg, acc);
            }
        }
        ExprIR::MethodCallExpr { object, args, .. } => {
            collect_expr_identifiers(object, acc);
            for arg in args {
                collect_expr_identifiers(arg, acc);
            }
        }
        ExprIR::FieldAccessExpr { object, .. } | ExprIR::OptionalChainExpr { object, .. } => {
            collect_expr_identifiers(object, acc);
        }
        ExprIR::IndexExpr { object, index } => {
            collect_expr_identifiers(object, acc);
            collect_expr_identifiers(index, acc);
        }
        ExprIR::TernaryIR {
            cond,
            then_expr,
            else_expr,
        } => {
            collect_expr_identifiers(cond, acc);
            collect_expr_identifiers(then_expr, acc);
            collect_expr_identifiers(else_expr, acc);
        }
        ExprIR::ArrayExpr { elements } => {
            for elem in elements {
                collect_expr_identifiers(elem, acc);
            }
        }
        ExprIR::MapExpr { entries } => {
            for (k, v) in entries {
                collect_expr_identifiers(k, acc);
                collect_expr_identifiers(v, acc);
            }
        }
        ExprIR::ClosureExpr { body, .. } => {
            collect_expr_identifiers(body, acc);
        }
        ExprIR::BlockExpr { statements, tail } => {
            for stmt in statements {
                collect_stmt_identifiers(stmt, acc);
            }
            collect_expr_identifiers(tail, acc);
        }
        ExprIR::MatchExpr { matched, arms } => {
            collect_expr_identifiers(matched, acc);
            for arm in arms {
                for stmt in &arm.body.statements {
                    collect_stmt_identifiers(stmt, acc);
                }
            }
        }
        ExprIR::VariantLiteral { fields, .. } => {
            for (_, v) in fields {
                collect_expr_identifiers(v, acc);
            }
        }
        ExprIR::StructExpr { fields, .. } => {
            for (_, v) in fields {
                collect_expr_identifiers(v, acc);
            }
        }
        ExprIR::SpreadExpr { operand } => {
            collect_expr_identifiers(operand, acc);
        }
        ExprIR::StoreFieldAccessExpr { call_args, .. } => {
            for arg in call_args {
                collect_expr_identifiers(arg, acc);
            }
        }
        ExprIR::AwaitExpr { operand } => {
            collect_expr_identifiers(operand, acc);
        }
        ExprIR::ArrayMethod {
            subject, predicate, ..
        } => {
            collect_expr_identifiers(subject, acc);
            collect_expr_identifiers(predicate, acc);
        }
        ExprIR::LiteralExpr { .. } => {}
        ExprIR::RefOpExpr { op, .. } => {
            collect_ref_op_identifiers(op, acc);
        }
        #[allow(unreachable_patterns)]
        _ => unreachable!("Unknown ExprIR variant — update codegen for new variant"),
    }
}

/// Collect identifier references from a `RefOpIR`'s child expressions
/// (e.g. ScrollTo/ScrollBy/SetSelection arguments).
fn collect_ref_op_identifiers(op: &RefOpIR, acc: &mut FxHashSet<String>) {
    match op {
        RefOpIR::Focus
        | RefOpIR::Blur
        | RefOpIR::Measure { .. }
        | RefOpIR::Select
        | RefOpIR::Value => {}
        RefOpIR::ScrollTo { x, y } => {
            if let Some(x) = x {
                collect_expr_identifiers(x, acc);
            }
            if let Some(y) = y {
                collect_expr_identifiers(y, acc);
            }
        }
        RefOpIR::ScrollBy { dx, dy } => {
            if let Some(dx) = dx {
                collect_expr_identifiers(dx, acc);
            }
            if let Some(dy) = dy {
                collect_expr_identifiers(dy, acc);
            }
        }
        RefOpIR::SetSelection { start, end } => {
            collect_expr_identifiers(start, acc);
            collect_expr_identifiers(end, acc);
        }
        RefOpIR::CapturePointer { id } => collect_expr_identifiers(id, acc),
        RefOpIR::ReleasePointer { id } => collect_expr_identifiers(id, acc),
        // RefOpIR is #[non_exhaustive] — cross-crate matches need a wildcard.
        #[allow(unreachable_patterns)]
        _ => {}
    }
}

/// Collect identifier references from a StatementIR.
fn collect_stmt_identifiers(stmt: &StatementIR, acc: &mut FxHashSet<String>) {
    match stmt {
        StatementIR::ExprStmtIR { expr } => {
            collect_expr_identifiers(expr, acc);
        }
        StatementIR::LetStmtIR { name: _, value, .. } => {
            if let Some(ref v) = value {
                collect_expr_identifiers(v, acc);
            }
        }
        StatementIR::ReturnStmtIR { value } => {
            if let Some(ref v) = value {
                collect_expr_identifiers(v, acc);
            }
        }
        StatementIR::IfStmtIR {
            condition,
            then_body,
            else_ifs,
            else_body,
        } => {
            collect_expr_identifiers(condition, acc);
            for s in &then_body.statements {
                collect_stmt_identifiers(s, acc);
            }
            for (cond, body) in else_ifs {
                collect_expr_identifiers(cond, acc);
                for s in &body.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
            if let Some(ref eb) = else_body {
                for s in &eb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
        }
        StatementIR::WhileStmtIR { condition, body } => {
            collect_expr_identifiers(condition, acc);
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::ForInStmtIR { iterable, body, .. } => {
            collect_expr_identifiers(iterable, acc);
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::BlockStmtIR { body } => {
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::MutationStmt { intent } => {
            if let Some(intent) = intent {
                collect_mutation_identifiers(intent, acc);
            }
        }
        StatementIR::ThrowStmtIR { expr } => {
            collect_expr_identifiers(expr, acc);
        }
        StatementIR::TryCatchStmtIR {
            try_body,
            catch_body,
            finally_body,
            ..
        } => {
            for s in &try_body.statements {
                collect_stmt_identifiers(s, acc);
            }
            if let Some(ref cb) = catch_body {
                for s in &cb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
            if let Some(ref fb) = finally_body {
                for s in &fb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
        }
        StatementIR::EventEmitStmtIR { event_name, args } => {
            // `emit onX(...)` emits the event prop name + argument
            // expressions verbatim — both must count as reads or the
            // generated call references an undeclared name (TS2304).
            acc.insert(event_name.clone());
            for arg in args {
                collect_expr_identifiers(arg, acc);
            }
        }
        StatementIR::BreakStmtIR | StatementIR::ContinueStmtIR => {}
        #[allow(unreachable_patterns)]
        _ => unreachable!("Unknown StatementIR variant — update codegen for new variant"),
    }
}

/// Collect identifiers from a MutationIntent.
fn collect_mutation_identifiers(intent: &MutationIntent, acc: &mut FxHashSet<String>) {
    match intent {
        MutationIntent::DirectAssign { value, .. } => {
            if let Some(ref v) = value {
                collect_expr_identifiers(v, acc);
            }
        }
        MutationIntent::Increment { amount, .. }
        | MutationIntent::Decrement { amount, .. }
        | MutationIntent::Multiply { amount, .. }
        | MutationIntent::Divide { amount, .. }
        | MutationIntent::Modulo { amount, .. } => {
            if let Some(ref v) = amount {
                collect_expr_identifiers(v, acc);
            }
        }
        MutationIntent::Push { item, .. } => {
            if let Some(ref v) = item {
                collect_expr_identifiers(v, acc);
            }
        }
        MutationIntent::Pop { .. } => {}
        #[allow(unreachable_patterns)]
        _ => unreachable!("Unknown MutationIntent variant — update codegen for new variant"),
    }
}
