impl ReactCodegen {
    /// Generate a React functional component .tsx file.
    pub(super) fn gen_component_tsx(
        &self,
        name: &str,
        comp: &ComponentIR,
        ir: &IRProgram,
        component_map: &FxHashMap<&str, &ComponentIR>,
    ) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang — React target");
        // Source traceability marker (task 7.5, regeneration contract):
        // maps the generated file back to the .omni declaration — edit the
        // .omni source and regenerate, never hand-edit generated output.
        // `source_file`/`source_span` are populated during lowering
        // (ComponentIR.source_span; hand-built IR fixtures emit no marker).
        if let Some(file) = comp.source_file.as_deref() {
            let line = comp.source_span.map(|s| s.line).unwrap_or(0);
            w.emit(&format!("// [omni] {}:{}", file, line));
        }
        w.emit("");

        // ADR-053 D5: body-level `@slot` declarations surface in the view as
        // `{name}` interpolations — materialize them into `ViewTree::Slot`
        // nodes (carrying the declared fallbacks) ONCE so every view
        // consumer below (motion / ref / signal collection and JSX
        // rendering) sees the fallback content, exactly like view-level
        // `@slot` directives. Fast path: components without body slots keep
        // the original view (no tree clone).
        let materialized_view: Option<ViewTree> = comp
            .view
            .as_ref()
            .filter(|_| !comp.slots.is_empty())
            .map(|v| materialize_view_slots(v, comp, &slot_collision_names(comp)));
        // All view consumers borrow the materialized tree when body slots
        // exist, otherwise the original view.
        let view = materialized_view.as_ref().or(comp.view.as_ref());

        // Determine which React hooks are actually needed
        let has_computeds = !comp.computeds.is_empty();
        let has_fn_form_computed = comp.computeds.iter().any(|c| {
            matches!(&c.body, ExprIR::BlockExpr { statements, .. }
                if statements.iter().any(|s| matches!(s, StatementIR::ReturnStmtIR { .. })))
        });
        let has_effects_or_lifecycles = !comp.effects.is_empty() || !comp.lifecycles.is_empty();
        let has_motion = view.is_some_and(effect::view_has_motion_or_effects);
        let has_semantic_bindings = view.is_some_and(state::view_has_semantic_bindings);

        // Motion elements without a user @ref get synthesized `__el_N` refs.
        // Collected here (DFS pre-order over motion elements) so useRef
        // imports and declarations exist for them; the JSX emitter and the
        // motion effect emitter derive the same names from the same order.
        let mut motion_internal_refs: Vec<(String, String)> = Vec::new(); // (ref_name, tag)
        if let Some(view) = view {
            super::motion::walk_motion_elements(view, component_map, |el, idx| {
                if el.ref_binding.is_none() {
                    motion_internal_refs.push((format!("__el_{}", idx), el.tag.clone()));
                }
            });
        }
        // @hover/@press emit useCallback handlers wired into the JSX
        let has_interactive_motion =
            view.is_some_and(|v| super::motion::view_has_interactive_triggers(v, component_map));

        // Scan all code paths for signal mutations and function calls
        let called_fns = function::collect_called_local_fns(comp);
        let mutated_signals = state::collect_signal_mutations(comp, &called_fns);

        // Build comprehensive read-signals set: signals referenced in view, computeds,
        // effects, lifecycles, and called local functions.
        let mut read_signals = view
            .map(state::collect_view_read_signals)
            .unwrap_or_default();
        for computed in &comp.computeds {
            collect_expr_identifiers(&computed.body, &mut read_signals);
        }
        for effect in &comp.effects {
            // Effect dep arrays are emitted verbatim (`useEffect(..., [username, fontSize])`)
            // — a signal referenced ONLY as a dep must still get its hook,
            // or the emitted dep name is undeclared (TS2304).
            for dep in &effect.deps {
                read_signals.insert(dep.clone());
            }
            for stmt in &effect.body.statements {
                collect_stmt_identifiers(stmt, &mut read_signals);
            }
        }
        for lc in &comp.lifecycles {
            for stmt in &lc.body.statements {
                collect_stmt_identifiers(stmt, &mut read_signals);
            }
        }
        for fun in &comp.fns {
            if called_fns.contains(&fun.name) {
                for stmt in &fun.body.statements {
                    collect_stmt_identifiers(stmt, &mut read_signals);
                }
            }
        }
        if let Some(view) = view {
            state::collect_view_inline_handler_reads(view, &mut read_signals);
        }

        // Task 2.11 — write-only signal DCE: a signal whose VALUE is never
        // consumed by the generated output (its only reads are its own
        // mutation RHS, which emit as functional updaters `setX((c) => ...)`
        // that never reference the state value) gets NO useState hook and
        // its mutations are pruned — otherwise the state value lints as
        // unused (@typescript-eslint/no-unused-vars, the `playAll` class)
        // and the setter references an undeclared name. Mutated signals
        // that are never READ AT ALL keep the pre-existing behavior (their
        // setters still emit — deferral #72 documents the TS2304 class).
        // The prune is further restricted to signals whose mutations are
        // ALL call-free: a mutation with a call-carrying value may have
        // observable effects (and the setter-emission contract — e.g. the
        // array_sort comparator path in tests_regression — stays intact).
        //
        // The pruned set is ALSO intersected with comp.signals (review N1):
        // the bare-name candidate pool (`read ∩ mutated − consumed`) can
        // contain STORE FIELD names and body locals (store fields are
        // mutated by bare name like component signals, and their reads
        // never enter read_signals via the qualified path). Pruning a name
        // that is not a component signal would silently drop a store write
        // (observable by OTHER components) or a local reassignment — only
        // component signals may be pruned. The colliding store write (a
        // store field sharing a pruned component signal's name) is
        // protected at the EMISSION side by the field_object check
        // (generate_statement_tsx, review I1).
        // ── Phase 1: direct-write channel classification (D1/D2) ──
        // D1 (direct-write) / D2 (write-only) signals store in `useRef`
        // cells (`gen_direct_write_storage` below) instead of useState —
        // their render-path reads are consumed by the active style entries
        // and their mutations move to direct DOM writes (Task 3 emission
        // contract). The union set gates both the useState import decision
        // (has_mutable_states) and the per-signal skip (gen_state_hooks).
        // Computed BEFORE the pruned-signals analysis: D1/D2 mutations are
        // NOT dead code — they are the ref write itself (Task 3 必须项;
        // a D2 signal whose only read is its own mutation RHS would
        // otherwise be pruned and its write silently dropped).
        let direct_write_sets = direct_write::classify_direct_write(comp);
        let direct_write_names: FxHashSet<String> = direct_write_sets
            .d1
            .iter()
            .chain(direct_write_sets.d2.iter())
            .cloned()
            .collect();

        let value_consumed = collect_value_consumed_signals(comp);
        let mutation_call_targets = collect_call_mutation_targets(comp);
        // v4 H2: pruned 集合必须排除「有 mutation 但无读」的信号——它现在
        // 保留 useState（D-V4-6），mutation 不得被发射侧剪枝。
        let pruned_signals: FxHashSet<String> = read_signals
            .iter()
            .filter(|s| {
                mutated_signals.contains(*s)
                    && !value_consumed.contains(*s)
                    && !mutation_call_targets.contains(*s)
                    // Phase 1 (Task 3 必须项): D1/D2 直写域信号豁免剪枝——
                    // 它们的 mutation 是 ref 写入本身（非死代码），剪掉即
                    // 静默写丢失（aRef 声明但永无写入）。
                    && !direct_write_names.contains(*s)
            })
            .filter(|s| comp.signals.iter().any(|sig| &sig.name == *s))
            // 修正：写专用信号不在 read_signals 中，天然不在此集合——
            // 无需额外排除。此注释记录决策。
            .cloned()
            .collect();

        // Determine if any state actually needs useState (has active setter)
        // v4 H2: 计入写专用信号（现会发射 useState）；排除 pruned 信号
        // （mutation 被剪枝、无 setter 引用——hook 不发射，import 也不得
        // 触发，否则 unused import）。
        // Phase 1: 再排除 D1/D2 直写域信号（useRef 存储，不走 useState）。
        let has_mutable_states = comp.signals.iter().any(|s| {
            mutated_signals.contains(&s.name)
                && !pruned_signals.contains(&s.name)
                && !direct_write_names.contains(&s.name)
        });
        // Component-local fn names — used by the task 2.8 prop-fn analysis
        // (fns passed by value to child components) and by the fn emission
        // and state hooks below.
        let fn_names: FxHashSet<String> = comp.fns.iter().map(|f| f.name.clone()).collect();
        // Task 5.6 (deferral #61): names whose value may be undefined at an
        // event-handler call site. Event props are emitted as OPTIONAL props
        // (`onX?: (value: string) => void` — the parent may not wire the
        // event), so every `onX(...)` call site is a TS2722
        // possibly-undefined invocation (25 instances at the 0.6 snapshot:
        // TabBar 9, EmitEventChild 3, SignalPatternsDemo 2, Timer 2,
        // EmitChild 2, SlotBox/TodoItem/FnFormatter/CapabilityCard/AddTodo/
        // AboutPage/HomePage 1 each). A signal initialized with the null
        // literal is also possibly-null when invoked (the hoisted
        // `const f = null` shape / fn-typed signal with null default).
        // Local fns and lib fns are always defined — they stay bare `f(...)`.
        let mut possibly_undefined_handlers: FxHashSet<String> =
            comp.events.iter().map(|e| e.name.clone()).collect();
        for sig in &comp.signals {
            if matches!(&sig.initial_value, ExprIR::LiteralExpr { value } if value.is_null()) {
                possibly_undefined_handlers.insert(sig.name.clone());
            }
        }
        // Task 2.8 (perf M4) pass 1: local fns passed BY VALUE to child
        // component instances (bare identifier props / bare FnRef events).
        // Each becomes `const __omni_cb_<fn> = useCallback(<fn>, [reads])` —
        // the fn consts are recreated every render, and a memoized child
        // would see a fresh fn identity per render. The full memo ctx is
        // built later once the store/lib-fn sets exist.
        let wrapped_prop_fns: FxHashSet<String> = view
            .map(|v| collect_wrapped_prop_fns(v, component_map, &fn_names))
            .unwrap_or_default();
        let mut hooks: Vec<String> = Vec::new();
        if has_mutable_states {
            hooks.push("useState".to_string());
        }
        if has_computeds {
            hooks.push("useMemo".to_string());
        }
        if has_fn_form_computed || has_interactive_motion || !wrapped_prop_fns.is_empty() {
            hooks.push("useCallback".to_string());
        }
        if has_effects_or_lifecycles
            || has_motion
            || has_semantic_bindings
            || component_uses_pointer_ops(comp, view)
        {
            hooks.push("useEffect".to_string());
        }

        // Ref declarations → useRef (user @refs + synthesized motion refs)
        let has_refs = !comp.refs.is_empty() || !motion_internal_refs.is_empty();
        if has_refs {
            hooks.push("useRef".to_string());
        }

        // Design context — design classes/variant classes are global CSS in
        // design.css and are emitted as literal class names (HIGH #1); the
        // CSS module import is only needed for component-local classes.
        let design_ctx = super::design::DesignCtx::new(ir);
        let used_style_classes = view
            .map(jsx::collect_used_style_classes)
            .unwrap_or_default();
        let local_style_classes: FxHashSet<String> = used_style_classes
            .difference(&design_ctx.global_class_names)
            .cloned()
            .collect();
        // `@if mode: "fade"` renders branches inside a wrapper div carrying
        // the CSS-module `.omni-if-fade` class — forces the stylesheet
        // import so the fade rules (emitted by gen_component_css) exist.
        // The same predicate gates the CSS rules (gen_component_css), so the
        // import and the rules can never diverge.
        let has_if_fade = component_has_fade_conditional(comp);
        let has_styles = !local_style_classes.is_empty()
            || (!comp.styles.is_empty()
                && local_style_classes
                    .iter()
                    .any(|c| comp.styles.iter().any(|s| &s.class_name == c)))
            || has_if_fade;

        // Props interface check — slot declarations also become props
        // (`children` for the unnamed slot, same-named props for named
        // slots). Body-level `@slot` declarations (ADR-053 D5) plus
        // view-level directives (back-compat).
        let declared_slots = jsx::component_declared_slots(comp, component_map);
        let has_props =
            !comp.props.is_empty() || !comp.events.is_empty() || !declared_slots.is_empty();

        // ── Store-related computation ──
        let all_stores = ir.all_stores();
        let used_store_signals = state::collect_used_store_signals(comp);
        // T3.3: per-store referenced fields (reads + action calls), from all
        // component bodies. Covers the IR forms the identifier collectors
        // miss (StoreFieldAccessExpr aliases, bind:value names, StoreAction
        // refs) so used_store_refs and the slice plan agree. Also returns
        // BARE store-alias identifier references (review LOW-3) — a store
        // referenced as a value keeps the whole-store object.
        let (mut comp_store_field_refs, mut bare_store_refs) =
            store_slices::collect_component_store_field_refs(comp, view);
        // Task 2.10 (perf M1): motion-context store references (motion value
        // expressions + trigger control dimensions) merge into the component
        // refs map HERE — before used_store_refs and the slice plan — so the
        // store is subscribed (per-field) and its slice locals reach the
        // motion formatters. Previously these references forced the
        // whole-store subscription (motion formatting carried no renames).
        let (motion_field_refs, motion_bare_refs) =
            store_slices::motion_store_field_refs(view, ir, component_map);
        for (store, fields) in motion_field_refs {
            comp_store_field_refs
                .entry(store)
                .or_default()
                .extend(fields);
        }
        bare_store_refs.extend(motion_bare_refs);

        let local_names: FxHashSet<String> = comp
            .signals
            .iter()
            .map(|s| s.name.clone())
            .chain(comp.props.keys().cloned())
            .chain(comp.fns.iter().map(|f| f.name.clone()))
            .collect();

        let mut used_store_refs: FxHashSet<String> = FxHashSet::default();
        for store_ref in &comp.store_refs {
            if used_store_signals.contains(store_ref.as_str())
                || comp_store_field_refs.contains_key(store_ref.as_str())
            {
                used_store_refs.insert(store_ref.clone());
                continue;
            }
            if let Some(store) = all_stores.get(store_ref.as_str()) {
                for sig_name in store.signals.keys() {
                    if !local_names.contains(sig_name) && used_store_signals.contains(sig_name) {
                        used_store_refs.insert(store_ref.clone());
                        break;
                    }
                }
            }
        }

        // Build signal_names (all state + store aliases), store_signal_map
        // (signal → "StoreRef.signal" for effect deps) and store_signal_owners
        // (signal → "StoreRef" for setState mutations, C7).
        let mut signal_names: FxHashSet<String> =
            comp.signals.iter().map(|s| s.name.clone()).collect();
        let mut store_signal_map: FxHashMap<String, String> = FxHashMap::default();
        let mut store_signal_owners: FxHashMap<String, String> = FxHashMap::default();
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            signal_names.insert(store_ref.clone());
            if let Some(store) = ir.all_stores().get(store_ref.as_str()) {
                for sig_name in store.signals.keys() {
                    signal_names.insert(sig_name.clone());
                    store_signal_map
                        .insert(sig_name.clone(), format!("{}.{}", store_ref, sig_name));
                    store_signal_owners.insert(sig_name.clone(), store_ref.clone());
                }
            }
        }

        // Build ref_names set for expression translation (ADR-036 Phase 2).
        // Phase 1 (Task 3): extend with D1/D2 names — inside fn/effect/
        // lifecycle/computed/inline-handler bodies, reads of D1/D2 signals
        // must resolve to `{name}Ref.current` (the always-live value; the
        // render path never consumes them). This one extension is the
        // read-resolution mechanism: every statement site flows through
        // ReactFormatExpr.format_identifier via the shared ref_names set.
        let mut ref_names: FxHashSet<String> = comp.refs.iter().map(|r| r.name.clone()).collect();
        ref_names.extend(direct_write_names.iter().cloned());
        // Apply-line table: signal → direct DOM write injected after its
        // mutations (D1 entries only; D2 has no output reads).
        let direct_write_applies = direct_write::build_apply_map(&direct_write_sets, &ref_names);

        // Ref name → element tag map (typing useRef declarations) — scanned
        // from the view because RefDeclIR.element_tag is not populated by
        // lowering yet.
        let ref_tags = state::collect_ref_tags(view);

        // Motion animation names — used to filter motion refs from event handlers
        let motion_names: FxHashSet<String> = ir
            .modules
            .values()
            .flat_map(|m| &m.motions)
            .map(|m| m.name.clone())
            .collect();
        // Motion name → body map (module-level + component-level @motion
        // defs; inline bodies are hoisted to named motions by lowering).
        // Shared by the module-scoped `_M` table emitter and the per-element
        // effects emitter.
        let motion_map: FxHashMap<String, MotionBodyIR> = ir
            .modules
            .values()
            .flat_map(|m| &m.motions)
            .map(|m| (m.name.clone(), m.body.clone()))
            .collect();

        // ── Design runtime wiring (root component only) ──
        // The root component mounts the design system: it imports and calls
        // the `useDesignTokens` hooks (dynamic token effects) and the
        // `useThemeStore` hook when a @theme signal is wired (v2 D1 —
        // useEffect data-theme subscription), or side-effect-imports the
        // legacy store otherwise, so design runtime behavior activates with
        // the app (HIGH #2).
        let is_root = super::design::is_root_component(name, ir);
        let design_wiring = if is_root {
            super::design::root_design_wiring(ir, comp.source_file.as_deref())
        } else {
            super::design::DesignWiring {
                import_lines: Vec::new(),
                hook_calls: Vec::new(),
            }
        };

        // ── Active-pointer tracker (design D3) ──
        // `capturePointer()`/`releasePointer()` are parameterless — they act
        // on the ACTIVE pointer. Ref ops can be called from fns/effects/
        // lifecycles where no event object is in scope, so the tracker
        // records the most recent pointerdown's id (capture-phase so it
        // fires before element-level handlers). The state lives at module
        // scope (ref ops reference it from any context); the LISTENER
        // registers in a mount effect inside the component — a module-level
        // `window.addEventListener` is a module-scope side effect (task
        // 2.11, L1). Emitted only when the component actually uses the
        // pointer-capture ops.
        if component_uses_pointer_ops(comp, view) {
            w.emit("");
            w.emit("// Active pointer tracking for ref.capturePointer()/releasePointer()");
            w.emit("// (parameterless DSL form — the most recent pointerdown's id is retained,");
            w.emit("// so a later releasePointer() can release it).");
            w.emit("let __omni_activePointerId: number | null = null;");
            w.emit("// The capture-phase pointerdown listener registers in a mount effect");
            w.emit("// (see the component body) and is removed on unmount.");
        }

        // ── Library functions ──
        let mut used_fn_names: FxHashSet<String> = FxHashSet::default();
        for computed in &comp.computeds {
            collect_expr_identifiers(&computed.body, &mut used_fn_names);
        }
        for effect in &comp.effects {
            for stmt in &effect.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        for lc in &comp.lifecycles {
            for stmt in &lc.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        for fun in &comp.fns {
            for stmt in &fun.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        if let Some(view) = view {
            jsx::collect_view_identifiers(view, &mut used_fn_names);
        }
        if let Some(view) = view {
            jsx::collect_motion_identifiers(view, &mut used_fn_names);
        }

        let all_lib_fns: Vec<&FunctionIR> = ir.all_functions();
        // Transitive closure: a lib fn used from the view may delegate to
        // other lib fns — every callee referenced by an emitted body needs
        // a declaration too (previously only the view-referenced entry was
        // emitted → TS2304 on the inner call).
        let mut prev_len = 0;
        while used_fn_names.len() > prev_len {
            prev_len = used_fn_names.len();
            for fun in &all_lib_fns {
                if used_fn_names.contains(&fun.name) {
                    for stmt in &fun.body.statements {
                        collect_stmt_identifiers(stmt, &mut used_fn_names);
                    }
                }
            }
        }
        let lib_fns: Vec<&&FunctionIR> = all_lib_fns
            .iter()
            .filter(|f| used_fn_names.contains(&f.name))
            .collect();

        // ── T3.3: store slice subscription plan ──
        // Decide per store between per-field slice selectors and the
        // whole-store object (collision/shadowing fallback), and build the
        // `"Store.field" → slice local` rename map threaded through every
        // read/action emission site below.
        // Library functions are intentionally excluded (review LOW-4): they
        // are emitted at module scope, where neither the slice locals nor a
        // whole-store const exist, so their store references keep the
        // pre-existing (qualified) output.
        let shadowing_names = store_slices::collect_shadowing_names(comp, view);
        let (store_field_renames, slice_fields) = store_slices::build_slice_plan(
            comp,
            &comp_store_field_refs,
            &shadowing_names,
            &bare_store_refs,
            &all_stores,
        );

        // ── Task 2.8 (perf M4): prop-fn useCallback + React.memo for
        // slot-free children ──
        // ① A component-local fn passed BY VALUE to a child component
        // instance is recreated every render (`const handleAdd = ...` sits
        // inside the component body) — wrapping it in useCallback keeps the
        // identity stable. ② A children-free instance whose props are all
        // render-stable forms (literals / signals / computeds / props /
        // store refs / wrapped fns) instantiates the `Memoized<Child>`
        // React.memo alias — ① is the precondition that keeps fn props from
        // defeating the shallow compare; slot-receiving instances are never
        // memoized (children is a fresh element tree every render).
        let lib_fn_names: FxHashSet<String> = lib_fns.iter().map(|f| f.name.clone()).collect();
        let prop_fn_ctx = collect_prop_fn_memo_ctx(
            view,
            comp,
            component_map,
            &fn_names,
            &lib_fn_names,
            &store_signal_map,
            &used_store_refs,
            &store_field_renames,
            &wrapped_prop_fns,
        );

        // ── Emit imports ──
        let comp_imports = imports::collect_component_imports(
            comp,
            ir,
            component_map,
            &used_store_refs,
            &hooks,
            has_styles,
            &design_wiring.import_lines,
            !prop_fn_ctx.memo_children.is_empty(),
        );
        comp_imports.emit(&mut w, name, comp, has_props);

        // ── Phase 1: sanitizeCss helper (apply 直写值特例) ──
        // apply 值含 $concat/$call/$field（动态拼接用户可控字符串）时，与
        // OmniView __omni_sanitizeCss 行为对齐包裹 sanitizeCss(...)——模块
        // 级 helper 在组件头部发射（react/design.rs 动态 token 同点；每文件
        // 一组件，无重复发射风险）。
        if direct_write::apply_needs_sanitize(&direct_write_sets) {
            w.emit("");
            super::design::emit_sanitize_css(&mut w);
            w.emit("");
        }

        // ── User type declarations (deferral #49) ──
        // Structs/unions/aliases referenced by THIS file's annotations are
        // declared inline at module scope: props interface, event param
        // types, signal types (the useState generic below), local fn params
        // and inlined lib fn params (`error_message(result: ApiResult)`).
        // The referenced set is closed transitively (a struct field may
        // reference another user type). TS type aliases are hoisted, so the
        // declarations may precede or follow their first use — emitted here,
        // before the inlined lib fns, for readability.
        let user_types = super::types::user_type_names(ir);
        let mut type_refs: FxHashSet<String> = FxHashSet::default();
        for ty in comp.props.values() {
            super::types::collect_annotation_refs(ty, &user_types, &mut type_refs);
        }
        // Signal types count ONLY when the useState emission actually
        // annotates them (mutated + value-consumed — gen_state_hooks' exact
        // gate): a non-mutated struct-typed signal emits a bare `const`
        // with no annotation, and declaring its type would be an unused
        // declaration (eslint no-unused-vars — FeatureCard's StatisticsData).
        for signal in &comp.signals {
            if mutated_signals.contains(&signal.name) && value_consumed.contains(&signal.name) {
                super::types::collect_annotation_refs(&signal.r#type, &user_types, &mut type_refs);
            }
        }
        // fn/lib-fn RETURN types are NOT scanned: the React target emits no
        // return annotations (`const getStats = () => {...}`) — collecting
        // them would declare unused types (eslint no-unused-vars;
        // FeatureCard's StatisticsData return annotation).
        for fun in &comp.fns {
            for p in &fun.params {
                if let Some(t) = &p.r#type {
                    super::types::collect_annotation_refs(t, &user_types, &mut type_refs);
                }
            }
        }
        for fun in &lib_fns {
            for p in &fun.params {
                if let Some(t) = &p.r#type {
                    super::types::collect_annotation_refs(t, &user_types, &mut type_refs);
                }
            }
        }
        for event in &comp.events {
            super::types::collect_ts_string_refs(&event.param_type, &user_types, &mut type_refs);
        }
        super::types::close_type_refs(ir, &user_types, &mut type_refs);
        super::types::emit_type_declarations(&mut w, ir, &type_refs);
        if !type_refs.is_empty() {
            w.emit("");
        }

        for fun in &lib_fns {
            let param_names: Vec<(String, bool)> = fun
                .params
                .iter()
                .map(|p| {
                    let escaped = escape_js_ident(&p.name);
                    let needs_rename = escaped != p.name;
                    (escaped, needs_rename)
                })
                .collect();
            let params_str = function::format_fn_params(fun);
            let is_async =
                fun.is_async || fun.body.statements.iter().any(effect::stmt_contains_await);
            let async_prefix = if is_async { "async " } else { "" };
            w.emit_fmt(format_args!(
                "const {} = {}({}) => {{",
                fun.name, async_prefix, params_str
            ));
            w.indent();
            let mut body_w = crate::codegen::CodeWriter::new();
            body_w.indent();
            let tail_idx = fun.body.statements.len().saturating_sub(1);
            for (i, stmt) in fun.body.statements.iter().enumerate() {
                if i == tail_idx {
                    if let StatementIR::ExprStmtIR { .. } = stmt {
                        // H1 (ts/react): the lib fn's trailing expression IS
                        // its return value — `return <expr>;` (the generic
                        // `{expr};` emission dropped match/block tail values;
                        // DataFetching's `error_message` returned undefined
                        // and its success branch was unreachable).
                        function::emit_fn_tail_return(
                            &mut body_w,
                            stmt,
                            &FxHashSet::default(),
                            &store_signal_owners,
                            &ref_names,
                            &FxHashMap::default(),
                            &FxHashSet::default(),
                            &FxHashSet::default(),
                            &FxHashSet::default(),
                            &FxHashMap::default(),
                        );
                        continue;
                    }
                }
                // No store-field renames here: lib fns are module-scope and
                // the slice locals (or whole-store const) live inside the
                // component — qualified output kept (review LOW-4).
                expr::generate_statement_tsx(
                    &mut body_w,
                    stmt,
                    &FxHashSet::default(),
                    &store_signal_owners,
                    &ref_names,
                    &FxHashMap::default(),
                    &FxHashSet::default(),
                    &FxHashSet::default(),
                    &FxHashSet::default(),
                    &FxHashMap::default(),
                );
            }
            let mut body_str = body_w.into_string();
            for (i, (new_name, needs_rename)) in param_names.iter().enumerate() {
                if *needs_rename {
                    let old_name = &fun.params[i].name;
                    body_str = body_str.replace(old_name, new_name);
                }
            }
            for line in body_str.lines() {
                w.emit(line);
            }
            w.dedent();
            w.emit("};");
        }
        if !lib_fns.is_empty() {
            w.emit("");
        }

        // ── Module-scoped motion table (task 2.6, perf L1) ──
        // `_M` maps motion names → WAAPI keyframes; motion definitions are
        // compile-time constants, so the table was re-allocated inside the
        // component function on every render (perf L1) and every `_M["x"]`
        // use site saw a fresh object identity (exhaustive-deps errors).
        // Hoisted to module scope when every referenced motion is constant;
        // a motion carrying non-literal values (store fields, signals —
        // resolved at render time) keeps the table in-function (the 2.10
        // slice channel unblocks the store case, deferred).
        let motion_table_hoisted = view
            .map(|v| motion::emit_motion_table_module_scope(&mut w, v, &motion_map))
            .unwrap_or(false);

        // ── Task 2.8 (perf M4): React.memo aliases for children with
        // memoizable instances ──
        // `Memoized<Child>` wraps the imported child component; children-free
        // instances whose props are all render-stable (literals / signals /
        // computeds / props / store refs / useCallback-wrapped fns)
        // instantiate the alias, so prop-shallow-equal re-renders skip the
        // child entirely (list-cascade elimination). The local fns passed as
        // props are useCallback-wrapped inside the component below — without
        // stable fn identity the shallow compare would never hit.
        if !prop_fn_ctx.memo_children.is_empty() {
            let mut memo_children: Vec<&String> = prop_fn_ctx.memo_children.iter().collect();
            memo_children.sort();
            for child in memo_children {
                w.emit_fmt(format_args!(
                    "const Memoized{} = React.memo({});",
                    child, child
                ));
            }
            w.emit("");
        }

        // ── Task 2.9 (perf M3): hoist never-mutated literal signals ──
        // A signal initialized with a pure literal (`signal items =
        // ["a", "b"]`) and never mutated was re-allocated inside the
        // component function on EVERY render; a computed/memo depending on
        // it recomputed every render because the deps compared a fresh
        // array identity (FilterBar `demoFrameworks` + `filteredFrameworks`
        // memo). Hoisted to module scope: one allocation per module, stable
        // identity across renders. The hoist must agree with the useState
        // decision (never-mutated only) and must not collide with the
        // module-scope bindings already in this file (component fn name,
        // imports, lib fns, memo aliases, internal tables) — a duplicate
        // `const` at module scope is a redeclaration SyntaxError.
        let mut module_reserved_names: FxHashSet<String> = FxHashSet::default();
        module_reserved_names.insert(name.to_string());
        module_reserved_names.insert("_M".to_string());
        module_reserved_names.insert("__omni_activePointerId".to_string());
        module_reserved_names.insert("React".to_string());
        module_reserved_names.extend(hooks.iter().cloned());
        if has_styles {
            module_reserved_names.insert("styles".to_string());
        }
        module_reserved_names.extend(used_store_refs.iter().map(|r| format!("use{}", r)));
        module_reserved_names.extend(lib_fn_names.iter().cloned());
        module_reserved_names.extend(
            prop_fn_ctx
                .memo_children
                .iter()
                .map(|c| format!("Memoized{}", c)),
        );
        module_reserved_names.extend(design_wiring.hook_calls.iter().cloned());
        let hoisted_signals = state::collect_hoistable_literal_signals(
            comp,
            &read_signals,
            &mutated_signals,
            &module_reserved_names,
        );
        state::gen_hoisted_signal_consts(
            &mut w,
            comp,
            &hoisted_signals,
            &store_field_renames,
            &user_types,
        );

        // Component function signature
        if !has_props {
            w.emit_fmt(format_args!("export function {}() {{", name));
        } else {
            let mut prop_list: Vec<String> = comp
                .props
                .keys()
                .map(|prop_name| {
                    if let Some(default_val) = comp.prop_defaults.get(prop_name) {
                        let default_tsx = expr::format_expr_ir_tsx(default_val, &ref_names);
                        format!("{} = {}", prop_name, default_tsx)
                    } else {
                        prop_name.clone()
                    }
                })
                .collect();
            for event in &comp.events {
                if read_signals.contains(event.name.as_str()) {
                    prop_list.push(event.name.clone());
                }
            }
            // Slot props must be destructured so `{children}` / `{header}`
            // render correctly in the JSX body. A slot whose prop name
            // collides with a signal/computed/function is skipped — the
            // semantic layer warns on the collision, and the hook/function
            // declaration would shadow (or duplicate) the destructured name.
            let slot_collides: FxHashSet<&str> = comp
                .signals
                .iter()
                .map(|s| s.name.as_str())
                .chain(comp.computeds.iter().map(|c| c.name.as_str()))
                .chain(comp.fns.iter().map(|f| f.name.as_str()))
                .collect();
            for slot_name in &declared_slots {
                let slot_prop = slot_name.as_deref().unwrap_or("children").to_string();
                if !prop_list.iter().any(|p| p == &slot_prop)
                    && !slot_collides.contains(slot_prop.as_str())
                {
                    prop_list.push(slot_prop);
                }
            }
            if prop_list.is_empty() {
                w.emit_fmt(format_args!(
                    "export function {}(_props: {}Props) {{",
                    name, name
                ));
            } else {
                w.emit_fmt(format_args!(
                    "export function {}({{ {} }}: {}Props) {{",
                    name,
                    prop_list.join(", "),
                    name
                ));
            }
        }
        w.indent();

        // Store hooks — per-field slice selectors by default (T3.3,
        // perf HIGH-1/H2): `const items = useTodoStore((s) => s.items);`
        // so a store write only re-renders the components that read the
        // changed field. Stores with name collisions / inner-scope capture
        // keep the whole-store object (`const TodoStore = useTodoStore();`)
        // — their reads stay qualified and unambiguous.
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            if let Some(store) = all_stores.get(store_ref.as_str()) {
                if let Some(fields) = slice_fields.get(store_ref.as_str()) {
                    store_slices::emit_store_slices(&mut w, store_ref, store, fields);
                } else {
                    let hook_name = format!("use{}", store_ref);
                    w.emit_fmt(format_args!("const {} = {}();", store_ref, hook_name));
                }
            }
        }

        // Design system hooks — called from the root component so the
        // dynamic-token effects and theme subscription activate (HIGH #2).
        if is_root {
            for hook_call in &design_wiring.hook_calls {
                w.emit_fmt(format_args!("{}();", hook_call));
            }
        }

        // State hooks + effects. gen_state_hooks skips signals whose value
        // is never consumed (write-only DCE, task 2.11 — a signal read only
        // via its own mutation RHS emits a functional-update setter and the
        // state value stays unread).
        self.gen_state_hooks(
            &mut w,
            comp,
            &value_consumed,
            &mutated_signals,
            &pruned_signals,
            &hoisted_signals,
            &direct_write_names,
            &fn_names,
            &store_field_renames,
            &user_types,
        );
        state::gen_ref_hooks(&mut w, comp, &ref_tags, &motion_internal_refs);
        // Phase 1: D1/D2 signal storage — `const nameRef = useRef<T>(init);`
        // cells replacing the useState path (reads/mutations resolve to
        // `{name}Ref.current`; Task 3 emission contract).
        direct_write::gen_direct_write_storage(&mut w, comp, &direct_write_sets, &user_types);
        // ── Active-pointer tracker listener (task 2.11, L1) ──
        // Registered in a mount effect, removed on unmount — the old
        // module-level `if (typeof window ...) window.addEventListener(...)`
        // was a module-scope side effect (fires on import, never removed).
        // `e` is inferred as PointerEvent by the addEventListener overload
        // (same inference the previous module-level arrow used).
        if component_uses_pointer_ops(comp, view) {
            w.emit("useEffect(() => {");
            w.indent();
            // Explicit PointerEvent: a const-arrow passed to addEventListener
            // does NOT get contextual typing in tsc (the drag handlers'
            // `(e) =>` params are TS7006-exempted for the same reason) — an
            // untyped param here would add a NEW TS7006 to the gate.
            w.emit("const onPointerDown = (e: PointerEvent) => {");
            w.indent();
            w.emit("__omni_activePointerId = e.pointerId;");
            w.dedent();
            w.emit("};");
            w.emit("window.addEventListener(\"pointerdown\", onPointerDown, true);");
            w.emit("return () => {");
            w.indent();
            w.emit("window.removeEventListener(\"pointerdown\", onPointerDown, true);");
            w.dedent();
            w.emit("};");
            w.dedent();
            w.emit("}, []);");
        }
        // Store alias → reactive fields (signals + getters) — the unmount
        // cleanup dep derivation distinguishes field reads from action calls
        // against this map (mirrors the semantic validate_effect_deps
        // universe; actions are never reactive).
        let store_fields: FxHashMap<String, FxHashSet<String>> = all_stores
            .iter()
            .map(|(name, store)| {
                let mut fields = FxHashSet::default();
                fields.extend(store.signals.keys().cloned());
                fields.extend(store.getters.keys().cloned());
                (name.to_string(), fields)
            })
            .collect();
        // Store alias → action names — the task 2.8 deps collector resolves
        // `TodoStore.add(x)` calls to the action slice local (or the
        // qualified name) exactly like signal-field reads.
        let store_actions: FxHashMap<String, FxHashSet<String>> = all_stores
            .iter()
            .map(|(name, store)| {
                let mut actions = FxHashSet::default();
                actions.extend(store.actions.iter().map(|a| a.name.clone()));
                (name.to_string(), actions)
            })
            .collect();
        self.gen_effects(
            &mut w,
            comp,
            &store_signal_map,
            &store_signal_owners,
            &signal_names,
            &ref_names,
            &store_field_renames,
            &store_fields,
            &hoisted_signals,
            &pruned_signals,
            &possibly_undefined_handlers,
            &direct_write_names,
            &direct_write_applies,
        );
        state::gen_semantic_binding_effects(
            &mut w,
            view,
            &store_signal_map,
            &ref_names,
            &store_field_renames,
            &hoisted_signals,
        );

        // Computed values (useMemo / useCallback)
        let mut known_signal_names: Vec<String> =
            comp.signals.iter().map(|s| s.name.clone()).collect();
        known_signal_names.extend(comp.store_refs.iter().cloned());
        known_signal_names.extend(comp.computeds.iter().map(|c| c.name.clone()));
        computed::gen_computed_values(
            &mut w,
            comp,
            &known_signal_names,
            &signal_names,
            &store_signal_owners,
            &ref_names,
            &store_field_renames,
            &hoisted_signals,
            &pruned_signals,
            &possibly_undefined_handlers,
            &direct_write_names,
            &direct_write_applies,
        );

        // Component-local function declarations
        self.gen_functions(
            &mut w,
            comp,
            &called_fns,
            &signal_names,
            &store_signal_owners,
            &fn_names,
            &ref_names,
            &store_field_renames,
            &pruned_signals,
            &possibly_undefined_handlers,
            &direct_write_names,
            &direct_write_applies,
        );

        // ── Task 2.8 (perf M4): useCallback wrappers for prop fns ──
        // The fn consts above are recreated every render, so a memoized
        // child would see a fresh fn identity per render (the memo shallow
        // compare never hits). Deps derive from the fn's reactive reads
        // (2.6 collector + fn-param shadowing + transitive local-fn calls) —
        // the wrapper re-creates exactly when a captured value changes.
        if !prop_fn_ctx.wrapped_fns.is_empty() {
            let mut wrapped_fns: Vec<String> = prop_fn_ctx.wrapped_fns.iter().cloned().collect();
            wrapped_fns.sort();
            for fn_name in &wrapped_fns {
                if let Some(fun) = comp.fns.iter().find(|f| f.name == *fn_name) {
                    // Fix round F1: D1/D2 names are useRef-stored — the
                    // wrapper reads `{name}Ref.current` at call time (always
                    // the live value), and the ref identity is stable across
                    // renders, so a D1/D2 dep adds nothing to the re-creation
                    // decision and is filtered out. Emitting the bare name
                    // would be TS2304 (`{name}` is not declared), and
                    // emitting `{name}Ref` would trip eslint
                    // exhaustive-deps ("unnecessary dependency").
                    let deps: Vec<String> = effect::fn_read_deps(
                        fun,
                        comp,
                        &fn_names,
                        &store_signal_map,
                        &store_field_renames,
                        &store_fields,
                        &store_actions,
                        &used_store_refs,
                        &hoisted_signals,
                    )
                    .into_iter()
                    .filter(|d| !direct_write_names.contains(d))
                    .collect();
                    w.emit_fmt(format_args!(
                        "const __omni_cb_{} = useCallback({}, [{}]);",
                        fn_name,
                        fn_name,
                        deps.join(", ")
                    ));
                }
            }
            w.emit("");
        }

        // Motion animation effects — per-ref native effects (all triggers).
        // Task 2.10 (perf M1): the store-field renames thread into the
        // in-function `_M` table and the trigger control dimensions — a
        // store-ref motion keeps the table in-function (2.6: slice locals
        // are component-scope, a module-level table cannot see them), and
        // its `Store.field` reads resolve to the slice locals.
        if let Some(view) = view {
            motion_effects::gen_motion_effects(
                &mut w,
                view,
                &motion_map,
                component_map,
                motion_table_hoisted,
                &store_field_renames,
            );
        }

        w.emit("");

        // Render return (JSX view tree) — the materialized view (body-slot
        // declarations already converted to `ViewTree::Slot` nodes).
        let mut motion_counter = 0usize;
        self.gen_jsx_return(
            &mut w,
            view,
            comp,
            component_map,
            &design_ctx,
            &signal_names,
            &store_signal_owners,
            &motion_names,
            name,
            &ref_names,
            &store_field_renames,
            &pruned_signals,
            &possibly_undefined_handlers,
            &direct_write_names,
            &direct_write_applies,
            &mut motion_counter,
            &prop_fn_ctx,
        );
        w.dedent();
        w.emit("}");
        w.emit("");

        w.into_string()
    }

    /// Generate a CSS module file from component styles.
    pub(super) fn gen_component_css(&self, name: &str, comp: &ComponentIR) -> String {
        let mut w = CodeWriter::new();
        w.emit_fmt(format_args!("/* Styles for {} */", name));
        crate::codegen::generate_css_style_block(&mut w, &comp.styles);
        // `@if mode: "fade"` — wrapper class + keyframes. Defined and
        // referenced within the same CSS module so the bundler scopes the
        // class name and the keyframe name consistently.
        if component_has_fade_conditional(comp) {
            w.emit("");
            w.emit(".omni-if-fade {");
            w.indent();
            w.emit("opacity: 0;");
            w.emit("animation: omni-if-fade 300ms ease-out forwards;");
            w.dedent();
            w.emit("}");
            w.emit("@keyframes omni-if-fade {");
            w.indent();
            w.emit("from { opacity: 0; }");
            w.emit("to { opacity: 1; }");
            w.dedent();
            w.emit("}");
            // prefers-reduced-motion: skip the animation, show content
            // immediately (never hide it).
            w.emit("@media (prefers-reduced-motion: reduce) {");
            w.indent();
            w.emit(".omni-if-fade {");
            w.indent();
            w.emit("animation: none;");
            w.emit("opacity: 1;");
            w.dedent();
            w.emit("}");
            w.dedent();
            w.emit("}");
        }
        w.into_string()
    }
}

/// Whether the component declares any `@if mode: "fade"` conditional — in
/// the view itself (including view-level `@slot` fallbacks, which are
/// already `ViewTree::Slot` nodes) or inside a body-declared slot fallback
/// (which the JSX emitter sees after slot materialization).
///
/// This single predicate gates BOTH the CSS-module import (`has_styles` →
/// `import styles`, component/imports.rs) and the fade rules in the CSS
/// module (`gen_component_css`) — the two must never diverge: a component
/// whose only fade sits in a body-slot fallback would otherwise reference
/// `styles['omni-if-fade']` with no import, producing `styles` undefined in
/// the generated TSX.
fn component_has_fade_conditional(comp: &ComponentIR) -> bool {
    comp.view
        .as_ref()
        .is_some_and(super::motion::view_has_fade_conditional)
        || comp.slots.iter().any(|s| {
            s.fallback
                .iter()
                .any(super::motion::view_has_fade_conditional)
        })
}

