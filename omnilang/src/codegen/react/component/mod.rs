/// Collect identifier references from an ExprIR.
///
/// Traversal uses the shared IR walker (`crate::ir::walk::walk_expr`) — the
/// pass is a pure filter collecting `IdentifierExpr` names plus `CallExpr`
/// callee names (the callee name is not an `ExprIR` child, so it is
/// collected at the `CallExpr` node itself). `RefOpExpr` child arguments are
/// covered by the walker's `RefOpIR` descent (Task 5.5 walker convergence).
///
/// One surface is NOT expressible through the walker's `&ExprIR` callback:
/// `emit onX(...)` statements in expression-level blocks (`BlockExpr`
/// statements, `MatchExpr` arm bodies) carry the event name on the
/// STATEMENT (`EventEmitStmtIR.event_name`, a `String`), never on an
/// `ExprIR` node. The generated `onX(...)` call references the event prop
/// verbatim, so the name must still count as a read — otherwise the event
/// prop is never destructured and the generated file fails with TS2304.
/// `collect_expr_emit_names` covers exactly that surface (statement-level
/// emit in fns/effects is already collected via `collect_stmt_identifiers`).
pub(super) fn collect_expr_identifiers(expr: &ExprIR, acc: &mut FxHashSet<String>) {
    walk::walk_expr(expr, &mut |e| match e {
        ExprIR::IdentifierExpr { name, .. } => {
            acc.insert(name.clone());
        }
        ExprIR::CallExpr { name, .. } => {
            acc.insert(name.clone());
        }
        _ => {}
    });
    collect_expr_emit_names(expr, acc);
}

/// Collect `EventEmitStmtIR` event names from expression-level blocks.
///
/// The shared walker cannot surface statement-level data, so this targeted
/// scanner (Task 5.5 review Important-1) walks every `BlockExpr` /
/// `MatchExpr` arm body in the expression tree — the only places statements
/// live inside expressions — and descends through nested statement bodies
/// (`if`/`while`/`for`/`try`/block statements), mirroring the statement
/// coverage `collect_stmt_identifiers` provides at statement level.
fn collect_expr_emit_names(expr: &ExprIR, acc: &mut FxHashSet<String>) {
    walk::walk_expr(expr, &mut |e| match e {
        ExprIR::BlockExpr { statements, .. } => {
            collect_block_emit_names(statements, acc);
        }
        ExprIR::MatchExpr { arms, .. } => {
            for arm in arms {
                collect_block_emit_names(&arm.body.statements, acc);
            }
        }
        _ => {}
    });
}

/// Collect emit event names from a statement list, descending through
/// nested statement bodies (the statement-level mirror of
/// `collect_stmt_identifiers`' traversal — only the emit surface).
fn collect_block_emit_names(statements: &[StatementIR], acc: &mut FxHashSet<String>) {
    for stmt in statements {
        collect_stmt_emit_names(stmt, acc);
    }
}

/// Collect the event name of an `emit` statement, recursing into nested
/// statement bodies.
fn collect_stmt_emit_names(stmt: &StatementIR, acc: &mut FxHashSet<String>) {
    match stmt {
        StatementIR::EventEmitStmtIR { event_name, .. } => {
            acc.insert(event_name.clone());
        }
        StatementIR::IfStmtIR {
            then_body,
            else_ifs,
            else_body,
            ..
        } => {
            collect_block_emit_names(&then_body.statements, acc);
            for (_, body) in else_ifs {
                collect_block_emit_names(&body.statements, acc);
            }
            if let Some(body) = else_body {
                collect_block_emit_names(&body.statements, acc);
            }
        }
        StatementIR::WhileStmtIR { body, .. } | StatementIR::ForInStmtIR { body, .. } => {
            collect_block_emit_names(&body.statements, acc)
        }
        StatementIR::BlockStmtIR { body } => collect_block_emit_names(&body.statements, acc),
        StatementIR::TryCatchStmtIR {
            try_body,
            catch_body,
            finally_body,
            ..
        } => {
            collect_block_emit_names(&try_body.statements, acc);
            if let Some(body) = catch_body {
                collect_block_emit_names(&body.statements, acc);
            }
            if let Some(body) = finally_body {
                collect_block_emit_names(&body.statements, acc);
            }
        }
        _ => {}
    }
}

/// True when the component calls the parameterless pointer-capture ref ops
/// (`ref.capturePointer()` / `ref.releasePointer()`, design D3) anywhere —
/// fns, effects, lifecycles, computeds, and the view tree. Gates the
/// module-scope active-pointer tracker in the generated file (the ops
/// themselves reference `__omni_activePointerId`).
fn component_uses_pointer_ops(comp: &ComponentIR, view: Option<&ViewTree>) -> bool {
    for f in &comp.fns {
        if f.body.statements.iter().any(stmt_has_pointer_ops) {
            return true;
        }
    }
    for e in &comp.effects {
        if e.body.statements.iter().any(stmt_has_pointer_ops) {
            return true;
        }
    }
    for lc in &comp.lifecycles {
        if lc.body.statements.iter().any(stmt_has_pointer_ops) {
            return true;
        }
    }
    for c in &comp.computeds {
        if expr_has_pointer_ops(&c.body) {
            return true;
        }
    }
    view.is_some_and(view_has_pointer_ops)
}

/// True when a statement subtree contains a CapturePointer/ReleasePointer op.
fn stmt_has_pointer_ops(stmt: &StatementIR) -> bool {
    match stmt {
        StatementIR::ExprStmtIR { expr } | StatementIR::ThrowStmtIR { expr } => {
            expr_has_pointer_ops(expr)
        }
        StatementIR::LetStmtIR { value, .. } | StatementIR::ReturnStmtIR { value } => {
            value.as_ref().is_some_and(expr_has_pointer_ops)
        }
        StatementIR::IfStmtIR {
            condition,
            then_body,
            else_ifs,
            else_body,
        } => {
            expr_has_pointer_ops(condition)
                || then_body.statements.iter().any(stmt_has_pointer_ops)
                || else_ifs.iter().any(|(c, b)| {
                    expr_has_pointer_ops(c) || b.statements.iter().any(stmt_has_pointer_ops)
                })
                || else_body
                    .as_ref()
                    .is_some_and(|b| b.statements.iter().any(stmt_has_pointer_ops))
        }
        StatementIR::WhileStmtIR { condition, body }
        | StatementIR::ForInStmtIR {
            iterable: condition,
            body,
            ..
        } => expr_has_pointer_ops(condition) || body.statements.iter().any(stmt_has_pointer_ops),
        StatementIR::BlockStmtIR { body } => body.statements.iter().any(stmt_has_pointer_ops),
        StatementIR::MutationStmt { intent } => {
            intent.as_ref().is_some_and(mutation_has_pointer_ops)
        }
        StatementIR::TryCatchStmtIR {
            try_body,
            catch_body,
            finally_body,
            ..
        } => {
            try_body.statements.iter().any(stmt_has_pointer_ops)
                || catch_body
                    .as_ref()
                    .is_some_and(|b| b.statements.iter().any(stmt_has_pointer_ops))
                || finally_body
                    .as_ref()
                    .is_some_and(|b| b.statements.iter().any(stmt_has_pointer_ops))
        }
        StatementIR::EventEmitStmtIR { args, .. } => args.iter().any(expr_has_pointer_ops),
        StatementIR::BreakStmtIR | StatementIR::ContinueStmtIR => false,
        // StatementIR is #[non_exhaustive] — cross-crate matches need a wildcard.
        #[allow(unreachable_patterns)]
        _ => false,
    }
}

/// True when a mutation intent carries a CapturePointer/ReleasePointer op.
fn mutation_has_pointer_ops(intent: &MutationIntent) -> bool {
    match intent {
        MutationIntent::DirectAssign { value, .. } => {
            value.as_deref().is_some_and(expr_has_pointer_ops)
        }
        MutationIntent::Increment { amount, .. }
        | MutationIntent::Decrement { amount, .. }
        | MutationIntent::Multiply { amount, .. }
        | MutationIntent::Divide { amount, .. }
        | MutationIntent::Modulo { amount, .. } => {
            amount.as_deref().is_some_and(expr_has_pointer_ops)
        }
        MutationIntent::Push { item, .. } => item.as_deref().is_some_and(expr_has_pointer_ops),
        MutationIntent::Pop { .. } => false,
        // MutationIntent is #[non_exhaustive] — cross-crate matches need a wildcard.
        #[allow(unreachable_patterns)]
        _ => false,
    }
}

/// True when an expression subtree contains a CapturePointer/ReleasePointer op.
fn expr_has_pointer_ops(expr: &ExprIR) -> bool {
    match expr {
        ExprIR::RefOpExpr { op, .. } => {
            matches!(op, RefOpIR::CapturePointer | RefOpIR::ReleasePointer)
        }
        ExprIR::FieldAccessExpr { object, .. }
        | ExprIR::OptionalChainExpr { object, .. }
        | ExprIR::UnaryOpExpr {
            operand: object, ..
        }
        | ExprIR::AwaitExpr { operand: object } => expr_has_pointer_ops(object),
        ExprIR::BinaryOpExpr { left, right, .. } => {
            expr_has_pointer_ops(left) || expr_has_pointer_ops(right)
        }
        ExprIR::TernaryIR {
            cond,
            then_expr,
            else_expr,
        } => {
            expr_has_pointer_ops(cond)
                || expr_has_pointer_ops(then_expr)
                || expr_has_pointer_ops(else_expr)
        }
        ExprIR::CallExpr { args, .. } | ExprIR::ArrayExpr { elements: args } => {
            args.iter().any(expr_has_pointer_ops)
        }
        ExprIR::SpreadExpr { operand }
        | ExprIR::IndexExpr {
            object: _,
            index: operand,
        } => expr_has_pointer_ops(operand),
        ExprIR::StructExpr { fields, .. } | ExprIR::VariantLiteral { fields, .. } => {
            fields.iter().any(|(_, v)| expr_has_pointer_ops(v))
        }
        ExprIR::MapExpr { entries } => entries
            .iter()
            .any(|(k, v)| expr_has_pointer_ops(k) || expr_has_pointer_ops(v)),
        ExprIR::StoreFieldAccessExpr { call_args, .. } => {
            call_args.iter().any(expr_has_pointer_ops)
        }
        ExprIR::MethodCallExpr { object, args, .. } => {
            expr_has_pointer_ops(object) || args.iter().any(expr_has_pointer_ops)
        }
        ExprIR::BlockExpr { statements, tail } => {
            statements.iter().any(stmt_has_pointer_ops) || expr_has_pointer_ops(tail)
        }
        ExprIR::ClosureExpr { body, .. } => expr_has_pointer_ops(body),
        ExprIR::MatchExpr { matched, arms } => {
            expr_has_pointer_ops(matched)
                || arms
                    .iter()
                    .any(|arm| arm.body.statements.iter().any(stmt_has_pointer_ops))
        }
        ExprIR::ArrayMethod {
            subject, predicate, ..
        } => expr_has_pointer_ops(subject) || expr_has_pointer_ops(predicate),
        ExprIR::LiteralExpr { .. } | ExprIR::IdentifierExpr { .. } => false,
        // ExprIR is #[non_exhaustive] — cross-crate matches need a wildcard.
        #[allow(unreachable_patterns)]
        _ => false,
    }
}

/// True when the view tree contains a CapturePointer/ReleasePointer op.
fn view_has_pointer_ops(node: &ViewTree) -> bool {
    match node {
        ViewTree::Element(el) => {
            el.props.values().any(expr_has_pointer_ops)
                || el.class_map_bindings.values().any(expr_has_pointer_ops)
                || el.events.values().any(|handler| match handler {
                    EventHandlerIR::InlineFn { body, .. } => {
                        body.statements.iter().any(stmt_has_pointer_ops)
                    }
                    EventHandlerIR::StoreAction { .. } | EventHandlerIR::FnRef { .. } => false,
                })
                || el.children.iter().any(view_has_pointer_ops)
        }
        ViewTree::Conditional(cond) => {
            cond.branches.iter().any(|b| {
                expr_has_pointer_ops(&b.condition)
                    || b.body.as_ref().is_some_and(view_has_pointer_ops)
            }) || cond.fallback.as_ref().is_some_and(view_has_pointer_ops)
        }
        ViewTree::ListRendering(list) => {
            expr_has_pointer_ops(&list.iterable)
                || list.body.as_ref().is_some_and(view_has_pointer_ops)
                || list.empty_body.as_ref().is_some_and(view_has_pointer_ops)
        }
        ViewTree::Interpolation(expr) => expr_has_pointer_ops(expr),
        ViewTree::Slot { fallback, .. } => fallback.iter().any(view_has_pointer_ops),
        ViewTree::Fragment(children) => children.iter().any(view_has_pointer_ops),
        ViewTree::Text(_) => false,
        // ViewTree is #[non_exhaustive] — cross-crate matches need a wildcard.
        #[allow(unreachable_patterns)]
        _ => false,
    }
}

/// Collect identifier references from a StatementIR.
pub(super) fn collect_stmt_identifiers(stmt: &StatementIR, acc: &mut FxHashSet<String>) {
    match stmt {
        StatementIR::ExprStmtIR { expr } => {
            collect_expr_identifiers(expr, acc);
        }
        StatementIR::LetStmtIR { name: _, value, .. } => {
            if let Some(ref v) = value {
                collect_expr_identifiers(v, acc);
            }
        }
        StatementIR::ReturnStmtIR { value } => {
            if let Some(ref v) = value {
                collect_expr_identifiers(v, acc);
            }
        }
        StatementIR::IfStmtIR {
            condition,
            then_body,
            else_ifs,
            else_body,
        } => {
            collect_expr_identifiers(condition, acc);
            for s in &then_body.statements {
                collect_stmt_identifiers(s, acc);
            }
            for (cond, body) in else_ifs {
                collect_expr_identifiers(cond, acc);
                for s in &body.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
            if let Some(ref eb) = else_body {
                for s in &eb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
        }
        StatementIR::WhileStmtIR { condition, body } => {
            collect_expr_identifiers(condition, acc);
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::ForInStmtIR { iterable, body, .. } => {
            collect_expr_identifiers(iterable, acc);
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::BlockStmtIR { body } => {
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::MutationStmt { intent } => {
            if let Some(intent) = intent {
                collect_mutation_identifiers(intent, acc);
            }
        }
        StatementIR::ThrowStmtIR { expr } => {
            collect_expr_identifiers(expr, acc);
        }
        StatementIR::TryCatchStmtIR {
            try_body,
            catch_body,
            finally_body,
            ..
        } => {
            for s in &try_body.statements {
                collect_stmt_identifiers(s, acc);
            }
            if let Some(ref cb) = catch_body {
                for s in &cb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
            if let Some(ref fb) = finally_body {
                for s in &fb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
        }
        StatementIR::EventEmitStmtIR { event_name, args } => {
            // `emit onX(...)` emits the event prop name + argument
            // expressions verbatim — both must count as reads or the
            // generated call references an undeclared name (TS2304).
            acc.insert(event_name.clone());
            for arg in args {
                collect_expr_identifiers(arg, acc);
            }
        }
        StatementIR::BreakStmtIR | StatementIR::ContinueStmtIR => {}
        #[allow(unreachable_patterns)]
        _ => unreachable!("Unknown StatementIR variant — update codegen for new variant"),
    }
}

