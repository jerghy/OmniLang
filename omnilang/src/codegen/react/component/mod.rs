// Component codegen: .tsx + .module.css generation
// ═══════════════════════════════════════════════════════════

pub(super) mod computed;
pub(super) mod effect;
pub(super) mod function;
pub(super) mod imports;
pub(super) mod jsx;
pub(super) mod motion_effects;
pub(super) mod state;

use super::expr;
use super::{escape_js_ident, CodeWriter, ReactCodegen};
use crate::ir::*;
use rustc_hash::FxHashMap;
use rustc_hash::FxHashSet;

impl ReactCodegen {
    /// Generate a React functional component .tsx file.
    pub(super) fn gen_component_tsx(
        &self,
        name: &str,
        comp: &ComponentIR,
        ir: &IRProgram,
        component_map: &FxHashMap<&str, &ComponentIR>,
    ) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang — React target");
        w.emit("");

        // Determine which React hooks are actually needed
        let has_computeds = !comp.computeds.is_empty();
        let has_fn_form_computed = comp.computeds.iter().any(|c| {
            matches!(&c.body, ExprIR::BlockExpr { statements, .. }
                if statements.iter().any(|s| matches!(s, StatementIR::ReturnStmtIR { .. })))
        });
        let has_effects_or_lifecycles = !comp.effects.is_empty() || !comp.lifecycles.is_empty();
        let has_motion = comp
            .view
            .as_ref()
            .is_some_and(effect::view_has_motion_or_effects);

        // Scan all code paths for signal mutations and function calls
        let called_fns = function::collect_called_local_fns(comp);
        let mutated_signals = state::collect_signal_mutations(comp, &called_fns);

        // Build comprehensive read-signals set: signals referenced in view, computeds,
        // effects, lifecycles, and called local functions.
        let mut read_signals = comp
            .view
            .as_ref()
            .map(state::collect_view_read_signals)
            .unwrap_or_default();
        for computed in &comp.computeds {
            collect_expr_identifiers(&computed.body, &mut read_signals);
        }
        for effect in &comp.effects {
            for stmt in &effect.body.statements {
                collect_stmt_identifiers(stmt, &mut read_signals);
            }
        }
        for lc in &comp.lifecycles {
            for stmt in &lc.body.statements {
                collect_stmt_identifiers(stmt, &mut read_signals);
            }
        }
        for fun in &comp.fns {
            if called_fns.contains(&fun.name) {
                for stmt in &fun.body.statements {
                    collect_stmt_identifiers(stmt, &mut read_signals);
                }
            }
        }
        if let Some(ref view) = comp.view {
            state::collect_view_inline_handler_reads(view, &mut read_signals);
        }

        // Determine if any state actually needs useState (has active setter)
        let has_mutable_states = comp
            .signals
            .iter()
            .any(|s| read_signals.contains(&s.name) && mutated_signals.contains(&s.name));
        let mut hooks: Vec<String> = Vec::new();
        if has_mutable_states {
            hooks.push("useState".to_string());
        }
        if has_computeds {
            hooks.push("useMemo".to_string());
        }
        if has_fn_form_computed {
            hooks.push("useCallback".to_string());
        }
        if has_effects_or_lifecycles || has_motion {
            hooks.push("useEffect".to_string());
        }

        // Style check — only import if styles exist and are referenced in view
        let used_style_classes = comp
            .view
            .as_ref()
            .map(jsx::collect_used_style_classes)
            .unwrap_or_default();
        let has_styles = !comp.styles.is_empty()
            && used_style_classes
                .iter()
                .any(|c| comp.styles.iter().any(|s| &s.class_name == c));

        // Props interface check
        let has_props = !comp.props.is_empty() || !comp.events.is_empty();

        // ── Store-related computation ──
        let all_stores = ir.all_stores();
        let used_store_signals = state::collect_used_store_signals(comp);

        let local_names: FxHashSet<String> = comp
            .signals
            .iter()
            .map(|s| s.name.clone())
            .chain(comp.props.keys().cloned())
            .chain(comp.fns.iter().map(|f| f.name.clone()))
            .collect();

        let mut used_store_refs: FxHashSet<String> = FxHashSet::default();
        for store_ref in &comp.store_refs {
            if used_store_signals.contains(store_ref.as_str()) {
                used_store_refs.insert(store_ref.clone());
                continue;
            }
            if let Some(store) = all_stores.get(store_ref.as_str()) {
                for sig_name in store.signals.keys() {
                    if !local_names.contains(sig_name) && used_store_signals.contains(sig_name) {
                        used_store_refs.insert(store_ref.clone());
                        break;
                    }
                }
            }
        }

        // Build signal_names (all state + store aliases) and store_signal_map
        let mut signal_names: FxHashSet<String> =
            comp.signals.iter().map(|s| s.name.clone()).collect();
        let mut store_signal_map: FxHashMap<String, String> = FxHashMap::default();
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            signal_names.insert(store_ref.clone());
            if let Some(store) = ir.all_stores().get(store_ref.as_str()) {
                for sig_name in store.signals.keys() {
                    signal_names.insert(sig_name.clone());
                    store_signal_map
                        .insert(sig_name.clone(), format!("{}.{}", store_ref, sig_name));
                }
            }
        }

        // Motion animation names — used to filter motion refs from event handlers
        let motion_names: FxHashSet<String> = ir
            .modules
            .values()
            .flat_map(|m| &m.motions)
            .map(|m| m.name.clone())
            .collect();

        // ── Emit imports ──
        let comp_imports = imports::collect_component_imports(
            comp,
            ir,
            component_map,
            &used_store_refs,
            &hooks,
            has_styles,
            has_motion,
        );
        comp_imports.emit(&mut w, name, comp, has_props);

        // ── Library functions ──
        let mut used_fn_names: FxHashSet<String> = FxHashSet::default();
        for computed in &comp.computeds {
            collect_expr_identifiers(&computed.body, &mut used_fn_names);
        }
        for effect in &comp.effects {
            for stmt in &effect.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        for lc in &comp.lifecycles {
            for stmt in &lc.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        for fun in &comp.fns {
            for stmt in &fun.body.statements {
                collect_stmt_identifiers(stmt, &mut used_fn_names);
            }
        }
        if let Some(ref view) = comp.view {
            jsx::collect_view_identifiers(view, &mut used_fn_names);
        }
        if let Some(ref view) = comp.view {
            jsx::collect_motion_identifiers(view, &mut used_fn_names);
        }

        let all_lib_fns: Vec<&FunctionIR> = ir.all_functions();
        let lib_fns: Vec<&&FunctionIR> = all_lib_fns
            .iter()
            .filter(|f| used_fn_names.contains(&f.name))
            .collect();
        for fun in &lib_fns {
            let param_names: Vec<(String, bool)> = fun
                .params
                .iter()
                .map(|p| {
                    let escaped = escape_js_ident(&p.name);
                    let needs_rename = escaped != p.name;
                    (escaped, needs_rename)
                })
                .collect();
            let param_escaped: Vec<&str> = param_names.iter().map(|(n, _)| n.as_str()).collect();
            let params_str = param_escaped.join(", ");
            let is_async =
                fun.is_async || fun.body.statements.iter().any(effect::stmt_contains_await);
            let async_prefix = if is_async { "async " } else { "" };
            w.emit_fmt(format_args!(
                "const {} = {}({}) => {{",
                fun.name, async_prefix, params_str
            ));
            w.indent();
            let mut body_w = crate::codegen::CodeWriter::new();
            body_w.indent();
            for stmt in &fun.body.statements {
                expr::generate_statement_tsx_with_mode(
                    &mut body_w,
                    stmt,
                    &FxHashSet::default(),
                    self.store_mode,
                );
            }
            let mut body_str = body_w.into_string();
            for (i, (new_name, needs_rename)) in param_names.iter().enumerate() {
                if *needs_rename {
                    let old_name = &fun.params[i].name;
                    body_str = body_str.replace(old_name, new_name);
                }
            }
            for line in body_str.lines() {
                w.emit(line);
            }
            w.dedent();
            w.emit("};");
        }
        if !lib_fns.is_empty() {
            w.emit("");
        }

        // Component function signature
        if !has_props {
            w.emit_fmt(format_args!("export function {}() {{", name));
        } else {
            let mut prop_list: Vec<String> = comp
                .props
                .keys()
                .map(|prop_name| {
                    if let Some(default_val) = comp.prop_defaults.get(prop_name) {
                        let default_tsx = expr::format_expr_ir_tsx(default_val);
                        format!("{} = {}", prop_name, default_tsx)
                    } else {
                        prop_name.clone()
                    }
                })
                .collect();
            for event in &comp.events {
                if read_signals.contains(event.name.as_str()) {
                    prop_list.push(event.name.clone());
                }
            }
            if prop_list.is_empty() {
                w.emit_fmt(format_args!(
                    "export function {}(_props: {}Props) {{",
                    name, name
                ));
            } else {
                w.emit_fmt(format_args!(
                    "export function {}({{ {} }}: {}Props) {{",
                    name,
                    prop_list.join(", "),
                    name
                ));
            }
        }
        w.indent();

        // Store hooks — only for stores whose signals are actually used
        for store_ref in &comp.store_refs {
            if !used_store_refs.contains(store_ref.as_str()) {
                continue;
            }
            if ir.has_store(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                w.emit_fmt(format_args!("const {} = {}();", store_ref, hook_name));
            }
        }

        // State hooks + effects
        let fn_names: FxHashSet<String> = comp.fns.iter().map(|f| f.name.clone()).collect();
        self.gen_state_hooks(&mut w, comp, &read_signals, &mutated_signals, &fn_names);
        self.gen_effects(&mut w, comp, &store_signal_map, &signal_names);

        // Computed values (useMemo / useCallback)
        let mut known_signal_names: Vec<String> =
            comp.signals.iter().map(|s| s.name.clone()).collect();
        known_signal_names.extend(comp.store_refs.iter().cloned());
        known_signal_names.extend(comp.computeds.iter().map(|c| c.name.clone()));
        computed::gen_computed_values(
            &mut w,
            comp,
            &known_signal_names,
            &signal_names,
            self.store_mode,
        );

        // Component-local function declarations
        self.gen_functions(&mut w, comp, &called_fns, &signal_names, &fn_names);

        // Motion animation effects
        if let Some(ref view) = comp.view {
            motion_effects::gen_motion_effects(&mut w, view, ir);
        }

        w.emit("");

        // Render return (JSX view tree)
        self.gen_jsx_return(
            &mut w,
            comp,
            component_map,
            &signal_names,
            &motion_names,
            name,
        );
        w.dedent();
        w.emit("}");
        w.emit("");

        w.into_string()
    }

    /// Generate a CSS module file from component styles.
    pub(super) fn gen_component_css(&self, name: &str, comp: &ComponentIR) -> String {
        let mut w = CodeWriter::new();
        w.emit_fmt(format_args!("/* Styles for {} */", name));
        crate::codegen::generate_css_style_block(&mut w, &comp.styles);
        w.into_string()
    }
}

// ═══════════════════════════════════════════════════════════
// Shared identifier collection — used to determine which
// library functions to emit and which React hooks are needed.
// ═══════════════════════════════════════════════════════════

/// Collect identifier references from an ExprIR.
fn collect_expr_identifiers(expr: &ExprIR, acc: &mut FxHashSet<String>) {
    match expr {
        ExprIR::IdentifierExpr { name, .. } => {
            acc.insert(name.clone());
        }
        ExprIR::BinaryOpExpr { left, right, .. } => {
            collect_expr_identifiers(left, acc);
            collect_expr_identifiers(right, acc);
        }
        ExprIR::UnaryOpExpr { operand, .. } => {
            collect_expr_identifiers(operand, acc);
        }
        ExprIR::CallExpr { name, args, .. } => {
            acc.insert(name.clone());
            for arg in args {
                collect_expr_identifiers(arg, acc);
            }
        }
        ExprIR::MethodCallExpr { object, args, .. } => {
            collect_expr_identifiers(object, acc);
            for arg in args {
                collect_expr_identifiers(arg, acc);
            }
        }
        ExprIR::FieldAccessExpr { object, .. } | ExprIR::OptionalChainExpr { object, .. } => {
            collect_expr_identifiers(object, acc);
        }
        ExprIR::IndexExpr { object, index } => {
            collect_expr_identifiers(object, acc);
            collect_expr_identifiers(index, acc);
        }
        ExprIR::TernaryIR {
            cond,
            then_expr,
            else_expr,
        } => {
            collect_expr_identifiers(cond, acc);
            collect_expr_identifiers(then_expr, acc);
            collect_expr_identifiers(else_expr, acc);
        }
        ExprIR::ArrayExpr { elements } => {
            for elem in elements {
                collect_expr_identifiers(elem, acc);
            }
        }
        ExprIR::MapExpr { entries } => {
            for (k, v) in entries {
                collect_expr_identifiers(k, acc);
                collect_expr_identifiers(v, acc);
            }
        }
        ExprIR::ClosureExpr { body, .. } => {
            collect_expr_identifiers(body, acc);
        }
        ExprIR::BlockExpr { statements, tail } => {
            for stmt in statements {
                collect_stmt_identifiers(stmt, acc);
            }
            collect_expr_identifiers(tail, acc);
        }
        ExprIR::MatchExpr { matched, arms } => {
            collect_expr_identifiers(matched, acc);
            for arm in arms {
                for stmt in &arm.body.statements {
                    collect_stmt_identifiers(stmt, acc);
                }
            }
        }
        ExprIR::VariantLiteral { fields, .. } => {
            for (_, v) in fields {
                collect_expr_identifiers(v, acc);
            }
        }
        ExprIR::StructExpr { fields, .. } => {
            for (_, v) in fields {
                collect_expr_identifiers(v, acc);
            }
        }
        ExprIR::SpreadExpr { operand } => {
            collect_expr_identifiers(operand, acc);
        }
        ExprIR::StoreFieldAccessExpr { call_args, .. } => {
            for arg in call_args {
                collect_expr_identifiers(arg, acc);
            }
        }
        ExprIR::AwaitExpr { operand } => {
            collect_expr_identifiers(operand, acc);
        }
        ExprIR::LiteralExpr { .. } => {}
    }
}

/// Collect identifier references from a StatementIR.
fn collect_stmt_identifiers(stmt: &StatementIR, acc: &mut FxHashSet<String>) {
    match stmt {
        StatementIR::ExprStmtIR { expr } => {
            collect_expr_identifiers(expr, acc);
        }
        StatementIR::LetStmtIR { name: _, value, .. } => {
            if let Some(ref v) = value {
                collect_expr_identifiers(v, acc);
            }
        }
        StatementIR::ReturnStmtIR { value } => {
            if let Some(ref v) = value {
                collect_expr_identifiers(v, acc);
            }
        }
        StatementIR::IfStmtIR {
            condition,
            then_body,
            else_ifs,
            else_body,
        } => {
            collect_expr_identifiers(condition, acc);
            for s in &then_body.statements {
                collect_stmt_identifiers(s, acc);
            }
            for (cond, body) in else_ifs {
                collect_expr_identifiers(cond, acc);
                for s in &body.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
            if let Some(ref eb) = else_body {
                for s in &eb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
        }
        StatementIR::WhileStmtIR { condition, body } => {
            collect_expr_identifiers(condition, acc);
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::ForInStmtIR { iterable, body, .. } => {
            collect_expr_identifiers(iterable, acc);
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::BlockStmtIR { body } => {
            for s in &body.statements {
                collect_stmt_identifiers(s, acc);
            }
        }
        StatementIR::MutationStmt { intent } => {
            if let Some(intent) = intent {
                collect_mutation_identifiers(intent, acc);
            }
        }
        StatementIR::ThrowStmtIR { expr } => {
            collect_expr_identifiers(expr, acc);
        }
        StatementIR::TryCatchStmtIR {
            try_body,
            catch_body,
            finally_body,
            ..
        } => {
            for s in &try_body.statements {
                collect_stmt_identifiers(s, acc);
            }
            if let Some(ref cb) = catch_body {
                for s in &cb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
            if let Some(ref fb) = finally_body {
                for s in &fb.statements {
                    collect_stmt_identifiers(s, acc);
                }
            }
        }
        StatementIR::EventEmitStmtIR { .. }
        | StatementIR::BreakStmtIR
        | StatementIR::ContinueStmtIR => {}
    }
}

/// Collect identifiers from a MutationIntent.
fn collect_mutation_identifiers(intent: &MutationIntent, acc: &mut FxHashSet<String>) {
    match intent {
        MutationIntent::DirectAssign { value, .. } => {
            if let Some(ref v) = value {
                collect_expr_identifiers(v, acc);
            }
        }
        MutationIntent::Increment { amount, .. }
        | MutationIntent::Decrement { amount, .. }
        | MutationIntent::Multiply { amount, .. }
        | MutationIntent::Divide { amount, .. }
        | MutationIntent::Modulo { amount, .. } => {
            if let Some(ref v) = amount {
                collect_expr_identifiers(v, acc);
            }
        }
        MutationIntent::Push { item, .. } => {
            if let Some(ref v) = item {
                collect_expr_identifiers(v, acc);
            }
        }
        MutationIntent::Pop { .. } => {}
    }
}
