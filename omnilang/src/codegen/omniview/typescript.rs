//! TypeScript declaration generation (.d.ts) from ComponentIR.
//!
//! Maps OmniLang type information to TypeScript type annotations so that
//! React consumers get proper type-checking on component props and events.
//!
//! For each component, emits:
//! - `export interface XxxProps { ... }` with typed props
//! - For each event: `export type XxxHandler = (detail: T) => void;`
//! - `export interface XxxComponent { (props: XxxProps): JSX.Element; }`
//! - `export type XxxEventNames = "onFoo" | "onBar";`

use crate::ir::{ComponentIR, TypeIR, TypeKind};
use std::fmt::Write;

/// Generate a complete `.d.ts` string from a list of component IRs.
///
/// Each component's type information (props, events) is emitted as
/// TypeScript declarations suitable for a `.d.ts` file consumed by
/// the React production path.
pub fn generate_typescript_declarations(components: &[ComponentIR]) -> String {
    let mut out = String::new();
    writeln!(out, "// Auto-generated by OmniLang compiler").unwrap();
    writeln!(
        out,
        "// Do not edit — generated from .omni component definitions\n"
    )
    .unwrap();

    for comp in components {
        emit_component_declaration(&mut out, comp);
    }

    out
}

/// Emit all TypeScript declarations for a single component:
/// props interface, event handler types, event name union, and component type.
fn emit_component_declaration(out: &mut String, comp: &ComponentIR) {
    emit_props_interface(out, comp);
    emit_event_handler_types(out, comp);
    emit_event_names_union(out, comp);
    emit_component_type(out, comp);
}

/// Emit `export interface XxxProps { ... }` with typed prop fields.
fn emit_props_interface(out: &mut String, comp: &ComponentIR) {
    writeln!(out, "export interface {}Props {{", comp.name).unwrap();

    for (prop_name, ty) in &comp.props {
        let optional = comp.prop_defaults.contains_key(prop_name);
        let ts_type = typeir_to_ts(ty);
        if optional {
            writeln!(out, "  {}?: {};", prop_name, ts_type).unwrap();
        } else {
            writeln!(out, "  {}: {};", prop_name, ts_type).unwrap();
        }
    }

    // Event handlers — always optional (parent may or may not listen)
    for (ev_name, param_type) in comp.event_names.iter().zip(comp.event_param_types.iter()) {
        let ts_param = if param_type.is_empty() {
            "any".to_string()
        } else {
            omnilang_type_name_to_ts(param_type)
        };
        writeln!(out, "  {}?: (detail: {}) => void;", ev_name, ts_param).unwrap();
    }

    writeln!(out, "}}\n").unwrap();
}

/// Emit `export type XxxHandler = (detail: T) => void;` for each event.
fn emit_event_handler_types(out: &mut String, comp: &ComponentIR) {
    for (ev_name, param_type) in comp.event_names.iter().zip(comp.event_param_types.iter()) {
        let ts_param = if param_type.is_empty() {
            "any".to_string()
        } else {
            omnilang_type_name_to_ts(param_type)
        };
        writeln!(
            out,
            "export type {ev}Handler = (detail: {param}) => void;",
            ev = ev_name,
            param = ts_param,
        )
        .unwrap();
    }

    if !comp.event_names.is_empty() {
        out.push('\n');
    }
}

/// Emit `export type XxxEventNames = "onFoo" | "onBar";` (or `never` if none).
fn emit_event_names_union(out: &mut String, comp: &ComponentIR) {
    if comp.event_names.is_empty() {
        writeln!(out, "export type {}EventNames = never;\n", comp.name).unwrap();
        return;
    }

    let event_union: Vec<String> = comp
        .event_names
        .iter()
        .map(|n| format!("\"{}\"", n))
        .collect();
    writeln!(
        out,
        "export type {}EventNames = {};\n",
        comp.name,
        event_union.join(" | ")
    )
    .unwrap();
}

/// Emit `export interface XxxComponent { (props: XxxProps): JSX.Element; }`.
fn emit_component_type(out: &mut String, comp: &ComponentIR) {
    writeln!(out, "export interface {}Component {{", comp.name).unwrap();
    writeln!(out, "  (props: {}Props): JSX.Element;", comp.name).unwrap();
    writeln!(out, "}}\n").unwrap();
}

/// Convert a fully qualified `TypeIR` to a TypeScript type string.
/// Handles nullability at the outermost level.
fn typeir_to_ts(ty: &TypeIR) -> String {
    let base = typekind_to_ts(&ty.kind, &ty.type_args);
    if ty.is_nullable {
        format!("{} | null", base)
    } else {
        base
    }
}

/// Convert a `TypeKind` (with type arguments) to a TypeScript type string.
///
/// # Panics
/// Panics if a new `#[non_exhaustive]` variant is added without updating this match.
fn typekind_to_ts(kind: &TypeKind, type_args: &[TypeIR]) -> String {
    match kind {
        TypeKind::String => "string".to_string(),
        TypeKind::Int | TypeKind::Float => "number".to_string(),
        TypeKind::Bool => "boolean".to_string(),
        TypeKind::Void => "void".to_string(),
        TypeKind::Any => "any".to_string(),
        TypeKind::Named { name } => map_named_type_to_ts(name, type_args),
        _other => {
            // TypeKind is #[non_exhaustive] — future variants degrade gracefully
            // rather than crashing the compiler.
            "/* unknown type kind */ any".to_string()
        }
    }
}

/// Map a named TypeKind (collection or custom type) to TypeScript.
///
/// Recognised collection types:
/// - `List` / `Vec` / `Array` → `T[]`
/// - `Map` / `HashMap` / `FxHashMap` → `Record<K, V>`
/// - `Optional` / `Option` → `T | null`
/// - `Set` → `Set<T>`
///
/// Everything else is treated as an opaque type name or a generic reference.
fn map_named_type_to_ts(name: &str, type_args: &[TypeIR]) -> String {
    match name {
        "List" | "Vec" | "Array" => {
            if let Some(arg) = type_args.first() {
                format!("{}[]", typeir_to_ts(arg))
            } else {
                "unknown[]".to_string()
            }
        }
        "Map" | "HashMap" | "FxHashMap" if type_args.len() >= 2 => {
            let k = typeir_to_ts(&type_args[0]);
            let v = typeir_to_ts(&type_args[1]);
            format!("Record<{}, {}>", k, v)
        }
        "Map" | "HashMap" | "FxHashMap" => {
            if let Some(arg) = type_args.first() {
                format!("Record<string, {}>", typeir_to_ts(arg))
            } else {
                "Record<string, unknown>".to_string()
            }
        }
        "Optional" | "Option" => {
            if let Some(arg) = type_args.first() {
                format!("{} | null", typeir_to_ts(arg))
            } else {
                "unknown | null".to_string()
            }
        }
        "Set" => {
            if let Some(arg) = type_args.first() {
                format!("Set<{}>", typeir_to_ts(arg))
            } else {
                "Set<unknown>".to_string()
            }
        }
        other => {
            if type_args.is_empty() {
                other.to_string()
            } else {
                let args: Vec<String> = type_args.iter().map(typeir_to_ts).collect();
                format!("{}<{}>", other, args.join(", "))
            }
        }
    }
}

/// Convert a raw OmniLang type name string to a TypeScript type.
/// Used for event parameter types stored as plain strings.
fn omnilang_type_name_to_ts(type_name: &str) -> String {
    match type_name.to_lowercase().as_str() {
        "string" => "string".to_string(),
        "int" | "i32" | "i64" | "float" | "f32" | "f64" => "number".to_string(),
        "bool" | "boolean" => "boolean".to_string(),
        "void" => "void".to_string(),
        "any" => "any".to_string(),
        // Pass through custom type names as-is — consumers can augment with
        // their own type declarations.
        _ => type_name.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::ExprIR;
    use rustc_hash::FxHashMap;

    #[test]
    fn typescript_declarations_emit_props_interface() {
        let mut props: FxHashMap<String, TypeIR> = FxHashMap::default();
        props.insert(
            "count".into(),
            TypeIR {
                kind: TypeKind::Int,
                type_args: vec![],
                is_nullable: false,
            },
        );
        props.insert(
            "label".into(),
            TypeIR {
                kind: TypeKind::String,
                type_args: vec![],
                is_nullable: false,
            },
        );
        props.insert(
            "enabled".into(),
            TypeIR {
                kind: TypeKind::Bool,
                type_args: vec![],
                is_nullable: false,
            },
        );

        let comp = ComponentIR {
            name: "Counter".into(),
            props,
            ..ComponentIR::default()
        };

        let result = generate_typescript_declarations(&[comp]);
        assert!(result.contains("export interface CounterProps {"));
        assert!(result.contains("  count: number;"));
        assert!(result.contains("  label: string;"));
        assert!(result.contains("  enabled: boolean;"));
        assert!(result.contains("export interface CounterComponent {"));
        assert!(result.contains("(props: CounterProps): JSX.Element;"));
    }

    #[test]
    fn props_interface_includes_event_handlers() {
        let mut props: FxHashMap<String, TypeIR> = FxHashMap::default();
        props.insert(
            "label".into(),
            TypeIR {
                kind: TypeKind::String,
                type_args: vec![],
                is_nullable: false,
            },
        );

        let comp = ComponentIR {
            name: "Button".into(),
            props,
            prop_defaults: Default::default(),
            event_names: vec!["onClick".into()],
            event_param_types: vec!["string".into()],
            ..Default::default()
        };

        let mut out = String::new();
        emit_props_interface(&mut out, &comp);

        // Must include the event handler in the Props interface
        assert!(
            out.contains("onClick?:"),
            "Props interface must include event handlers, got:\n{}",
            out
        );
        assert!(
            out.contains("(detail: string)"),
            "Event handler param type must be mapped, got:\n{}",
            out
        );
    }

    #[test]
    fn typescript_declarations_optional_for_defaulted_props() {
        let mut props: FxHashMap<String, TypeIR> = FxHashMap::default();
        props.insert(
            "required".into(),
            TypeIR {
                kind: TypeKind::String,
                type_args: vec![],
                is_nullable: false,
            },
        );
        props.insert(
            "optional".into(),
            TypeIR {
                kind: TypeKind::Int,
                type_args: vec![],
                is_nullable: false,
            },
        );

        let mut prop_defaults: FxHashMap<String, ExprIR> = FxHashMap::default();
        prop_defaults.insert(
            "optional".into(),
            ExprIR::LiteralExpr {
                value: serde_json::json!(42),
            },
        );

        let comp = ComponentIR {
            name: "Widget".into(),
            props,
            prop_defaults,
            ..ComponentIR::default()
        };

        let result = generate_typescript_declarations(&[comp]);
        assert!(result.contains("export interface WidgetProps {"));
        assert!(result.contains("  required: string;"));
        assert!(result.contains("  optional?: number;"));
    }
}
