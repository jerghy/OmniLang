//! Vue codegen: IR -> Vue SFC (.vue) + store composables (.ts).
//!
//! Each component generates a `.vue` Single File Component with
//! `<template>`, `<script setup lang="ts">`, and `<style scoped>` sections.
//! Each store generates a `useXxx.ts` composable using Vue's Composition API.

mod expr;
mod template;
#[cfg(test)]
mod tests;

use expr::*;
use template::*;

use std::collections::HashMap;

use super::{CodeWriter, Codegen, CompileOutput, CompiledFile};
use crate::codegen::{camel_to_kebab, format_css_value};
use crate::ir::*;

pub struct VueCodegen;

impl Codegen for VueCodegen {
    fn generate(&self, ir: &IRProgram, _source_files: &HashMap<String, String>) -> CompileOutput {
        let mut files = Vec::new();

        // Each component -> .vue SFC
        for (name, comp) in ir.all_components() {
            let sfc = self.gen_component_sfc(name, comp, ir);
            files.push(CompiledFile {
                path: format!("{}.vue", name),
                content: sfc,
            });
        }

        // Each store -> useXxx.ts composable
        for (name, store) in ir.all_stores() {
            let hook = self.gen_store_hook(name, store);
            files.push(CompiledFile {
                path: format!("use{}.ts", name),
                content: hook,
            });
        }

        CompileOutput::success(files)
    }
}

impl VueCodegen {
    /// Generate a Vue SFC (.vue) file for a component.
    fn gen_component_sfc(&self, name: &str, comp: &ComponentIR, ir: &IRProgram) -> String {
        let mut w = CodeWriter::new();
        w.emit("<!-- Generated by OmniLang -- Vue target -->");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <template>
        // ═══════════════════════════════════════════════════════
        w.emit("<template>");
        w.indent();
        if let Some(view) = &comp.view {
            gen_template_node(&mut w, view);
        } else {
            w.emit("<div class=\"container\">");
            w.indent();
            w.emit(&format!("<h1>{{ '{}' }}</h1>", name));
            w.dedent();
            w.emit("</div>");
        }
        w.dedent();
        w.emit("</template>");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <script setup lang="ts">
        // ═══════════════════════════════════════════════════════
        w.emit("<script setup lang=\"ts\">");
        w.indent();

        // Determine which Vue imports are needed
        let mut vue_imports: Vec<String> = Vec::new();
        vue_imports.push("ref".into());
        if (!comp.computeds.is_empty() || !comp.store_refs.is_empty())
            && !vue_imports.contains(&"computed".into())
        {
            vue_imports.push("computed".into());
        }
        if !comp.effects.is_empty() {
            vue_imports.push("watchEffect".into());
        }
        let has_mount = comp.lifecycles.iter().any(|lc| lc.kind == "mount");
        let has_unmount = comp.lifecycles.iter().any(|lc| lc.kind == "unmount");
        if has_mount {
            vue_imports.push("onMounted".into());
        }
        if has_unmount {
            vue_imports.push("onUnmounted".into());
        }

        w.emit(&format!(
            "import {{ {} }} from 'vue';",
            vue_imports.join(", ")
        ));
        w.emit("");

        // Store hook imports
        let mut store_hook_imports = Vec::new();
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                store_hook_imports.push(format!(
                    "import {{ {} }} from './use{}';",
                    hook_name, store_ref
                ));
            }
        }
        for import_line in &store_hook_imports {
            w.emit(import_line);
        }
        if !store_hook_imports.is_empty() {
            w.emit("");
        }

        // Props interface + defineProps
        if !comp.props.is_empty() {
            w.emit("const props = defineProps<{");
            w.indent();
            for (prop_name, prop_type) in &comp.props {
                let ts_type =
                    super::javascript::js_type(&prop_type.kind, &prop_type.type_args, true);
                w.emit(&format!("  {}: {};", prop_name, ts_type));
            }
            w.dedent();
            w.emit("}>();");
            w.emit("");
        }

        // Store composable calls
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                w.emit(&format!("const {} = {}();", store_ref, hook_name));
            }
        }

        // State (ref declarations)
        for state in &comp.states {
            let init_val = format_expr_vue(&state.initial_value);
            let ts_type =
                super::javascript::js_type(&state.r#type.kind, &state.r#type.type_args, true);
            if ts_type.is_empty() {
                w.emit(&format!("const {} = ref({});", state.name, init_val));
            } else {
                w.emit(&format!(
                    "const {} = ref<{}>({});",
                    state.name, ts_type, init_val
                ));
            }
        }

        // Effects (watchEffect)
        for effect in &comp.effects {
            w.emit("watchEffect(() => {");
            w.indent();
            for stmt in &effect.body.statements {
                generate_statement_vue(&mut w, stmt);
            }
            w.dedent();
            w.emit("});");
        }

        // Lifecycles (onMounted / onUnmounted)
        for lc in &comp.lifecycles {
            match lc.kind.as_str() {
                "mount" => {
                    w.emit("onMounted(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_vue(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                "unmount" => {
                    w.emit("onUnmounted(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_vue(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                _ => {
                    w.emit(&format!("// TODO: lifecycle '{}'", lc.kind));
                }
            }
        }

        // Computed values
        for computed in &comp.computeds {
            w.emit(&format!("const {} = computed(() => {{", computed.name));
            w.indent();
            w.emit(&format!("  return {};", format_expr_vue(&computed.body)));
            w.dedent();
            w.emit("});");
        }

        // Functions
        for func in &comp.fns {
            generate_function_vue(&mut w, func);
        }

        w.dedent();
        w.emit("</script>");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <style scoped>
        // ═══════════════════════════════════════════════════════
        w.emit("<style scoped>");
        w.indent();
        if comp.styles.is_empty() {
            w.emit(".container {");
            w.indent();
            w.emit("  display: flex;");
            w.emit("  flex-direction: column;");
            w.emit("  padding: 16px;");
            w.dedent();
            w.emit("}");
        } else {
            for style in &comp.styles {
                let prefix = if style.is_tag_selector { "" } else { "." };
                w.emit(&format!("{}{} {{", prefix, style.class_name));
                for (prop, value) in &style.properties {
                    let css_val = format_css_value(value);
                    w.emit(&format!("  {}: {};", camel_to_kebab(prop), css_val));
                }
                w.emit("}");
            }
        }
        w.dedent();
        w.emit("</style>");
        w.emit("");

        w.into_string()
    }

    /// Generate a store composable (useXxx.ts).
    fn gen_store_hook(&self, name: &str, store: &StoreIR) -> String {
        let mut w = CodeWriter::new();
        w.emit(&format!(
            "// Generated by OmniLang -- Store composable: use{}",
            name
        ));
        w.emit("import { ref, computed } from 'vue';");
        w.emit("");

        w.emit(&format!("export function use{}() {{", name));
        w.indent();

        // Signals as refs
        for (sig_name, sig_type) in &store.signals {
            let init = store
                .signal_defaults
                .get(sig_name)
                .map(format_json_value_vue)
                .unwrap_or_else(|| "null".into());
            let ts_type = super::javascript::js_type(&sig_type.kind, &sig_type.type_args, true);
            if ts_type.is_empty() {
                w.emit(&format!("const {} = ref({});", sig_name, init));
            } else {
                w.emit(&format!("const {} = ref<{}>({});", sig_name, ts_type, init));
            }
        }

        // Getters as computed
        for (getter_name, getter_expr) in &store.getters {
            w.emit(&format!("const {} = computed(() => {{", getter_name));
            w.indent();
            w.emit(&format!("  return {};", format_expr_vue(getter_expr)));
            w.dedent();
            w.emit("});");
        }

        // Return value (refs are returned directly; templates auto-unwrap)
        let mut return_keys: Vec<String> = Vec::new();
        for sig_name in store.signals.keys() {
            return_keys.push(sig_name.clone());
        }
        for getter_name in store.getters.keys() {
            return_keys.push(getter_name.clone());
        }
        w.emit(&format!("return {{ {} }};", return_keys.join(", ")));

        w.dedent();
        w.emit("}");
        w.into_string()
    }
}
