//! Vue codegen: IR -> Vue SFC (.vue) + store composables (.ts).
//!
//! Each component generates a `.vue` Single File Component with
//! `<template>`, `<script setup lang="ts">`, and `<style scoped>` sections.
//! Each store generates a `useXxx.ts` composable using Vue's Composition API.

mod expr;
mod template;
#[cfg(test)]
mod tests;

use expr::*;
use template::*;

use super::{CodeWriter, Codegen, CompileOutput, CompiledFile};
use crate::codegen::format_json_value;
use crate::codegen::shared::expr::FormatExpr;
use crate::codegen::shared::types::{FormatType, JsTypeFormatter};
use crate::codegen::JSON_VUE;
use crate::ir::*;
use rustc_hash::FxHashMap;
use std::fmt::Write;

pub struct VueCodegen;

impl Codegen for VueCodegen {
    fn generate(&self, ir: &IRProgram, source_files: &FxHashMap<String, String>) -> CompileOutput {
        self.generate_per_component(ir, source_files)
    }

    fn gen_component_file(
        &self,
        name: &str,
        comp: &ComponentIR,
        ir: &IRProgram,
    ) -> Vec<CompiledFile> {
        vec![CompiledFile {
            path: format!("{}.vue", name),
            content: self.gen_component_sfc(name, comp, ir),
        }]
    }
    fn gen_store_file(&self, name: &str, store: &StoreIR) -> Vec<CompiledFile> {
        vec![CompiledFile {
            path: format!("use{}.ts", name),
            content: self.gen_store_hook(name, store),
        }]
    }
}

impl VueCodegen {
    /// Generate a Vue SFC (.vue) file for a component.
    fn gen_component_sfc(&self, name: &str, comp: &ComponentIR, ir: &IRProgram) -> String {
        let fmt = VueFormatExpr;
        let mut w = CodeWriter::new();
        w.emit("<!-- Generated by OmniLang -- Vue target -->");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <template>
        // ═══════════════════════════════════════════════════════
        w.emit("<template>");
        w.indent();
        if let Some(view) = &comp.view {
            gen_template_node(&mut w, view, &fmt);
        } else {
            w.emit("<div class=\"container\">");
            w.indent();
            w.emit_fmt(format_args!("<h1>{{ '{}' }}</h1>", name));
            w.dedent();
            w.emit("</div>");
        }
        w.dedent();
        w.emit("</template>");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <script setup lang="ts">
        // ═══════════════════════════════════════════════════════
        w.emit("<script setup lang=\"ts\">");
        w.indent();

        // Determine which Vue imports are needed
        let mut vue_imports: Vec<String> = Vec::new();
        vue_imports.push("ref".into());
        if (!comp.computeds.is_empty() || !comp.store_refs.is_empty())
            && !vue_imports.contains(&"computed".into())
        {
            vue_imports.push("computed".into());
        }

        // Check effects and lifecycles for watch vs watchEffect
        let has_watch_effect_effects = comp.effects.iter().any(|e| e.deps.is_empty());
        let has_watch_effects = comp.effects.iter().any(|e| !e.deps.is_empty());
        let has_lifecycle_effects = comp
            .lifecycles
            .iter()
            .any(|lc| lc.kind == LifecycleKind::Effect);

        if has_watch_effect_effects || has_lifecycle_effects {
            vue_imports.push("watchEffect".into());
        }
        if has_watch_effects && !vue_imports.contains(&"watch".into()) {
            vue_imports.push("watch".into());
        }
        let has_mount = comp
            .lifecycles
            .iter()
            .any(|lc| lc.kind == LifecycleKind::Mount);
        let has_unmount = comp
            .lifecycles
            .iter()
            .any(|lc| lc.kind == LifecycleKind::Unmount);
        if has_mount {
            vue_imports.push("onMounted".into());
        }
        if has_unmount {
            vue_imports.push("onUnmounted".into());
        }

        w.emit_fmt(format_args!(
            "import {{ {} }} from 'vue';",
            vue_imports.join(", ")
        ));
        w.emit("");

        // Store hook imports
        let mut store_hook_imports = Vec::new();
        for store_ref in &comp.store_refs {
            if ir.has_store(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                store_hook_imports.push(format!(
                    "import {{ {} }} from './use{}';",
                    hook_name, store_ref
                ));
            }
        }
        for import_line in &store_hook_imports {
            w.emit(import_line);
        }
        if !store_hook_imports.is_empty() {
            w.emit("");
        }

        // Props interface + defineProps
        if !comp.props.is_empty() {
            w.emit("const props = defineProps<{");
            w.indent();
            for (prop_name, prop_type) in &comp.props {
                let ts_type =
                    JsTypeFormatter.format_type(prop_type.kind.as_str(), &prop_type.type_args);
                w.emit_fmt(format_args!("  {}: {};", prop_name, ts_type));
            }
            w.dedent();
            w.emit("}>();");
            w.emit("");
        }

        // Store composable calls
        for store_ref in &comp.store_refs {
            if ir.has_store(store_ref.as_str()) {
                let hook_name = format!("use{}", store_ref);
                w.emit_fmt(format_args!("const {} = {}();", store_ref, hook_name));
            }
        }

        // State (ref declarations)
        for state in &comp.signals {
            let init_val = fmt.format_expr(&state.initial_value);
            let ts_type =
                JsTypeFormatter.format_type(state.r#type.kind.as_str(), &state.r#type.type_args);
            if ts_type.is_empty() {
                w.emit_fmt(format_args!("const {} = ref({});", state.name, init_val));
            } else {
                w.emit_fmt(format_args!(
                    "const {} = ref<{}>({});",
                    state.name, ts_type, init_val
                ));
            }
        }

        // Effects (watch or watchEffect)
        for effect in &comp.effects {
            if effect.deps.is_empty() {
                w.emit("watchEffect(() => {");
                w.indent();
                // Comment to warn about state mutation inside watchEffect
                w.emit("// WARNING: Mutating state inside watchEffect may cause infinite loops");
                for stmt in &effect.body.statements {
                    generate_statement_vue(&mut w, stmt);
                }
                w.dedent();
                w.emit("});");
            } else {
                let deps_str = effect.deps.join(", ");
                w.emit_fmt(format_args!("watch([{}], () => {{", deps_str));
                w.indent();
                for stmt in &effect.body.statements {
                    generate_statement_vue(&mut w, stmt);
                }
                w.dedent();
                w.emit("});");
            }
        }

        // Lifecycles (onMounted / onUnmounted)
        for lc in &comp.lifecycles {
            match lc.kind {
                LifecycleKind::Mount => {
                    w.emit("onMounted(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_vue(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                LifecycleKind::Unmount => {
                    w.emit("onUnmounted(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_vue(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                LifecycleKind::Effect => {
                    // @effect lifecycle — always uses watchEffect (no dep analysis on lifecycle effects)
                    w.emit("watchEffect(() => {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_vue(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
            }
        }

        // Computed values
        for computed in &comp.computeds {
            w.emit_fmt(format_args!("const {} = computed(() => {{", computed.name));
            w.indent();
            w.emit_fmt(format_args!(
                "  return {};",
                fmt.format_expr(&computed.body)
            ));
            w.dedent();
            w.emit("});");
        }

        // Functions
        for func in &comp.fns {
            generate_function_vue(&mut w, func);
        }

        w.dedent();
        w.emit("</script>");
        w.emit("");

        // ═══════════════════════════════════════════════════════
        // <style scoped>
        // ═══════════════════════════════════════════════════════
        w.emit("<style scoped>");
        w.indent();
        crate::codegen::generate_css_style_block(&mut w, &comp.styles);
        w.dedent();
        w.emit("</style>");
        w.emit("");

        w.into_string()
    }

    /// Generate a store composable (useXxx.ts).
    fn gen_store_hook(&self, name: &str, store: &StoreIR) -> String {
        let fmt = VueFormatExpr;
        let mut w = CodeWriter::new();
        w.emit_fmt(format_args!(
            "// Generated by OmniLang -- Store composable: use{}",
            name
        ));
        w.emit("import { ref, computed } from 'vue';");
        w.emit("");

        w.emit_fmt(format_args!("export function use{}() {{", name));
        w.indent();

        // Signals as refs
        for (sig_name, sig_type) in &store.signals {
            let init = store
                .signal_defaults
                .get(sig_name)
                .map(|v| format_json_value(v, &JSON_VUE))
                .unwrap_or_else(|| "null".into());
            let ts_type = JsTypeFormatter.format_type(sig_type.kind.as_str(), &sig_type.type_args);
            if ts_type.is_empty() {
                w.emit_fmt(format_args!("const {} = ref({});", sig_name, init));
            } else {
                w.emit_fmt(format_args!(
                    "const {} = ref<{}>({});",
                    sig_name, ts_type, init
                ));
            }
        }

        // Getters as computed
        for (getter_name, getter_expr) in &store.getters {
            w.emit_fmt(format_args!("const {} = computed(() => {{", getter_name));
            w.indent();
            w.emit_fmt(format_args!("  return {};", fmt.format_expr(getter_expr)));
            w.dedent();
            w.emit("});");
        }

        // Actions as plain functions (Vue has no stale closure problem with refs)
        for action in &store.actions {
            let mut param_strs = Vec::new();
            for p in &action.params {
                let mut s = p.name.clone();
                if let Some(ref ty) = p.r#type {
                    let ann = JsTypeFormatter.format_type(ty.kind.as_str(), &ty.type_args);
                    if !ann.is_empty() {
                        let _ = write!(s, ": {}", ann);
                    }
                }
                param_strs.push(s);
            }
            let async_kw = if action.is_async { "async " } else { "" };
            w.emit_fmt(format_args!(
                "{}function {}({}) {{",
                async_kw,
                action.name,
                param_strs.join(", ")
            ));
            w.indent();
            for stmt in &action.body.statements {
                generate_statement_vue(&mut w, stmt);
            }
            w.dedent();
            w.emit("}");
        }

        // Return value (refs are returned directly; templates auto-unwrap)
        let mut return_keys: Vec<String> = Vec::new();
        for sig_name in store.signals.keys() {
            return_keys.push(sig_name.clone());
        }
        for getter_name in store.getters.keys() {
            return_keys.push(getter_name.clone());
        }
        for action in &store.actions {
            return_keys.push(action.name.clone());
        }
        w.emit_fmt(format_args!("return {{ {} }};", return_keys.join(", ")));

        w.dedent();
        w.emit("}");
        w.into_string()
    }
}
