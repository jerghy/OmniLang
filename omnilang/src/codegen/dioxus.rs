//! Dioxus codegen: IR -> Dioxus RSX components (.rs).
//!
//! Each component generates a `.rs` file with a `#[component]` function
//! using Dioxus's `rsx!` macro for the view layer. Each store generates
//! a module with a `use_X_store()` hook function.

use std::collections::HashMap;

use super::{CodeWriter, Codegen, CompileOutput, CompiledFile};
use crate::ir::*;

pub struct DioxusCodegen;

impl Codegen for DioxusCodegen {
    fn generate(&self, ir: &IRProgram, _source_files: &HashMap<String, String>) -> CompileOutput {
        let mut files = Vec::new();

        for (name, comp) in ir.all_components() {
            let rs = self.gen_component_rs(name, comp, ir);
            files.push(CompiledFile {
                path: format!("{}.rs", name),
                content: rs,
            });
        }

        for (name, store) in ir.all_stores() {
            let store_mod = self.gen_store_module(name, store);
            files.push(CompiledFile {
                path: format!("{}.rs", to_snake_case(name)),
                content: store_mod,
            });
        }

        CompileOutput::success(files)
    }
}

impl DioxusCodegen {
    /// Generate a Dioxus component .rs file.
    fn gen_component_rs(&self, name: &str, comp: &ComponentIR, ir: &IRProgram) -> String {
        let mut w = CodeWriter::new();
        w.emit("// Generated by OmniLang -- Dioxus target");
        w.emit("");

        // Imports
        w.emit("use dioxus::prelude::*;");
        w.emit("");

        // Props struct
        if !comp.props.is_empty() {
            w.emit("#[derive(Props, PartialEq, Clone)]");
            w.emit(&format!("struct {}Props {{", name));
            w.indent();
            for (prop_name, prop_type) in &comp.props {
                let rs_ty = super::rust::rs_type(&prop_type.kind, &prop_type.type_args);
                w.emit(&format!("{}: {},", prop_name, rs_ty));
            }
            w.dedent();
            w.emit("}");
            w.emit("");
        }

        // Component function
        if comp.props.is_empty() {
            w.emit("#[allow(non_snake_case)]");
            w.emit("#[component]");
            w.emit(&format!("pub fn {}() -> Element {{", name));
        } else {
            w.emit("#[allow(non_snake_case)]");
            w.emit("#[component]");
            w.emit(&format!(
                "pub fn {}(props: {}Props) -> Element {{",
                name, name
            ));
        }
        w.indent();

        // Store module imports
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let snake = to_snake_case(store_ref);
                w.emit(&format!("mod {};", snake));
            }
        }
        if !comp.store_refs.is_empty() {
            w.emit("");
        }

        // Store hook calls
        for store_ref in &comp.store_refs {
            if ir.all_stores().contains_key(store_ref.as_str()) {
                let snake = to_snake_case(store_ref);
                w.emit(&format!("let {} = {}::use_{}();", store_ref, snake, snake));
            }
        }

        // State signals (use_signal)
        for state in &comp.states {
            let init_val = format_expr_ir_dioxus(&state.initial_value);
            w.emit(&format!(
                "let mut {} = use_signal(|| {});",
                state.name, init_val
            ));
        }

        // Effects (use_effect)
        for effect in &comp.effects {
            w.emit("use_effect(move || async move {");
            w.indent();
            for stmt in &effect.body.statements {
                generate_statement_dioxus(&mut w, stmt);
            }
            w.dedent();
            w.emit("});");
        }

        // Lifecycles (mount/unmount)
        for lc in &comp.lifecycles {
            match lc.kind.as_str() {
                "mount" => {
                    w.emit("use_effect(move || async move {");
                    w.indent();
                    for stmt in &lc.body.statements {
                        generate_statement_dioxus(&mut w, stmt);
                    }
                    w.dedent();
                    w.emit("});");
                }
                "unmount" => {
                    w.emit("// TODO: unmount lifecycle");
                    for stmt in &lc.body.statements {
                        generate_statement_dioxus(&mut w, stmt);
                    }
                }
                _ => {
                    w.emit(&format!("// TODO: lifecycle '{}'", lc.kind));
                }
            }
        }

        // Computed values (use_memo)
        for computed in &comp.computeds {
            w.emit(&format!("let {} = use_memo(move || {{", computed.name));
            w.indent();
            w.emit(&format_expr_ir_dioxus(&computed.body).to_string());
            w.dedent();
            w.emit("});");
        }

        w.emit("");

        // Render return (rsx! view tree)
        w.emit("rsx! {");
        w.indent();
        if let Some(view) = &comp.view {
            gen_view_node_dioxus(&mut w, view, true);
        } else {
            w.emit("div {");
            w.indent();
            w.emit(&format!("\"{}\"", name));
            w.dedent();
            w.emit("},");
        }
        w.dedent();
        w.emit("}");

        w.dedent();
        w.emit("}");
        w.emit("");

        w.into_string()
    }

    /// Generate a store module file with a hook function.
    fn gen_store_module(&self, name: &str, store: &StoreIR) -> String {
        let mut w = CodeWriter::new();
        w.emit(&format!(
            "// Generated by OmniLang -- Store module: {}",
            name
        ));
        w.emit("use dioxus::prelude::*;");
        w.emit("");

        if store.signals.is_empty() {
            w.emit(&format!("pub struct {};", name));
            w.emit("");
            let hook_name = format!("use_{}", to_snake_case(name));
            w.emit(&format!("pub fn {}() -> {} {{", hook_name, name));
            w.indent();
            w.emit(name);
            w.dedent();
            w.emit("}");
            return w.into_string();
        }

        // Struct with Signal<T> fields
        w.emit(&format!("pub struct {} {{", name));
        w.indent();
        for (sig_name, sig_type) in &store.signals {
            let rs_ty = super::rust::rs_type(&sig_type.kind, &sig_type.type_args);
            w.emit(&format!("pub {}: Signal<{}>,", sig_name, rs_ty));
        }
        w.dedent();
        w.emit("}");
        w.emit("");

        // Hook function
        let hook_name = format!("use_{}", to_snake_case(name));
        w.emit(&format!("pub fn {}() -> {} {{", hook_name, name));
        w.indent();
        w.emit(&format!("{} {{", name));
        w.indent();
        for sig_name in store.signals.keys() {
            let default = store
                .signal_defaults
                .get(sig_name)
                .map(format_json_value_dioxus)
                .unwrap_or_else(|| "Default::default()".into());
            w.emit(&format!("{}: use_signal(|| {}),", sig_name, default));
        }
        w.dedent();
        w.emit("}");
        w.dedent();
        w.emit("}");

        // Getters -- skipped for now; too dependent on component context
        if !store.getters.is_empty() {
            w.emit("");
            w.emit("// Getters: implement as methods if needed");
        }

        w.into_string()
    }
}

// ═══════════════════════════════════════════════════════════
// View tree generation (RSX)
// ═══════════════════════════════════════════════════════════

/// Generate a Dioxus RSX view node.
///
/// `is_root` controls trailing-comma behavior: root-level nodes
/// inside `rsx! {{ ... }}` should NOT have a trailing comma (it causes
/// a syntax error), while nested nodes DO need commas between siblings.
fn gen_view_node_dioxus(w: &mut CodeWriter, node: &ViewTree, is_root: bool) {
    match node {
        ViewTree::Element(el) => {
            let mut attrs: Vec<String> = Vec::new();

            // Static props
            for (prop_name, prop_value) in &el.props {
                let attr_name = to_dioxus_attr(prop_name);
                match prop_value {
                    ExprIR::LiteralExpr { value } if value.is_string() => {
                        let s = value.as_str().expect("literal string value confirmed by is_string()");
                        let escaped = s.replace('\\', "\\\\").replace('"', "\\\"");
                        attrs.push(format!(r#"{}: "{}","#, attr_name, escaped));
                    }
                    _ => {
                        let val = format_expr_ir_dioxus(prop_value);
                        attrs.push(format!("{}: {},", attr_name, val));
                    }
                }
            }

            // Signal bindings (two-way)
            for (bind_name, signal_ref) in &el.bindings {
                let attr_name = to_dioxus_attr(bind_name);
                attrs.push(format!(r#"{}: "{{{}}}","#, attr_name, signal_ref.name));
                attrs.push(format!(
                    "oninput: move |e| {}.set(e.value()),",
                    signal_ref.name
                ));
            }

            // Events
            for (event_name, handler) in &el.events {
                let dioxus_event = to_dioxus_event(event_name);
                match handler.kind.as_str() {
                    "fn_ref" => {
                        if let Some(ref fn_name) = handler.r#ref {
                            if handler.event_data.is_some() {
                                let event_obj = emit_event_object_dioxus(&handler.event_data, &handler.used_fields, "e");
                                attrs.push(format!(
                                    "{}: move |e| {{ {}({}); }},",
                                    dioxus_event, fn_name, event_obj
                                ));
                            } else {
                                attrs.push(format!("{}: {},", dioxus_event, fn_name));
                            }
                        }
                    }
                    "inline_fn" => {
                        if let Some(ref body) = handler.body {
                            if handler.event_data.is_some() {
                                let event_obj = emit_event_object_dioxus(&handler.event_data, &handler.used_fields, "e");
                                let mut hw = CodeWriter::new();
                                for stmt in &body.statements {
                                    generate_statement_dioxus(&mut hw, stmt);
                                }
                                let content = hw.into_string();
                                let mut result = String::from("move |e| {\n");
                                for line in content.lines() {
                                    result.push_str(&format!("                {}\n", line));
                                }
                                result.push_str("            }");
                                attrs.push(format!("{}: {},", dioxus_event, result));
                            } else {
                                attrs.push(format!(
                                    "{}: {},",
                                    dioxus_event,
                                    format_inline_handler_dioxus(body)
                                ));
                            }
                        }
                    }
                    "store_action" => {
                        if let Some(ref action) = handler.r#ref {
                            attrs.push(format!(
                                "{}: move |_| {{ /* TODO: action {} */ }},",
                                dioxus_event, action
                            ));
                        }
                    }
                    _ => {
                        attrs.push(format!(
                            "{}: move |_| {{ /* TODO: kind '{}' */ }},",
                            dioxus_event, handler.kind
                        ));
                    }
                }
            }

            // Style classes
            if let Some(ref classes) = el.style_classes {
                if let Some(classes_str) = classes.as_str() {
                    attrs.push(format!("class: \"{}\",", classes_str));
                }
            }

            // Emit element
            if attrs.is_empty() && el.children.is_empty() {
                // Self-closing empty element
                let suffix = if is_root { "" } else { "," };
                w.emit(&format!("{} {{}}{}", el.tag, suffix));
                return;
            }

            let suffix = if is_root { "" } else { "," };
            w.emit(&format!("{} {{", el.tag));
            w.indent();
            for attr in &attrs {
                w.emit(attr);
            }
            for child in &el.children {
                gen_view_node_dioxus(w, child, false);
            }
            w.dedent();
            w.emit(&format!("}}{}", suffix));
        }
        ViewTree::Conditional(cond) => {
            if cond.branches.is_empty() {
                if let Some(ref fb) = cond.fallback {
                    gen_view_node_dioxus(w, fb, is_root);
                }
                return;
            }

            // First branch
            let cond_str = format_expr_ir_dioxus(&cond.branches[0].condition);
            w.emit(&format!("if {} {{", cond_str));
            w.indent();
            w.emit("rsx! {");
            w.indent();
            if let Some(ref body) = cond.branches[0].body {
                gen_view_node_dioxus(w, body, true);
            }
            w.dedent();
            w.emit("},");
            w.dedent();

            // Else-if branches
            for branch in cond.branches[1..].iter() {
                let else_if_cond = format_expr_ir_dioxus(&branch.condition);
                w.emit(&format!("}} else if {} {{", else_if_cond));
                w.indent();
                w.emit("rsx! {");
                w.indent();
                if let Some(ref body) = branch.body {
                    gen_view_node_dioxus(w, body, true);
                }
                w.dedent();
                w.emit("},");
                w.dedent();
            }

            // Fallback
            if let Some(ref fb) = cond.fallback {
                w.emit("} else {");
                w.indent();
                w.emit("rsx! {");
                w.indent();
                gen_view_node_dioxus(w, fb, true);
                w.dedent();
                w.emit("},");
                w.dedent();
            }

            w.emit("}");
        }
        ViewTree::ListRendering(list) => {
            let iterable_str = format_expr_ir_dioxus(&list.iterable);
            let item_name = &list.item_binding.name;
            w.emit(&format!("{}.iter().map(|{}| {{", iterable_str, item_name));
            w.indent();
            w.emit("rsx! {");
            w.indent();
            if let Some(ref body) = list.body {
                gen_view_node_dioxus(w, body, true);
            }
            w.dedent();
            w.emit("},");
            w.dedent();
            w.emit("})");
        }
        ViewTree::Text(text) => {
            let comma = if is_root { "" } else { "," };
            if text.starts_with('{') && text.ends_with('}') {
                // Interpolation: {name} -> "{name}"
                let inner = &text[1..text.len() - 1];
                w.emit(&format!("\"{{{}}}\"{}", inner, comma));
            } else {
                // Plain text
                w.emit(&format!("\"{}\"{}", text, comma));
            }
        }
        ViewTree::Interpolation(_expr) => {
            let comma = if is_root { "" } else { "," };
            w.emit(&format!("\"{{}}\"{}", comma));
        }
        ViewTree::Slot(_) => {
            // slots not supported in Dioxus — emit placeholder
        }
    }
}

/// Build an inline Rust closure string from a BlockIR for Dioxus event handlers.
fn format_inline_handler_dioxus(body: &BlockIR) -> String {
    if body.statements.is_empty() {
        return "move |_| {}".to_string();
    }
    let mut hw = CodeWriter::new();
    for stmt in &body.statements {
        generate_statement_dioxus(&mut hw, stmt);
    }
    let content = hw.into_string();
    let mut result = String::from("move |_| {\n");
    for line in content.lines() {
        result.push_str(&format!("                {}\n", line));
    }
    result.push_str("            }");
    result
}

// ═══════════════════════════════════════════════════════════
// Statement generation (Rust)
// ═══════════════════════════════════════════════════════════

fn generate_statement_dioxus(w: &mut CodeWriter, stmt: &StatementIR) {
    match stmt {
        StatementIR::LetStmtIR {
            name,
            value,
            r#type,
        } => {
            let rhs = value
                .as_ref()
                .map(format_expr_ir_dioxus)
                .unwrap_or_else(|| "Default::default()".into());
            let type_ann = r#type
                .as_ref()
                .map(|t| format!(": {}", super::rust::rs_type(&t.kind, &t.type_args)))
                .unwrap_or_default();
            w.emit(&format!("let {}{} = {};", name, type_ann, rhs));
        }
        StatementIR::IfStmtIR {
            condition,
            then_body,
            else_ifs,
            else_body,
        } => {
            let cond = format_expr_ir_dioxus(condition);
            w.emit(&format!("if {} {{", cond));
            w.indent();
            for s in &then_body.statements {
                generate_statement_dioxus(w, s);
            }
            w.dedent();
            for (elif_cond, elif_body) in else_ifs {
                let elif_js = format_expr_ir_dioxus(elif_cond);
                w.emit(&format!("}} else if ({}) {{", elif_js));
                w.indent();
                for s in &elif_body.statements {
                    generate_statement_dioxus(w, s);
                }
                w.dedent();
            }
            if let Some(else_blk) = else_body {
                if !else_blk.statements.is_empty() {
                    w.emit("} else {");
                    w.indent();
                    for s in &else_blk.statements {
                        generate_statement_dioxus(w, s);
                    }
                    w.dedent();
                }
            }
            w.emit("}");
        }
        StatementIR::ReturnStmtIR { value } => {
            let rhs = value
                .as_ref()
                .map(format_expr_ir_dioxus)
                .unwrap_or_else(|| "()".into());
            w.emit(&format!("return {};", rhs));
        }
        StatementIR::MutationStmt { intent: None } => {}
        StatementIR::MutationStmt {
            intent: Some(mut_intent),
        } => {
            let target = &mut_intent.target.name;
            let amount = mut_intent
                .amount
                .as_ref()
                .map(format_expr_ir_dioxus)
                .unwrap_or_else(|| "0".into());
            match mut_intent.operation.as_str() {
                "direct_assign" => {
                    w.emit(&format!("{}.set({});", target, amount));
                }
                "increment" => {
                    w.emit(&format!("{} += {};", target, amount));
                }
                "decrement" => {
                    w.emit(&format!("{} -= {};", target, amount));
                }
                "multiply" => {
                    w.emit(&format!("{} *= {};", target, amount));
                }
                "divide" => {
                    w.emit(&format!("{} /= {};", target, amount));
                }
                "modulo" => {
                    w.emit(&format!("{} %= {};", target, amount));
                }
                other => {
                    w.emit(&format!(
                        "// TODO: mutation operation '{}' on '{}'",
                        other, target
                    ));
                }
            }
        }
        StatementIR::ExprStmtIR { expr } => {
            let line = format_expr_ir_dioxus(expr);
            if line != "None" {
                w.emit(&format!("{};", line));
            }
        }
        StatementIR::EventEmitStmtIR { event_name, args } => {
            let arg_str = if args.is_empty() {
                String::new()
            } else {
                let formatted: Vec<String> = args.iter().map(format_expr_ir_dioxus).collect();
                format!("({})", formatted.join(", "))
            };
            w.emit(&format!("// emit event: {}{}", event_name, arg_str));
        }
        StatementIR::WhileStmtIR { condition, body } => {
            let cond = format_expr_ir_dioxus(condition);
            w.emit(&format!("while {} {{", cond));
            w.indent();
            for s in &body.statements {
                generate_statement_dioxus(w, s);
            }
            w.dedent();
            w.emit("}");
        }
        StatementIR::ForInStmtIR {
            var_name,
            iterable,
            body,
        } => {
            let iter = format_expr_ir_dioxus(iterable);
            w.emit(&format!("for {} in {} {{", var_name, iter));
            w.indent();
            for s in &body.statements {
                generate_statement_dioxus(w, s);
            }
            w.dedent();
            w.emit("}");
        }
        StatementIR::BreakStmtIR => {
            w.emit("break;");
        }
        StatementIR::ContinueStmtIR => {
            w.emit("continue;");
        }
        _ => {}
    }
}

fn format_block_as_dioxus_expr(block: &BlockIR) -> String {
    if let Some(last) = block.statements.last() {
        match last {
            StatementIR::ExprStmtIR { expr } => format_expr_ir_dioxus(expr),
            StatementIR::ReturnStmtIR { value } => value
                .as_ref()
                .map(|e| format_expr_ir_dioxus(e))
                .unwrap_or_else(|| "None".into()),
            _ => "None".into(),
        }
    } else {
        "None".into()
    }
}

// ═══════════════════════════════════════════════════════════
// Expression formatting (Rust)
// ═══════════════════════════════════════════════════════════

fn format_expr_ir_dioxus(expr: &ExprIR) -> String {
    match expr {
        ExprIR::LiteralExpr { value } => format_json_value_dioxus(value),
        ExprIR::IdentifierExpr { name } => name.clone(),
        ExprIR::FieldAccessExpr { object, field } => {
            format!("{}.{}", format_expr_ir_dioxus(object), field)
        }
        ExprIR::OptionalChainExpr { object, field } => {
            format!("{}.{}", format_expr_ir_dioxus(object), field)
        }
        ExprIR::BinaryOpExpr { op, left, right } => {
            let rs_op = binary_op_to_dioxus(op);
            let lhs = format_expr_ir_dioxus(left);
            let rhs = format_expr_ir_dioxus(right);
            format!("{} {} {}", lhs, rs_op, rhs)
        }
        ExprIR::UnaryOpExpr { op, operand } => {
            let rs_op = match op.as_str() {
                "not" => "!",
                "neg" => "-",
                _ => op,
            };
            format!("{}{}", rs_op, format_expr_ir_dioxus(operand))
        }
        ExprIR::TernaryIR {
            cond,
            then_expr,
            else_expr,
        } => {
            let c = format_expr_ir_dioxus(cond);
            let t = format_expr_ir_dioxus(then_expr);
            let e = format_expr_ir_dioxus(else_expr);
            format!("if {} {{ {} }} else {{ {} }}", c, t, e)
        }
        ExprIR::CallExpr { name, args } => {
            let arg_strs: Vec<String> = args.iter().map(format_expr_ir_dioxus).collect();
            format!("{}({})", name, arg_strs.join(", "))
        }
        ExprIR::StoreFieldAccessExpr {
            store_alias,
            field_name,
            call_args,
        } => {
            let args: Vec<String> = call_args.iter().map(format_expr_ir_dioxus).collect();
            let arg_str = if args.is_empty() {
                String::new()
            } else {
                format!("({})", args.join(", "))
            };
            format!("{}.{}{}", store_alias, field_name, arg_str)
        }
        ExprIR::ArrayExpr { elements } => {
            let items: Vec<String> = elements.iter().map(format_expr_ir_dioxus).collect();
            format!("vec![{}]", items.join(", "))
        }
        ExprIR::StructExpr { fields, .. } => {
            let entries: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("{}: {}", k, format_expr_ir_dioxus(v)))
                .collect();
            format!("{{ {} }}", entries.join(", "))
        }
        ExprIR::VariantLiteral {
            union_type,
            variant,
            fields,
        } => {
            let entries: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("{}: {}", k, format_expr_ir_dioxus(v)))
                .collect();
            format!("{}::{} {{ {} }}", union_type, variant, entries.join(", "))
        }
        ExprIR::MethodCallExpr {
            object,
            method,
            args,
            ..
        } => {
            let obj = format_expr_ir_dioxus(object);
            let arg_strs: Vec<String> = args.iter().map(|a| format_expr_ir_dioxus(a)).collect();
            format!("{}.{}({})", obj, method, arg_strs.join(", "))
        }
        ExprIR::BlockExpr {
            statements: _,
            tail,
        } => {
            // Only tail expression emitted; preceding statements preserved in IR for future codegen
            format_expr_ir_dioxus(tail)
        }
        ExprIR::IndexExpr { object, index } => {
            let obj = format_expr_ir_dioxus(object);
            let idx = format_expr_ir_dioxus(index);
            format!("({obj})[{idx} as usize]")
        }
        ExprIR::AwaitExpr { operand } => {
            format!("{}.await", format_expr_ir_dioxus(operand))
        }
        ExprIR::MatchExpr { matched, arms } => {
            let m = format_expr_ir_dioxus(matched);
            let cases: Vec<String> = arms
                .iter()
                .map(|arm| {
                    let body = format_block_as_dioxus_expr(&arm.body);
                    match &arm.pattern.kind {
                        MatchPatternKindIR::Variant { name, .. } => {
                            format!("    UnionType::{} {{ .. }} => {},", name, body)
                        }
                        MatchPatternKindIR::Wildcard => {
                            format!("    _ => {},", body)
                        }
                        _ => String::new(),
                    }
                })
                .collect();
            format!("match &{} {{\n{}\n}}", m, cases.join("\n"))
        }
        ExprIR::ClosureExpr { params, body } => {
            let b = format_expr_ir_dioxus(body);
            let p = params.join(", ");
            format!("(move |{p}| {b})")
        }
    }
}

/// Format a JSON value as a Rust literal expression.
fn format_json_value_dioxus(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::Null => "None".into(),
        serde_json::Value::Bool(b) => {
            if *b {
                "true".into()
            } else {
                "false".into()
            }
        }
        serde_json::Value::Number(n) => n.to_string(),
        serde_json::Value::String(s) => {
            let escaped = s
                .replace('\\', "\\\\")
                .replace('"', "\\\"")
                .replace('\n', "\\n")
                .replace('\r', "\\r")
                .replace('\t', "\\t");
            format!("\"{}\".to_string()", escaped)
        }
        serde_json::Value::Array(arr) => {
            let items: Vec<_> = arr.iter().map(format_json_value_dioxus).collect();
            format!("vec![{}]", items.join(", "))
        }
        serde_json::Value::Object(obj) => {
            let items: Vec<_> = obj
                .iter()
                .map(|(k, v)| format!("{}: {}", k, format_json_value_dioxus(v)))
                .collect();
            format!("{{ {} }}", items.join(", "))
        }
    }
}

/// Map OMNI binary operator name to Rust operator.
fn binary_op_to_dioxus(op: &str) -> &str {
    match op {
        "add" => "+",
        "sub" => "-",
        "mul" => "*",
        "div" => "/",
        "mod" => "%",
        "eq" => "==",
        "neq" => "!=",
        "lt" => "<",
        "gt" => ">",
        "lteq" => "<=",
        "gteq" => ">=",
        "and" => "&&",
        "or" => "||",
        "assign" => "=",
        "addassign" => "+=",
        "subassign" => "-=",
        "mulassign" => "*=",
        "divassign" => "/=",
        "modassign" => "%=",
        _ => op,
    }
}

